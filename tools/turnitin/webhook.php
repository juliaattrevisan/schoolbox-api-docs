declare(strict_types=1);

use Schoolbox\Application\CliTool;
use Schoolbox\Learning\Turnitin\Controller as TurnitinController;
use Schoolbox\Learning\Turnitin;
use Schoolbox\Learning\Turnitin\Helper;
use Schoolbox\Url\Factory;

require_once __DIR__ . '/../../conf/core/require.php';

/**
 * CLI Tool
 *
 * Copy this to /tools folder
 *
 * To redirect log output to a file(s):
 *     STDOUT is file descriptor 1
 *     STDERR is file descriptor 2; our logger output ends up going here
 *
 *     Example: php example.php 2> log.txt
 */
$app = new class extends CliTool\App
{
    /**
     * --help
     *
     * Print help text for those who don't know how to use this tool
     */
    private const OPT_LONG_HELP = 'help';


    /**
     * --instance
     */
    private const OPT_LONG_INSTANCE = 'register';


    /**
     * --reset
     *
     * Forcibly clear and re-register all three webhooks
     */
    private const OPT_LONG_RESET = 'reset';


    /**
     * Normally generated by an aura router, but this is the place
     * where Turnitin POSTs all three payloads
     */
    private const WEBHOOK_URL = '/learning/turnitin/webhook';


    /**
     * @inheritdoc
     */
    public function getLongOpts(): array
    {
        return [
            self::OPT_LONG_HELP,
            self::OPT_LONG_INSTANCE,
            self::OPT_LONG_RESET
        ];
    }


    /**
     * Run the cli tool
     */
    public function run(): void
    {
        if ($this->getOpt(self::OPT_LONG_HELP)) {
            echo <<<HELP

Register Turnitin webhooks. Turnitin posts payloads to a schoolbox endpoint(s) when it
finishes various stages of its processing - upload of documents, generation of reports,
and updating of the report contents. Each webhook's endpoint is an absolute url so that
Turnitin can send stuff there.

Every now and then you might need to set up the webhook urls again, such as when an
absolute url changes name or if something is just broken.

The --instance flag isn't used at the moment, but infra might need it later so I
kept it in here for their convenience.

Get a diagnostic list of all currently registered webhooks:
    Usage: webhook.php [--instance=INSTANCE_ID]

Forcibly register all webhooks again:
    Usage: webhook.php [--instance=INSTANCE_ID] [--reset]


HELP;
            exit;
        }

        /* Check if turnitin is configured sufficiently
         */
        if (!(new Helper($this->getConfig()))->isConfigured()) {
            $this->getLogger()->info('Turnitin configuration invalid.');
            exit;
        }

        /* Check that your api setup is functioning
         * We need this api working
         */
        $api = new Turnitin\Api(
            $this->getConfig()->get('site_version'),
            $this->getConfig()->get('turnitin_api_host'),
            $this->getConfig()->get('turnitin_api_key')
        );

        /* If the basic test() failed, then your turnitin config is broken
         * and your api host/key combo is somehow wrong
         */
        try {
            $api->test();
        } catch (\Schoolbox\Learning\Turnitin\Exception\Exception $e) {
            $this->getLogger()->warning($e->getMessage());
            exit(1);
        }

        /* Forcibly register all three webhooks if the option was chosen
         */
        if ($this->getOpt(self::OPT_LONG_RESET)) {
            $this->getLogger()->info('Resetting all webhooks to defaults...');
            $this->getLogger()->info('');

            $this->unregisterAll($api);

            $this->getLogger()->info('');

            $this->registerAll($api);

            $this->getLogger()->info('');

            exit();
        }

        /* Get a list of all the webhooks currently registered
         * Also happens to be default behaviour for this tool
         */
        $this->getWebhookList($api);

        exit();
    }


    /**
     * Clear all webhooks
     *
     * @param Turnitin\Api $api
     */
    private function unregisterAll(Turnitin\Api $api): void
    {
        $webhooks = $this->getWebhooks($api);

        foreach ($webhooks as $webhook) {
            $this->getLogger()->info(sprintf(
                'Removing webhook %s (%s)',
                $webhook['id'],
                $webhook['description']
            ));

            try {
                $api->retrieve('DELETE', "/api/v1/webhooks/{$webhook['id']}", []);
            } catch (\DomainException $e) {
                /* 204 is successful in this context; but maybe not others
                 */
                if (204 === $e->getCode()) {
                    $this->getLogger()->info('Successfully removed.');
                }
            }
        }
    }


    /**
     * Register webhook url for all Event Types
     *
     * @param Turnitin\Api $api
     */
    private function registerAll(Turnitin\Api $api): void
    {
        $payload = [
            'signing_secret' => base64_encode('aaa'),
            'description' => 'Unified Turnitin Endpoint',
            'url' => (new Factory($this->getConfig()))->buildFullyQualified() . self::WEBHOOK_URL,
            'event_types' => [
                TurnitinController::SUBMISSION_COMPLETE,
                TurnitinController::SIMILARITY_COMPLETE,
                TurnitinController::SIMILARITY_UPDATED,
            ]
        ];

        $this->getLogger()->info(sprintf(
            'Adding webhook: %s (%s) for %s values %s',
            $payload['description'],
            $payload['url'],
            TurnitinController::HEADER_EVENT_TYPE,
            implode(', ', $payload['event_types'])
        ));

        try {
            $result = $api->retrieve('POST', '/api/v1/webhooks', $payload);
        } catch (\DomainException $e) {
            /* 409 Conflict arises if you try to register a url that already was registered
             * but this normally won't happen if you clear it all first
             */
            if (409 === $e->getCode()) {
                $this->getLogger()->warning(sprintf(
                    'Webhook %s has already been registered and cannot be added again.',
                    $payload['url']
                ));
            }

            exit();
        }

        $this->getLogger()->info('Successfully added.');
    }


    /**
     * Get a list of existing webhooks
     *
     * @param Turnitin\Api $api
     * @return array
     */
    private function getWebhooks(Turnitin\Api $api): array
    {
        return $api->retrieve('GET', '/api/v1/webhooks', []);
    }


    /**
     * Generate a list of webhooks and their info
     *
     * @param Turnitin\Api $api
     */
    private function getWebhookList(Turnitin\Api $api): void
    {
        $this->getLogger()->info('Retrieving list of existing webhooks...');

        $result = $this->getWebhooks($api);

        /* No webhooks? No trabajo
         */
        if (!\count($result)) {
            $this->getLogger()->info('No webhooks found.');
            exit();
        }

        /* Otherwise list it all out
         */
        $this->getLogger()->info('');

        $n = \count($result);

        for ($i = 0; $i < $n; $i++) {
            $webhook = $result[$i];

            $this->getLogger()->info(sprintf(
                'Webhook %s: %s',
                $i + 1,
                $webhook['description']
            ));

            $this->getLogger()->info(sprintf(
                '%s is set up to receive %s values %s',
                $webhook['url'],
                TurnitinController::HEADER_EVENT_TYPE,
                implode(', ', $webhook['event_types'])
            ));

            $this->getLogger()->debug(sprintf(
                'Identifier: %s',
                $webhook['id']
            ));

            $this->getLogger()->info('');
        }
    }


    /**
     * Script does not modify the filesystem, so it does not care who it is run as
     * @return bool|null
     */
    public function runAsRoot(): ?bool
    {
        return null;
    }
};

/* OPTION_ERRORS => E_ALL causes all notices and errors to fatally crash your script
 *
 * You should generally try to fix those, even though in some special cases php will throw notices
 * for its own expected behaviours which will inadvertently cause this to fail
 */
$options = [CliTool\Kernel::OPTION_LEVEL => Monolog\Logger::DEBUG, CliTool\Kernel::OPTION_ERRORS => E_ALL,];

/** @noinspection PhpUnhandledExceptionInspection */
(new Schoolbox\Application\CliTool\Kernel($app, $options))->runApp();
