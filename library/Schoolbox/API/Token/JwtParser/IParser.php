declare(strict_types=1);

namespace Schoolbox\API\Token\JwtParser;

use Schoolbox\User;

/**
 * Interface for JWT parsers.
 */
interface IParser
{
    /**
     * Constant for the issuer JWT claim.
     *
     * This identifies the party which issued the JWT.
     *
     * @see https://datatracker.ietf.org/doc/html/rfc7519#section-4.1.1
     */
    public const CLAIM_ISS = 'iss';

    /**
     * Constant for the subject JWT claim.
     *
     * This claim may be used to identify the user which is the subject of the
     * JWT.
     *
     * @see https://datatracker.ietf.org/doc/html/rfc7519#section-4.1.2
     */
    public const CLAIM_SUB = 'sub';

    /**
     * Constant for the audience JWT claim.
     *
     * This identifies the party/parties intended to receive the JWT.
     *
     * @see https://datatracker.ietf.org/doc/html/rfc7519#section-4.1.3
     */
    public const CLAIM_AUD = 'aud';

    /**
     * Constant for the expiry JWT claim.
     *
     * This defines the time at which the JWT expires: it will be rejected after
     * this time.
     *
     * @see https://datatracker.ietf.org/doc/html/rfc7519#section-4.1.4
     */
    public const CLAIM_EXP = 'exp';

    /**
     * Constant for the not-before JWT claim.
     *
     * This defines the earliest time at which the JWT will be accepted: it will
     * be rejected before this time.
     *
     * @see https://datatracker.ietf.org/doc/html/rfc7519#section-4.1.5
     */
    public const CLAIM_NBF = 'nbf';

    /**
     * Constant for the issued-at JWT claim.
     *
     * The JWT will be rejected before this time.
     *
     * @see https://datatracker.ietf.org/doc/html/rfc7519#section-4.1.6
     */
    public const CLAIM_IAT = 'iat';

    /**
     * Constant for the JWT ID JWT claim.
     *
     * This is a unique identifier for the JWT: its purpose is to ensure that
     * the JWT has actually been generated by the issuing party, and to allow
     * for application-specific logic to further verify its validity.
     *
     * @see https://datatracker.ietf.org/doc/html/rfc7519#section-4.1.7
     */
    public const CLAIM_JTI = 'jti';

    /**
     * Constant for the email JWT claim.
     *
     * This claim may be used instead of `self::CLAIM_AUD` to identify the user
     * which is the subject of the JWT.
     *
     * @see https://openid.net/specs/openid-connect-core-1_0.html#StandardClaims
     */
    public const CLAIM_EMAIL = 'email';

    /**
     * Namespace used for custom claims created by Schoolbox.
     *
     * Any claims added to a token which are not registered or public claims
     * must be prefixed with this value.
     *
     * @see https://tools.ietf.org/html/rfc7519#section-4.1
     * @see https://www.iana.org/assignments/jwt/jwt.xhtml
     */
    public const CUSTOM_CLAIM_NAMESPACE = 'https://schoolbox.com.au/';

    /**
     * Does this parser accept this JWT?
     *
     * In order to determine this, the parser is expected to decode the JWT's
     * claims without verifying it: this means that the JWT must be signed but
     * not encrypted.
     *
     * @param string $jwt The JWT to verify.
     * @return bool
     * @throws Exception\Unparseable if the JWT is malformed and cannot be
     *                               parsed.
     */
    public function accepts(string $jwt): bool;

    /**
     * Determine the user identified by the JWT.
     *
     * Presumes `$this->accepts($jwt)` has returned true.
     *
     * @param string $jwt The JWT to use to identify a user.
     * @return User The user identified by the JWT.
     * @throws Exception\Unparseable     if the JWT is malformed and cannot be parsed.
     *                                   (Should have been caught by `accepts`, but could be raised here.)
     * @throws Exception\Rejected        if the JWT is properly formed, but is rejected before evaluating the user which
     *                                   it identifies.
     * @throws Exception\InvalidIdentity if the JWT is accepted, but does not identify a valid user.
     */
    public function determineUser(string $jwt): User;
}
