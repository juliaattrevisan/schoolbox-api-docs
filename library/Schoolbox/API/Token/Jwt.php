declare(strict_types=1);

namespace Schoolbox\API\Token;

use Alaress_Date_Format;
use Firebase\JWT\BeforeValidException;
use Firebase\JWT\ExpiredException;
use Firebase\JWT\JWT as JwtLibrary;
use Firebase\JWT\SignatureInvalidException;
use Schoolbox\Config\ConfigMapper;
use Schoolbox\IConfigLoader;
use Schoolbox\User;
use UnexpectedValueException;

/**
 * JWT generator and validator.
 */
class Jwt
{
    private const SIGNING_ALGORITHM = 'RS256';


    /**
     * @var IConfigLoader
     */
    private $config;


    /**
     * Constructor
     *
     * @param IConfigLoader $configLoader
     */
    public function __construct(IConfigLoader $configLoader)
    {
        $this->config = $configLoader;
    }


    /**
     * Generates a JWT for this user.
     *
     * @param User     $user
     * @param int|null $lifetime     If provided, the JWT expires after this
     *                               many seconds.
     * @param bool     $includeEmail If true, add the user's email address to
     *                               the "email" claim.
     * @return string
     */
    public function generate(User $user, ?int $lifetime = null, bool $includeEmail = false): string
    {
        // Issuer:     this Schoolbox instance's FQDN
        // Subject:    $user
        // Expiry:     optional
        // Not before: not used for now
        // May add ability to regenerate tokens later?
        $claims = [
            'iss' => trim($this->config->get('site_hostname') . '.' . $this->config->get('site_domain'), ';.'),
            'sub' => $user->getUsername(),
        ];
        if (isset($lifetime)) {
            $claims['exp'] = Alaress_Date_Format::now()->addSeconds($lifetime)->getUnixTimeStamp();
        }
        if ($includeEmail) {
            $claims['email'] = $user->getEmail();
        }
        return JwtLibrary::encode(
            $claims,
            $this->config->get(ConfigMapper::NAME_JWT_PRIVATE_KEY),
            self::SIGNING_ALGORITHM
        );
    }


    /**
     * Parses a JWT generated by `generate`, and verifies that the JWT has been
     * signed appropriately and not tampered with.
     *
     * @param string $jwt
     * @return array
     * @throws SignatureInvalidException Provided JWT was invalid because the signature verification failed
     * @throws BeforeValidException      Provided JWT is trying to be used before it's eligible as defined by 'nbf'
     * @throws BeforeValidException      Provided JWT is trying to be used before it's been created as defined by 'iat'
     * @throws ExpiredException          Provided JWT has since expired, as defined by the 'exp' claim
     * @throws UnexpectedValueException  Provided JWT was invalid for any other reason
     */
    public function decode(string $jwt): array
    {
        return (array)JwtLibrary::decode(
            $jwt,
            $this->config->get(ConfigMapper::NAME_JWT_PUBLIC_KEY),
            [self::SIGNING_ALGORITHM]
        );
    }

    /**
     * Parses a JWT generated by `generate`, without verifying that the JWT is
     * valid.
     *
     * This is required so that an instance ID may be extracted from the JWT, so
     * that its verification key may be determined.
     *
     * @param string $jwt
     * @return array
     */
    public function decodeWithoutVerification(string $jwt): array
    {
        [, $payload, ] = explode('.', $jwt);
        return (array)JwtLibrary::jsonDecode(JwtLibrary::urlsafeB64Decode($payload));
    }
}
