declare(strict_types=1);

namespace Schoolbox\API\Token;

use Alaress_Date_Format;
use DomainException;
use Firebase\JWT\BeforeValidException;
use Firebase\JWT\ExpiredException;
use Firebase\JWT\JWT as JwtLibrary;
use Firebase\JWT\Key;
use Firebase\JWT\SignatureInvalidException;
use OAT\Library\Lti1p3Core\Message\Payload\MessagePayloadInterface;
use Schoolbox\Config\ConfigMapper;
use Schoolbox\IConfigLoader;
use Schoolbox\Url\Factory;
use Schoolbox\User;
use UnexpectedValueException;

/**
 * JWT generator and validator.
 */
class Jwt
{
    /**
     * Signing algorithm for JWTs.
     */
    private const SIGNING_ALGORITHM = 'RS256';


    /**
     * Namespace used for custom claims created by Schoolbox.
     *
     * Any claims added to a token which are not registered or public claims
     * must be prefixed with this value.
     *
     * @see https://tools.ietf.org/html/rfc7519#section-4.1
     * @see https://www.iana.org/assignments/jwt/jwt.xhtml
     */
    public const CUSTOM_CLAIM_NAMESPACE = 'https://schoolbox.com.au/';


    /**
     * Config settings are stored here.
     */
    private IConfigLoader $config;


    /**
     * Constructor
     *
     * @param IConfigLoader $configLoader
     */
    public function __construct(IConfigLoader $configLoader)
    {
        $this->config = $configLoader;
    }


    /**
     * Generates a JWT for this user.
     *
     * @param User                     $user
     * @param Alaress_Date_Format|null $expiry           If provided, the JWT expires after this
     * @param string|null              $jwtId
     *                                   many seconds.
     * @param array                    $additionalClaims Any extra claims to make beyond the
     *                                   standard 'iss', 'sub', 'exp'. 'jti'
     * @return string
     */
    public function generate(User $user, ?Alaress_Date_Format $expiry = null, ?string $jwtId = null, array $additionalClaims = []): string
    {
        // Issuer:     this Schoolbox instance's FQDN
        // Subject:    $user
        // Expiry:     optional
        // Not before: not used for now
        // May add ability to regenerate tokens later?
        $claims = [
            MessagePayloadInterface::CLAIM_ISS => $this->getSchoolboxIssuer(),
            MessagePayloadInterface::CLAIM_SUB => $user->getUsername(),
        ];
        if ($expiry !== null && !$expiry->isNull()) {
            $claims[MessagePayloadInterface::CLAIM_EXP] = $expiry->getUnixTimeStamp();
        }
        if ($jwtId !== null) {
            $claims[MessagePayloadInterface::CLAIM_JTI] = $jwtId;
        }
        return JwtLibrary::encode(
            array_merge($claims, $additionalClaims),
            $this->config->get(ConfigMapper::NAME_JWT_PRIVATE_KEY),
            self::SIGNING_ALGORITHM
        );
    }


    /**
     * Parses a JWT generated by `generate`, and verifies that the JWT has been
     * signed appropriately and not tampered with.
     *
     * @param string      $jwt
     * @param string|null $publicKey A public key to decode the JWT with: if not
     *                               provided, use the public key in config.
     * @return array
     * @throws UnexpectedValueException  JWT doesn't contain a header, payload
     *                                   and signature segment
     * @throws DomainException           JWT payload is invalid JSON
     * @throws SignatureInvalidException JWT was invalid because the signature
     *                                   verification failed
     * @throws BeforeValidException      JWT is trying to be used before it's
     *                                   eligible as defined by 'nbf'
     * @throws BeforeValidException      JWT is trying to be used before it's
     *                                   been created as defined by 'iat'
     * @throws ExpiredException          JWT has since expired, as defined by
     *                                   the 'exp' claim
     * @throws UnexpectedValueException  JWT was invalid for any other reason
     */
    public function decode(string $jwt, ?string $publicKey = null): array
    {
        // Set leeway for this decode only, set it back once done
        $previousLeeway     = JwtLibrary::$leeway;
        JwtLibrary::$leeway = (int)$this->config->get(ConfigMapper::NAME_JWT_LEEWAY);
        $key = new Key($publicKey ?? $this->config->get(ConfigMapper::NAME_JWT_PUBLIC_KEY), self::SIGNING_ALGORITHM);
        try {
            return (array)JwtLibrary::decode($jwt, $key);
        } finally {
            JwtLibrary::$leeway = $previousLeeway;
        }
    }

    /**
     * Parses a JWT generated by `generate`, without verifying that the JWT is
     * valid.
     *
     * This is required so that an instance ID may be extracted from the JWT, so
     * that its verification key may be determined.
     *
     * @param string $jwt
     * @return array
     * @throws UnexpectedValueException JWT doesn't contain a header, payload
     *                                  and signature segment
     * @throws DomainException          JWT payload is invalid JSON
     */
    public function decodeWithoutVerification(string $jwt): array
    {
        $parts = explode('.', $jwt);
        if (count($parts) !== 3) {
            throw new UnexpectedValueException('JWT must contain a header, payload and signature');
        }
        [, $payload,] = $parts;
        return (array)JwtLibrary::jsonDecode(JwtLibrary::urlsafeB64Decode($payload));
    }

    /**
     * @return string|null
     */
    private function getSchoolboxIssuer(): ?string
    {
        return (new Factory($this->config))->buildFullyQualified()->getHost();
    }
}
