namespace Schoolbox\Fixtures\Team\Player;

use Alaress\Async\Notification\Instance\Builder;
use Alaress\Async\Notification\Parameter\Param;
use Monolog\Logger;
use Schoolbox\Mapper as BaseMapper;
use Schoolbox\Realtime\Message\NSMapper;
use Schoolbox\Realtime\Notification\Envelope;
use Schoolbox\Realtime\Notification\Parameter\UserParam;
use Schoolbox\Realtime\Schedule\Module\AbstractModuleNotifier;
use Schoolbox\Realtime\Schedule\Trigger\TriggerBundle;
use Schoolbox\User;
use Schoolbox\UserMapper;
use Schoolbox\Fixtures\Team\Player\Model as TeamPlayer;
use Schoolbox\Fixtures\Team\Model as Team;
use Schoolbox\Fixtures\Team\Mapper as TeamMapper;
use Schoolbox\Fixtures\Matchup\Mapper as MatchupMapper;

class Notifier extends AbstractModuleNotifier
{
    /**
     * These constants are the labels that need to be defined in msg_source
     * They also need to match the names of the callbacks specified below.
     */
    const TRIGGER_REMOVED = 'removed';

    /**
     * @var TeamMapper
     */
    protected $teamMapper;

    /**
     * @var MatchupMapper
     */
    protected $matchupMapper;

    /**
     * @var UserMapper
     */
    protected $userMapper;

    /**
     * This string is the namespace as defined for the msg_source in db.
     *
     * @return string
     */
    protected function getSlug()
    {
        return NSMapper::NS_SPORTS_FIXTURES;
    }

    /**
     * @inheritdoc
     *
     * @param mixed $dependencies
     */
    public function loadDependencies($dependencies = null)
    {
        if (empty($dependencies['teamMapper'])) {
            $dependencies['teamMapper'] = TeamMapper::getInstance();
        }

        if (empty($dependencies['matchupMapper'])) {
            $dependencies['matchupMapper'] = MatchupMapper::getInstance();
        }

        if (empty($dependencies['userMapper'])) {
            $dependencies['userMapper'] = UserMapper::getInstance();
        }

        parent::loadDependencies($dependencies); // TODO: Change the autogenerated stub
    }

    /**
     * @param TriggerBundle $bundle
     * @return void
     * @throws BaseMapper\Exception
     * @throws BaseMapper\Exception\Deleted
     */
    public function bundleTriggers($bundle)
    {
        $method = $bundle->getEvent()->getAction();

        /* check contents of $bundle->getEvent()
         */
        switch ($method) {
            case Mapper::METHOD_DELETE:
                $team = $this->getTeamMapper()->findById($bundle->getEvent()->getObject()->getTeam()->getId());
                try {
                    $matchup = $this->getMatchupMapper()->findNextMatch($team);

                    $diff = \Alaress_Date_Format::now()->diffInHours($matchup->getStartAt());

                    if ($diff > 0 && $diff < 24) {
                        $bundle->attach(self::TRIGGER_REMOVED, self::IMMEDIATELY);
                    }
                } catch (\OutOfBoundsException $e) {
                    //no match found, no future notifications to remove
                }

                break;
        }
    }

    /**
     * Message being sent to students
     *
     * @param Model      $teamPlayer
     * @param User       $effector
     * @param array|null $diff
     * @return Envelope
     * @throws BaseMapper\Exception
     * @throws BaseMapper\Exception\Deleted
     * @throws \InvalidArgumentException
     * @throws \OutOfBoundsException
     */
    public function notifyStudentRemoved(TeamPlayer $teamPlayer, User $effector, array $diff = null)
    {
        $team = $this->getTeamMapper()->findById($teamPlayer->getTeam()->getId());

        $title = 'You were removed from :team';
        $params = [
            'team' => new Param($team->getName(), $team->getUrl() . '?' . microtime(), Param::STACKING_REPLACE)
        ];

        $bob = $this->notifyRemovedFromTeam($effector, $teamPlayer, $team, $title, $params)->build();

        $envelope = new Envelope();
        $envelope->targetToUser($teamPlayer->getUser()->getId(), $bob);

        return $envelope;
    }

    /**
     * Message being sent to parents
     *
     * @param Model      $teamPlayer
     * @param User       $effector
     * @param array|null $diff
     * @return Envelope
     * @throws BaseMapper\Exception
     * @throws BaseMapper\Exception\Deleted
     * @throws \InvalidArgumentException
     * @throws \OutOfBoundsException
     */
    public function notifyParentRemoved(TeamPlayer $teamPlayer, User $effector, array $diff = null)
    {
        $team = $this->getTeamMapper()->findById($teamPlayer->getTeam()->getId());

        /* For some reason I now have to do this
         */
        $user = $this->getUserMapper()->findById($teamPlayer->getUser()->getId());
        $teamPlayer->setUser($user);

        $title = ':user was removed from :team';
        $params = [
            'user' => new UserParam($teamPlayer->getUser(), Param::STACKING_IGNORE),
            'team' => new Param($team->getName(), $team->getUrl() . '?' . microtime(), Param::STACKING_REPLACE)
        ];

        $bob = $this
            ->notifyRemovedFromTeam($effector, $teamPlayer, $team, $title, $params)
            ->putMeta('studentExternalId', $teamPlayer->getUser()->getExternalId())
            ->build();

        $envelope = new Envelope();
        $envelope->targetToParent($teamPlayer->getUser()->getId(), $bob);

        return $envelope;
    }

    /**
     * @param User   $effector
     * @param Model  $teamPlayer
     * @param Team   $team
     * @param string $title
     * @param array  $params
     * @return Builder
     * @throws \OutOfBoundsException
     */
    private function notifyRemovedFromTeam(User $effector, TeamPlayer $teamPlayer, Team $team, $title, array $params)
    {
        $matchup = $this->getMatchupMapper()->findNextMatch($team);

        $bob = new Builder();
        $bob->setTitle($title)
            ->setParams($params)
            ->setHref($team->getUrl() ? : "/fixtures/match/{$matchup->getId()}/results/{$team->getId()}")
            ->setIcon($this->getUserIcon($effector))
            ->setSeverity(Logger::INFO)
            ->setTopics([ sprintf('%s.%d.%s', $this->getSlug(), $teamPlayer->getId(), self::TRIGGER_REMOVED) ])
            ->setNamespace($this->getSlug())
        ;

        return $bob;
    }

    /* Getters/Setters
     */

    /**
     * @return TeamMapper
     */
    public function getTeamMapper()
    {
        return $this->teamMapper;
    }

    /**
     * @param TeamMapper $teamMapper
     */
    public function setTeamMapper($teamMapper)
    {
        $this->teamMapper = $teamMapper;
    }

    /**
     * @return MatchupMapper
     */
    public function getMatchupMapper()
    {
        return $this->matchupMapper;
    }

    /**
     * @param MatchupMapper $matchupMapper
     */
    public function setMatchupMapper($matchupMapper)
    {
        $this->matchupMapper = $matchupMapper;
    }

    /**
     * @return UserMapper
     */
    public function getUserMapper()
    {
        return $this->userMapper;
    }

    /**
     * @param UserMapper $userMapper
     */
    public function setUserMapper($userMapper)
    {
        $this->userMapper = $userMapper;
    }
}
