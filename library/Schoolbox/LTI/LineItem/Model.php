declare(strict_types=1);

namespace Schoolbox\LTI\LineItem;

use Alaress_Date_Format;
use Schoolbox\ISoftDeletable;
use Schoolbox\LTI\Assessment\Model as LtiAssessment;
use Schoolbox\Mapper\Traits\Model\CreatedAtDate;
use Schoolbox\Mapper\Traits\Model\DeletedAtDate;
use Schoolbox\Mapper\Traits\Model\Id;
use Schoolbox\Mapper\Traits\Model\UpdatedAtDate;

/**
 * LTI line item model.
 *
 * Represents a line item created directly by an LTI tool, as part of a 3rd
 * party assessment being created within Schoolbox.
 *
 * Some LTI tools request to create a line item before the assessment has
 * been created within Schoolbox. In order to facilitate this:
 * * Schoolbox generates a GUID, and passes the GUID in the create line item
 *   endpoint
 * * the tool may create line items with that endpoint
 * * upon saving of the assessment, Schoolbox associates the line item with
 *   the assessment
 *
 * Later, the LTI tool may post scores to this line item directly.
 */
class Model implements ISoftDeletable
{
    use Id;
    use CreatedAtDate;
    use UpdatedAtDate;
    use DeletedAtDate;

    /**
     * Associated LTI assessment, if one has been associated yet.
     */
    private ?LtiAssessment $ltiAssessment = null;

    /**
     * The GUID which this LTI line item was created with.
     *
     * As mentioned earlier: this is generated by Schoolbox, and used to set
     * `$this->ltiAssessment` when the assessment itself is saved.
     */
    private ?string $ltiAssessmentGuid = null;

    /**
     * The URL which is used to locate this line item.
     */
    private ?string $identifierUrl = null;

    /**
     * Human-readable label for the line item.
     */
    private ?string $label = null;

    /**
     * Maximum score for the line item.
     */
    private ?float $scoreMaximum = null;

    /**
     * Resource identifier for the line item.
     */
    private ?string $resourceId = null;

    /**
     * Resource link identifier for the line item.
     */
    private ?string $resourceLinkId = null;

    /**
     * Tag for the line item.
     */
    private ?string $tag = null;

    /**
     * Start date for the line item.
     */
    private ?Alaress_Date_Format $startDate = null;

    /**
     * End date for the line item.
     */
    private ?Alaress_Date_Format $endDate = null;

    /**
     * @return string|null
     */
    public function getLtiAssessmentGuid(): ?string
    {
        return $this->ltiAssessmentGuid;
    }

    /**
     * @param string|null $ltiAssessmentGuid
     * @return $this
     */
    public function setLtiAssessmentGuid(?string $ltiAssessmentGuid): self
    {
        $this->ltiAssessmentGuid = $ltiAssessmentGuid;
        return $this;
    }

    /**
     * @return string|null
     */
    public function getIdentifierUrl(): ?string
    {
        return $this->identifierUrl;
    }

    /**
     * @param string|null $identifierUrl
     * @return $this
     */
    public function setIdentifierUrl(?string $identifierUrl): self
    {
        $this->identifierUrl = $identifierUrl;
        return $this;
    }

    /**
     * @return LtiAssessment|null
     */
    public function getLtiAssessment(): ?LtiAssessment
    {
        return $this->ltiAssessment;
    }

    /**
     * @param LtiAssessment|null $ltiAssessment
     * @return $this
     */
    public function setLtiAssessment(?LtiAssessment $ltiAssessment): self
    {
        $this->ltiAssessment = $ltiAssessment;
        return $this;
    }

    /**
     * @return string|null
     */
    public function getLabel(): ?string
    {
        return $this->label;
    }

    /**
     * @param string|null $label
     * @return $this
     */
    public function setLabel(?string $label): self
    {
        $this->label = $label;
        return $this;
    }

    /**
     * @return float|null
     */
    public function getScoreMaximum(): ?float
    {
        return $this->scoreMaximum;
    }

    /**
     * @param float|null $scoreMaximum
     * @return $this
     */
    public function setScoreMaximum(?float $scoreMaximum): self
    {
        $this->scoreMaximum = $scoreMaximum;
        return $this;
    }

    /**
     * @return string|null
     */
    public function getResourceId(): ?string
    {
        return $this->resourceId;
    }

    /**
     * @param string|null $resourceId
     * @return $this
     */
    public function setResourceId(?string $resourceId): self
    {
        $this->resourceId = $resourceId;
        return $this;
    }

    /**
     * @return string|null
     */
    public function getResourceLinkId(): ?string
    {
        return $this->resourceLinkId;
    }

    /**
     * @param string|null $resourceLinkId
     * @return $this
     */
    public function setResourceLinkId(?string $resourceLinkId): self
    {
        $this->resourceLinkId = $resourceLinkId;
        return $this;
    }

    /**
     * @return string|null
     */
    public function getTag(): ?string
    {
        return $this->tag;
    }

    /**
     * @param string|null $tag
     * @return $this
     */
    public function setTag(?string $tag): self
    {
        $this->tag = $tag;
        return $this;
    }

    /**
     * @return Alaress_Date_Format|null
     */
    public function getStartDate(): ?Alaress_Date_Format
    {
        return $this->startDate;
    }

    /**
     * @param Alaress_Date_Format|null $startDate
     * @return $this
     */
    public function setStartDate(?Alaress_Date_Format $startDate): self
    {
        $this->startDate = $startDate;
        return $this;
    }

    /**
     * @return Alaress_Date_Format|null
     */
    public function getEndDate(): ?Alaress_Date_Format
    {
        return $this->endDate;
    }

    /**
     * @param Alaress_Date_Format|null $endDate
     * @return $this
     */
    public function setEndDate(?Alaress_Date_Format $endDate): self
    {
        $this->endDate = $endDate;
        return $this;
    }
}
