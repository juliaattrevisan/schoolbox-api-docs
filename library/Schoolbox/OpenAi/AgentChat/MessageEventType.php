declare(strict_types=1);

namespace Schoolbox\OpenAi\AgentChat;

/**
 * The possible event types that agentChat expects to receive during an event stream
 * This differs from the event types received from an AI tool, they are internal types to Agent Chat logic
 * @see /library/Schoolbox/Editor/OpenAI/templates/agentChat/store/agentChatPayload.ts
 */
enum MessageEventType: string
{
    /**
     * Intermediate event - The response was created and we received some sign of life back from the AI
     * Includes the response ID for tracking
     */
    case CREATED = 'created';
    /**
     * Intermediate event - A partial image generated by the AI
     */
    case PARTIAL_IMAGE = 'partial_image';
    /**
     * Intermediate event - A delta of text output from the AI
     * Will be appended to the current message to show the user that something is happening
     */
    case DELTA = 'delta';
    /**
     * A final response with a valid image/text to be shown
     * The frontend will terminate the stream after receiving this event
     */
    case COMPLETE = 'complete';
    /**
     * Something went wrong during the event stream, whether an internal error or an error from OpenAI
     * The data payload should contain error details following the format of RFC 9457 "API Problem" (title/detail)
     * The frontend will terminate the stream after receiving this event
     */
    case ERROR = 'error';
}
