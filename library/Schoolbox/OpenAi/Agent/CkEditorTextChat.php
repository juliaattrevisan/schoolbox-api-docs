declare(strict_types=1);

namespace Schoolbox\OpenAi\Agent;

use Schoolbox\Admin\OpenAI\Config;
use Schoolbox\Editor\OpenAI\Helper;
use Schoolbox\Editor\OpenAI\Log;
use Schoolbox\OpenAi\EventStream\Message;
use Schoolbox\OpenAi\IClient;
use Schoolbox\User;
use UnexpectedValueException;

/**
 * Agent for generating text chat responses via OpenAI, for CKEditor's AI
 * assistant feature.
 *
 * See https://ckeditor.com/docs/ckeditor5/latest/features/ai/ai-assistant/ai-assistant-overview.html
 * for an overview of this feature.
 */
class CkEditorTextChat
{
    /**
     * Constructor
     *
     * @param IClient $client An AI provider client.
     * @param array   $config Configuration for the agent: generated by `\Schoolbox\Admin\OpenAI\Config::decode`.
     */
    public function __construct(
        private IClient $client,
        private array $config,
    ) {
    }

    /**
     * Generate a text chat response, and stream the response as it's received.
     *
     * @param User   $user        The user making the request: used for logging.
     * @param array  $payload     The request payload, as generated by the CKEditor AI assistant.
     *                            This directly matches the request body of OpenAI's create chat completion API:
     *                            https://platform.openai.com/docs/api-reference/chat/create
     * @param string $aiSessionId An identifier for this AI session, used for logging.
     *                            Currently, this is generated per-request by Schoolbox: it is not reused between
     *                            requests.
     * @return iterable<string> Each message in `text/event-stream` format,
     *                          as it's received.
     */
    public function requestStream(
        User $user,
        array $payload,
        string $aiSessionId,
    ): iterable {
        // Need to inspect payload to figure out what the actual input text was!
        $payload = $this->buildPayload($payload);
        $log     = $this->client->createLog(
            $payload,
            $this->extractUserInput($payload),
            $user,
            Helper::FEATURE_CHAT,
            $aiSessionId,
        );
        return $this->client->createChatCompletionStream($payload, $log, streamListener: $this->listenForOutputText(...));
    }

    /**
     * Augment the payload for OpenAI with any required fields.
     *
     * This adds:
     * * a system prompt if one is configured
     * * usage data to the response
     *
     * @param array $payload
     * @return array
     */
    private function buildPayload(array $payload): array
    {
        $payload['messages'] ??= [];
        $payload['stream_options'] = ['include_usage' => true];
        $systemPrompt = $this->config[Helper::ENDPOINT_TYPE_GENERAL][Config::FIELD_SYSTEM_PROMPT]['value'] ?? '';
        if ($systemPrompt !== '') {
            array_unshift(
                $payload['messages'],
                [
                    'role'    => 'system',
                    'content' => $systemPrompt,
                ]
            );
        }
        return $payload;
    }

    /**
     * Extract the actual user input from the payload.
     *
     * @param array $payload
     * @return string|null
     */
    private function extractUserInput(array $payload): ?string
    {
        foreach (($payload['messages'] ?? []) as $message) {
            $role = $message['role'] ?? '';
            if ($role === 'user' && isset($message['content'])) {
                return $message['content'];
            }
        }
        return null;
    }

    /**
     * Callback method for message stream.
     *
     * If this message is a finished response, then extract the output text out
     * of it and add it to the log.
     *
     * @param Message   $message
     * @param Log\Model $log
     * @return void
     */
    private function listenForOutputText(Message $message, Log\Model $log): void
    {
        // Chat completions only returns chunked output, and never returns a
        // summary.
        // Need to reconstitute output text from the chunks.
        try {
            $decodedMessage = $message->getDataAsArray();
            foreach (($decodedMessage['choices'] ?? []) as $choice) {
                $content = $choice['delta']['content'] ?? null;
                if (isset($content)) {
                    $log->setOutputText($log->getOutputText() . $content);
                }
            }
            return;
        } catch (UnexpectedValueException) {
            // Not valid data: nothing can be done.
            // However the stream may return a `[DONE]` event:
            // that needs to be handled, and used to convert the content into
            // plain text (it's HTML)
        }

        if ($message->data === '[DONE]') {
            // The stream has finished:
            // make a best effort to convert HTML to plain text.
            // This assumes that the output:
            // * is actually Markdown
            // * contains actual HTML within ```html``` blocks

            // First up, remove the markdown wrappers:
            // assume anything within is HTML
            // If there's no markdown: assume the whole thing is HTML
            $htmlParts = [];
            if (preg_match_all('/```html(?P<html>.*?)```/s', $log->getOutputText(), $matches)) {
                $htmlParts = $matches['html'];
            } else {
                $htmlParts[] = $log->getOutputText();
            }

            // Now, for each HTML part: get its text only
            $outputTextParts = [];
            foreach ($htmlParts as $html) {
                // Then: use HTML2Text to remove all tags and header content
                $htmlToText = new \Html2Text\Html2Text($html);
                $html = $htmlToText->getText();
                $outputTextParts[] = $html;
            }

            // Finally: reconstitute the output text
            $outputText = !empty($outputTextParts)
                ? implode("\n\n", $outputTextParts)
                : null;
            $log->setOutputText($outputText);
        }
    }
}
