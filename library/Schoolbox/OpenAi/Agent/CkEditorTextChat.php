declare(strict_types=1);

namespace Schoolbox\OpenAi\Agent;

use Html2Text\Html2Text;
use Schoolbox\Admin\OpenAI\Config;
use Schoolbox\Editor\OpenAI\Helper;
use Schoolbox\OpenAi\IClient;
use Schoolbox\User;

/**
 * Agent for generating text chat responses via OpenAI, for CKEditor's AI
 * assistant feature.
 *
 * See https://ckeditor.com/docs/ckeditor5/latest/features/ai/ai-assistant/ai-assistant-overview.html
 * for an overview of this feature.
 */
class CkEditorTextChat
{
    /**
     * Constructor
     *
     * @param IClient   $client    An AI provider client.
     * @param array     $config    Configuration for the agent: generated by `\Schoolbox\Admin\OpenAI\Config::decode`.
     * @param Html2Text $html2Text HTML to text converter: required for converting the HTML response to plain text, for
     *                             storing in the log.
     */
    public function __construct(
        private IClient $client,
        private array $config,
        private Html2Text $html2Text,
    ) {
    }

    /**
     * Generate a text chat response, and stream the response as it's received.
     *
     * @param User   $user        The user making the request: used for logging.
     * @param array  $payload     The request payload, as generated by the CKEditor AI assistant.
     *                            This directly matches the request body of OpenAI's create chat completion API:
     *                            https://platform.openai.com/docs/api-reference/chat/create
     * @param string $aiSessionId An identifier for this AI session, used for logging.
     *                            Currently, this is generated per-request by Schoolbox: it is not reused between
     *                            requests.
     * @return iterable<string> Each message in `text/event-stream` format,
     *                          as it's received.
     */
    public function requestStream(
        User $user,
        array $payload,
        string $aiSessionId,
    ): iterable {
        // Need to inspect payload to figure out what the actual input text was!
        $payload = $this->buildPayload($payload);
        $log     = $this->client->createLog(
            $payload,
            $this->extractUserInput($payload),
            $user,
            Helper::FEATURE_CHAT,
            $aiSessionId,
            null, // TODO: should be able to use the AgentChat log format
        );

        /* Immediately pass on all streamed messages without any changes as CKEditor expects the raw response format */
        return $this->client->createChatCompletionStream(
            $payload,
            $log,
            logListener: new CkEditorTextChat\LogListener($this->html2Text),
        );
    }

    /**
     * Augment the payload for OpenAI with any required fields.
     *
     * This adds:
     * * a system prompt if one is configured
     * * usage data to the response
     *
     * @param array $payload
     * @return array
     */
    private function buildPayload(array $payload): array
    {
        // Model depends on azure vs. OpenAI
        $provider = $this->config[Config::FIELD_PROVIDER]['value'];
        $payload['model'] = $provider === Helper::ENDPOINT_TYPE_AZURE
            ? ($this->config[Helper::ENDPOINT_TYPE_AZURE][Config::FIELD_DEPLOYMENT_ID]['value'] ?? '')
            : ($this->config[Helper::ENDPOINT_TYPE_OPENAI][Config::FIELD_MODEL]['value'] ?? '')
        ;
        $payload['stream'] = true;
        $payload['max_completion_tokens'] = 10000;
        $reasoningEffort = trim($this->config[Config::SECTION_GENERAL][Config::FIELD_REASONING_EFFORT]['value'] ?? '');
        if ($reasoningEffort !== Config::REASONING_EFFORT_OPTION_DEFAULT) {
            $payload['reasoning_effort'] = $reasoningEffort;
        }
        $payload['verbosity'] = trim($this->config[Config::SECTION_GENERAL][Config::FIELD_TEXT_VERBOSITY]['value'] ?? '') ?: Config::TEXT_VERBOSITY_DEFAULT;
        $payload['temperature'] = 1;
        $payload['top_p'] = 1;
        $payload['messages'] ??= [];
        $payload['stream_options'] = ['include_usage' => true];
        $systemPrompt = $this->config[Helper::ENDPOINT_TYPE_GENERAL][Config::FIELD_SYSTEM_PROMPT]['value'] ?? '';
        if ($systemPrompt !== '') {
            array_unshift(
                $payload['messages'],
                [
                    'role'    => 'system',
                    'content' => $systemPrompt,
                ]
            );
        }

        // GPT-5 doesn't support max_tokens at all, it is deprecated for other
        // models
        if (isset($payload['max_tokens'])) {
            $maxTokens = $payload['max_tokens'];
            unset($payload['max_tokens']);
            $payload['max_completion_tokens'] = $maxTokens;
        }

        return $payload;
    }

    /**
     * Extract the actual user input from the payload.
     *
     * @param array $payload
     * @return string|null
     */
    private function extractUserInput(array $payload): ?string
    {
        foreach (($payload['messages'] ?? []) as $message) {
            $role = $message['role'] ?? '';
            if ($role === 'user' && isset($message['content'])) {
                return $message['content'];
            }
        }
        return null;
    }
}
