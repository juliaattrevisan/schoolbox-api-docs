declare(strict_types=1);

namespace Schoolbox\OpenAi\Agent;

use Schoolbox\Admin\OpenAI\Config;
use Schoolbox\Editor\OpenAI\Helper;
use Schoolbox\OpenAi\IClient;
use Schoolbox\User;

/**
 * Agent for generating text chat responses via OpenAI, for CKEditor's AI
 * assistant feature.
 *
 * See https://ckeditor.com/docs/ckeditor5/latest/features/ai/ai-assistant/ai-assistant-overview.html
 * for an overview of this feature.
 */
class CkEditorTextChat
{
    /**
     * Constructor
     *
     * @param IClient $client An AI provider client.
     * @param array   $config Configuration for the agent: generated by `\Schoolbox\Admin\OpenAI\Config::decode`.
     */
    public function __construct(
        private IClient $client,
        private array $config,
    ) {
    }

    /**
     * Generate a text chat response, and stream the response as it's received.
     *
     * @param User   $user        The user making the request: used for logging.
     * @param array  $payload     The request payload, as generated by the CKEditor AI assistant.
     *                            This directly matches the request body of OpenAI's create chat completion API:
     *                            https://platform.openai.com/docs/api-reference/chat/create
     * @param string $aiSessionId An identifier for this AI session, used for logging.
     *                            Currently, this is generated per-request by Schoolbox: it is not reused between
     *                            requests.
     * @return iterable<string> Each message in `text/event-stream` format,
     *                          as it's received.
     */
    public function requestStream(
        User $user,
        array $payload,
        string $aiSessionId,
    ): iterable {
        // Need to inspect payload to figure out what the actual input text was!
        $payload = $this->buildPayload($payload);
        $log     = $this->client->createLog($payload, null, $user, Helper::FEATURE_CHAT, $aiSessionId);
        return $this->client->createChatCompletionStream($payload, $log);
    }

    /**
     * Augment the payload for OpenAI with any required fields.
     *
     * This adds:
     * * a system prompt if one is configured
     * * usage data to the response
     *
     * @param array $payload
     * @return array
     */
    private function buildPayload(array $payload): array
    {
        $payload['messages'] ??= [];
        $payload['stream_options'] = ['include_usage' => true];
        $systemPrompt = $this->config[Helper::ENDPOINT_TYPE_GENERAL][Config::FIELD_SYSTEM_PROMPT]['value'] ?? '';
        if ($systemPrompt !== '') {
            array_unshift(
                $payload['messages'],
                [
                    'role'    => 'system',
                    'content' => $systemPrompt,
                ]
            );
        }
        return $payload;
    }
}
