declare(strict_types=1);

namespace Schoolbox\OpenAi\Agent;

use JsonException;
use Psr\Http\Client\ClientExceptionInterface;
use Schoolbox\Admin\OpenAI\Config;
use Schoolbox\Editor\OpenAI\Helper;
use Schoolbox\Editor\OpenAI\Log;
use Schoolbox\Editor\OpenAI\Payload\ImageGeneration as PayloadGenerator;
use Schoolbox\OpenAi\EventStream\Message;
use Schoolbox\OpenAi\IClient;
use Schoolbox\OpenAi\LogHandler\ResponseMessage;
use Schoolbox\User;

/**
 * Agent for generating images via OpenAI.
 */
class ImageGeneration
{
    /**
     * Constructor
     *
     * @param IClient $client An AI provider client: needs to point to the Responses endpoint of the client
     *                        (e.g. https://platform.openai.com/docs/api-reference/responses/create).
     * @param array   $config Configuration for the agent: generated by `\Schoolbox\Admin\OpenAI\Config::decode`.
     */
    public function __construct(
        private IClient $client,
        private array $config,
    ) {
    }

    /**
     * Streams an image generation payload.
     *
     * @param User        $user               The user making the request.
     * @param string      $prompt             The user's input prompt.
     * @param string      $sessionId          The session ID against which this request should be logged.
     * @param string|null $size               If provided: a size for the image.
     *                                        Should match a value of `ImageSize`.
     * @param string|null $style              If provided: a style for the image.
     *                                        Should match a value of `ImageStyle`.
     * @param string|null $imageUrl           If provided: a URL to use as an example for the image.
     * @param string|null $previousResponseId If provided: the ID of a previous request made to OpenAI.
     * @return iterable
     * @throws ClientExceptionInterface
     */
    public function requestStream(
        User $user,
        string $prompt,
        string $sessionId,
        ?string $size = null,
        ?string $style = null,
        ?string $imageUrl = null,
        ?string $previousResponseId = null,
    ): iterable {
        $payload = $this->buildPayload($prompt, $size, $style, $imageUrl, $previousResponseId);
        $log     = $this->client->createLog($payload, $prompt, $user, Helper::FEATURE_IMAGE, $sessionId);
        return $this->client->createResponseStream($payload, $log, 8192, $this->listenForOutputText(...));
    }

    /**
     * Build a payload for the AI provider.
     *
     * @param string      $prompt              The user's input prompt.
     * @param string|null $size                If provided: a size for the image.
     *                                         Should match a value of `ImageSize`.
     * @param string|null $style               If provided: a style for the image.
     *                                         Should match a value of `ImageStyle`.
     * @param string|null $imageUrl            If provided: a URL to use as an example for the image.
     * @param string|null $previousResponseId  If provided: the ID of a previous request made to OpenAI.
     * @return array
     */
    private function buildPayload(
        string $prompt,
        ?string $size = null,
        ?string $style = null,
        ?string $imageUrl = null,
        ?string $previousResponseId = null,
    ): array {
        // Retrieve model and quality from config:
        // this could vary if Schoolbox supports Azure or other providers later,
        // but for now it doesn't.
        $model        = $this->config[Config::SECTION_OPENAI][Config::FIELD_MODEL]['value'] ?? '';
        $quality      = $this->config[Config::SECTION_OPENAI][Config::FIELD_OUTPUT_QUALITY]['value'] ?? Config::OUTPUT_QUALITY_DEFAULT;
        $systemPrompt = $this->config[Config::SECTION_GENERAL][Config::FIELD_SYSTEM_PROMPT]['value'] ?? '';
        $payloadGenerator = new PayloadGenerator(
            $model,
            $systemPrompt,
            $quality,
        );
        return $payloadGenerator->generate(
            $prompt,
            (ImageSize::tryFrom($size) ?? ImageSize::Auto)->value,
            ImageStyle::tryFrom($style)?->value,
            $imageUrl,
            $previousResponseId,
        );
    }

    /**
     * Callback method for message stream.
     *
     * If this message is a finished response, then extract the output text out
     * of it and add it to the log.
     *
     * @param Message   $message
     * @param Log\Model $log
     * @return void
     */
    private function listenForOutputText(Message $message, Log\Model $log): void
    {
        if (in_array($message->eventType, ResponseMessage::EVENT_TYPES_FINISHED)) {
            $outputTextParts = [];
            try {
                $decodedMessage = json_decode($message->data, true, flags: JSON_THROW_ON_ERROR);
            } catch (JsonException) {
                // Not JSON: nothing can be done.
                // Could always inspect the full stream data to figure it out?
            }
            foreach (($decodedMessage['response']['output']) ?? [] as $output) {
                foreach (($output['content'] ?? []) as $content) {
                    if ($content['type'] === 'output_text' && isset($content['text'])) {
                        $outputTextParts[] = $content['text'];
                    }
                }
            }
            $outputText = !empty($outputTextParts)
                ? implode("\n\n", $outputTextParts)
                : null;
            $log->setOutputText($outputText);
        }
    }
}
