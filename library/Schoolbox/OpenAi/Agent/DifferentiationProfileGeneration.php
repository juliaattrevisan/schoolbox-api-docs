declare(strict_types=1);

namespace Schoolbox\OpenAi\Agent;

use Schoolbox\Admin\OpenAI\Config;
use Schoolbox\Collection;
use Schoolbox\Editor\OpenAI\Helper;
use Schoolbox\OpenAi\IClient;
use Schoolbox\Pastoral\Model;
use Schoolbox\Resource\Storage\FilesystemProxy;
use Schoolbox\User;
use Smalot\PdfParser\Parser;
use PhpOffice\PhpWord\IOFactory;

class DifferentiationProfileGeneration
{
    /**
     * Constructor
     *
     * @param IClient $client An AI provider client.
     * @param array   $config Configuration for the agent: generated by `\Schoolbox\Admin\OpenAI\Config::decode`.
     */
    public function __construct(
        private IClient $client,
        private array $config,
        private FilesystemProxy $filesystemProxy,
        private Parser $pdfParser,
    ) {
    }

    public function request(
        User $user,
        Collection $pastoralRecords,
        ?string $aiSessionId = null,
    ): array {

        $attachments = $this->generateFilePrompts($pastoralRecords);

        $payloadGenerator = new \Schoolbox\Editor\OpenAI\Payload\DifferentiationProfile(
            trim($this->config[Config::FIELD_PROVIDER]['value']),
            trim($this->config[Helper::ENDPOINT_TYPE_OPENAI][Config::FIELD_MODEL]['value'] ?? ''),
            trim($this->config[Helper::ENDPOINT_TYPE_AZURE][Config::FIELD_DEPLOYMENT_ID]['value'] ?? ''),
            trim($this->config[Config::SECTION_GENERAL][Config::FIELD_SYSTEM_PROMPT]['value'] ?? ''),
            trim($attachments)
        );

        $payload = $payloadGenerator->generate();

        $response = $this->client->createResponse(
            $payload,
            $user,
            Helper::FEATURE_DIFFERENTIATION,
            $aiSessionId
        );

        $data = json_decode($response->getBody()->getContents(), true);

        $relevantData = $data['output'][0]['content'][0]['text'] ?? null;

        if (!isset($relevantData)) {
            return [$data['output'] ?? null, 500];
        }

        try {
            $fieldData = json_decode(
                $relevantData,
                true,
                512,
                JSON_THROW_ON_ERROR
            );
        } catch (\JsonException $e) {
            return [$data['output'] ?? null, 500];
        }
        return [$fieldData, 200];
    }

    private function generateFilePrompts(Collection $pastoralRecords): string
    {
        $processed = $pastoralRecords->map(
            fn (Model $record) =>
                ($record->getBodyPublic() ?? '') . "\n\n" .
                $record->getAttachments()->reduce(
                    function (string $carry, \Schoolbox\Pastoral\Attachment\Model $attachment) {
                        if ($attachment->isDeleted()) {
                            return $carry;
                        }
                        if ($attachment->getMimetype()->isPDF()) {
                            $carry .= $this->pdfParser->parseContent(
                                $this->filesystemProxy->read($attachment)
                            )->getText() . "\n\n";
                        }

                        if ($attachment->getMimetype()->matches('application/vnd.openxmlformats-officedocument.wordprocessingml.document')) {
                            $readerType = 'Word2007';
                        } else if ($attachment->getMimetype()->matches('application/msword')) {
                            $readerType = 'MsDoc';
                        } else if ($attachment->getMimetype()->matches('application/vnd.oasis.opendocument.text')) {
                            $readerType = 'ODText';
                        }

                        if (isset($readerType)) {
                            $phpWord = IOFactory::load($this->filesystemProxy->localPath($attachment), $readerType);
                            foreach ($phpWord->getSections() as $section) {
                                foreach ($section->getElements() as $element) {
                                    if (method_exists($element, 'getText')) {
                                        $carry .= $element->getText() . "\n";
                                    } elseif ($element instanceof \PhpOffice\PhpWord\Element\TextRun) {
                                        foreach ($element->getElements() as $textRunElement) {
                                            if (method_exists($textRunElement, 'getText')) {
                                                $carry .= $textRunElement->getText();
                                            }
                                        }
                                        $carry .= "\n";
                                    } elseif ($element instanceof \PhpOffice\PhpWord\Element\Table) {
                                        // Handle table elements
                                        foreach ($element->getRows() as $row) {
                                            foreach ($row->getCells() as $cell) {
                                                foreach ($cell->getElements() as $cellElement) {
                                                    if (method_exists($cellElement, 'getText')) {
                                                        $carry .= $cellElement->getText() . "\t";
                                                    } elseif ($cellElement instanceof \PhpOffice\PhpWord\Element\TextRun) {
                                                        foreach ($cellElement->getElements() as $textRunElement) {
                                                            if (method_exists($textRunElement, 'getText')) {
                                                                $carry .= $textRunElement->getText();
                                                            }
                                                        }
                                                        $carry .= "\t";
                                                    }
                                                }
                                            }
                                            $carry .= "\n";
                                        }
                                    }
                                }
                            }
                        }
                        return $carry;
                    },
                    ''
                )
        );
        return implode("\n", $processed->getAll());
    }
}
