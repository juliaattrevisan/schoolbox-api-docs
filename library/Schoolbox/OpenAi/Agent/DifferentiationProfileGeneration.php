declare(strict_types=1);

namespace Schoolbox\OpenAi\Agent;

use Schoolbox\Admin\OpenAI\Config;
use Schoolbox\Collection;
use Schoolbox\DifferentiationProfile\FileParser\ParserFactory;
use Schoolbox\Editor\OpenAI\Helper;
use Schoolbox\OpenAi\IClient;
use Schoolbox\Pastoral\Model;
use Schoolbox\Presidio\Client;
use Schoolbox\Resource\Storage\FilesystemProxy;
use Schoolbox\User;

class DifferentiationProfileGeneration
{
    /**
     * Constructor
     *
     * @param IClient $client An AI provider client.
     * @param array   $config Configuration for the agent: generated by `\Schoolbox\Admin\OpenAI\Config::decode`.
     */
    public function __construct(
        private IClient $client,
        private array $config,
        private FilesystemProxy $filesystemProxy,
        private ParserFactory $parserFactory,
        private Client $presidioClient,
    ) {
    }

    /**
     * @param User        $user
     * @param Collection  $pastoralRecords
     * @param Collection  $enabledFields
     * @param User        $student
     * @param string|null $aiSessionId
     * @return array
     * @throws \Psr\Http\Client\ClientExceptionInterface
     */
    public function request(
        User $user,
        Collection $pastoralRecords,
        Collection $enabledFields,
        User $student,
        ?string $aiSessionId = null,
    ): array {

        $attachments = $this->generateFilePrompts($pastoralRecords);

        /* Deny list to force the anonymisation of the student's name
         * we will enforce anonymise student's full name, first name and preferred name
         */
        $personDenyList = [
            $student->getFullName(),
            (string)$student->getFirstName(),
            (string)$student->getPreferredName(),
        ];

        $customPersonRecognizer = [
            "name" => "CustomPersonDenyList",
            "supported_language" => "en",
            "supported_entity" => "PERSON",
            "deny_list" => array_filter($personDenyList),
        ];

        $attachments = $this->presidioClient->anonymiseWithTokens(
            $attachments,
            [
                'entities' => ['PERSON'],
                'ad_hoc_recognizers' => [
                    $customPersonRecognizer,
                ]
            ]
        )['anonymisedText'] ?? '';

        $payloadGenerator = new \Schoolbox\Editor\OpenAI\Payload\DifferentiationProfile(
            trim($this->config[Config::FIELD_PROVIDER]['value']),
            trim($this->config[Helper::ENDPOINT_TYPE_OPENAI][Config::FIELD_MODEL]['value'] ?? ''),
            trim($this->config[Helper::ENDPOINT_TYPE_AZURE][Config::FIELD_DEPLOYMENT_ID]['value'] ?? ''),
            trim($this->config[Config::SECTION_GENERAL][Config::FIELD_SYSTEM_PROMPT]['value'] ?? ''),
            trim($attachments),
            $enabledFields,
        );

        $payload = $payloadGenerator->generate();

        $log = $this->client->createLog(
            $payload,
            null,
            $user,
            Helper::FEATURE_DIFFERENTIATION,
            $aiSessionId,
            null, // These requests can't be restored in the AI Usage Log yet
        );
        $response = $this->client->createResponse($payload, $log);

        $data = json_decode($response->getBody()->getContents(), true);

        $relevantData = new ResponseParser()->extractContentText($data);

        if (!isset($relevantData)) {
            return [$data['output'] ?? null, 500];
        }

        try {
            $fieldData = json_decode(
                $relevantData,
                true,
                512,
                JSON_THROW_ON_ERROR
            );
        } catch (\JsonException $e) {
            return [$data['output'] ?? null, 500];
        }
        return [$fieldData, 200];
    }

    /**
     * Generate file prompts from pastoral records and flattening its attachments.
     *
     * @param Collection $pastoralRecords The collection of pastoral records.
     * @return string The generated file prompts.
     */
    private function generateFilePrompts(Collection $pastoralRecords): string
    {
        $processed = $pastoralRecords->map(
            fn (Model $record) =>
                ($record->getBodyPublic() ?? '') . "\n\n" .
                $record->getAttachments()->reduce(
                    function (string $carry, \Schoolbox\Pastoral\Attachment\Model $attachment) {
                        /* Skip deleted or private attachments
                         */
                        if ($attachment->isDeleted() || !$attachment->isPublic()) {
                            return $carry;
                        }
                        $parser = $this->parserFactory->produce($attachment);
                        /* Skipping unsupported file types
                         */
                        if ($parser === null) {
                            return $carry;
                        }

                        $carry .= $parser->flattenText($this->filesystemProxy->localPath($attachment));

                        return $carry;
                    },
                    ''
                )
        );
        /* Removing excessive whitespace but preserves the line breaks
         */
        return preg_replace("/[ \t]+/", " ", implode("\n", $processed->getAll()));
    }
}
