<?php

namespace Schoolbox\OpenAi\Agent;

use League\Flysystem\FilesystemException;
use Psr\Http\Client\ClientExceptionInterface;
use Schoolbox\Admin\OpenAI\Config;
use Schoolbox\DifferentiationProfile\FileParser\ParserFactory;
use Schoolbox\DifferentiationProfile\Model as DifferentiationProfileModel;
use Schoolbox\DifferentiationProfile\Translator\ProfileToArray;
use Schoolbox\Editor\OpenAI\Helper;
use Schoolbox\Learning\Assessment\IAssessable;
use Schoolbox\OpenAi\IClient;
use Schoolbox\Resource\Folder\Model as Folder;
use Schoolbox\Resource\Storage\FilesystemProxy;
use Schoolbox\Resource\Storage\IStorage;
use Schoolbox\User;

class LearningActivityCustomisationGeneration
{
    /**
     * Constructor
     *
     * @param IClient $client An AI provider client.
     * @param array   $config Configuration for the agent: generated by `\Schoolbox\Admin\OpenAI\Config::decode`.
     */
    public function __construct(
        private IClient $client,
        private array $config,
        private FilesystemProxy $filesystemProxy,
        private ParserFactory $parserFactory,
        private ProfileToArray $profileToArray,
    ) {
    }

    /**
     * @param User                        $user                        The user requesting the customisation.
     * @param IAssessable                 $assessable                  The assessable learning activity.
     * @param DifferentiationProfileModel $differentiationProfileModel The differentiation profile
     * @param Folder                      $course
     * @param string|null                 $aiSessionId
     * @return array
     * @throws ClientExceptionInterface
     */
    public function request(
        User $user,
        IAssessable $assessable,
        DifferentiationProfileModel $differentiationProfileModel,
        Folder $course,
        ?string $aiSessionId = null,
    ): array {
        $attachments = $this->generateFilePrompts($assessable);

        $payloadGenerator = new \Schoolbox\Editor\OpenAI\Payload\LearningActivityCustomisation(
            trim($this->config[Config::FIELD_PROVIDER]['value']),
            trim($this->config[Helper::ENDPOINT_TYPE_OPENAI][Config::FIELD_MODEL]['value'] ?? ''),
            trim($this->config[Helper::ENDPOINT_TYPE_AZURE][Config::FIELD_DEPLOYMENT_ID]['value'] ?? ''),
            trim($this->config[Config::SECTION_GENERAL][Config::FIELD_SYSTEM_PROMPT]['value'] ?? ''),
            trim($this->config[Config::SECTION_GENERAL][Config::FIELD_REASONING_EFFORT]['value'] ?? '') ?: Config::REASONING_EFFORT_DEFAULT,
            trim($this->config[Config::SECTION_GENERAL][Config::FIELD_TEXT_VERBOSITY]['value'] ?? '') ?: Config::TEXT_VERBOSITY_DEFAULT,
            $assessable,
            $differentiationProfileModel->getStudent(),
            $course,
            $attachments,
            json_encode(\call_user_func($this->profileToArray, $differentiationProfileModel), JSON_THROW_ON_ERROR),
        );

        $payload = $payloadGenerator->generate();
        $log = $this->client->createLog($payload, null, $user, Helper::FEATURE_LEARNING_ACTIVITY_CUSTOMISATION, $aiSessionId);
        $response = $this->client->createResponse($payload, $log);

        $data = json_decode($response->getBody()->getContents(), true);

        $relevantData = new ResponseParser()->extractContentText($data);

        if (!isset($relevantData)) {
            return [$data['output'] ?? null, 500];
        }

        try {
            $fieldData = json_decode(
                $relevantData,
                true,
                512,
                JSON_THROW_ON_ERROR
            );
        } catch (\JsonException $e) {
            return [$data['output'] ?? null, 500];
        }
        // Implementation for learning activity customisation generation
        return [$fieldData, 200];
    }

    /**
     * Generate file prompts from assessable's attachments and flattening its content.
     *
     * @param IAssessable $assessable The assessable learning activity.
     * @return string The generated file prompts.
     * @throws FilesystemException
     */
    private function generateFilePrompts(IAssessable $assessable): string
    {
        if (!is_callable([$assessable, 'getAttachedFiles'])) {
            return '';
        }

        $processed = $assessable->getAttachedFiles()->reduce(
        /**
         * @throws FilesystemException
         */
            function (string $carry, IStorage $attachment) {
                $parser = $this->parserFactory->produce($attachment);
                /* Skipping unsupported file types
                 */
                if ($parser === null) {
                    return $carry;
                }

                $carry .= $parser->flattenText($this->filesystemProxy->localPath($attachment));

                return $carry;
            },
            ''
        );
        return $processed;
    }
}
