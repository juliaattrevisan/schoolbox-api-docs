declare(strict_types=1);

namespace Schoolbox\OpenAi\Agent;

use Psr\Http\Client\ClientExceptionInterface;
use Schoolbox\Application\Exception\Exception as SchoolboxException;
use Schoolbox\Admin\OpenAI\Config;
use Schoolbox\Editor\OpenAI\Helper;
use Schoolbox\OpenAi\Session\Log;
use Schoolbox\Editor\OpenAI\Payload\InteractionModeration as PayloadGenerator;
use Schoolbox\OpenAi\Moderation\Result\Result;
use Schoolbox\OpenAi\IClient;
use Schoolbox\GenericCollection;
use Schoolbox\User;

/**
 * Moderation agent for reviewing AI interactions.
 *
 * This differs to the Moderation Guardrail Check as it's designed to review with full conversation context
 * rather than an individual message.
 */
class InteractionModeration
{
    /**
     * Constructor
     *
     * @param IClient $client An AI provider client: needs to point to the Responses endpoint of the client
     *                        (e.g. https://platform.openai.com/docs/api-reference/responses/create).
     * @param array   $config Configuration for the agent: generated by `\Schoolbox\Admin\OpenAI\Config::decode`.
     */
    public function __construct(
        private IClient $client,
        private array $config,
    ) {
    }

    /**
     * Request moderation of an interaction feed to be generated.
     *
     * @param ?User    $user      The user making the request, if any.
     * @param string   $sessionId The session ID against which this request should be logged.
     * @param GenericCollection<Log\Model> $interactionFeed The chronological feed of AI interaction logs for a session to moderate
     * @return Result
     * @throws ClientExceptionInterface
     * @throws SchoolboxException
     */
    public function request(
        ?User $user,
        string $sessionId,
        GenericCollection $interactionFeed
    ): Result {
        $payload = new PayloadGenerator(
            trim($this->config[Config::FIELD_PROVIDER]['value']),
            trim($this->config[Helper::ENDPOINT_TYPE_OPENAI][Config::FIELD_MODEL]['value'] ?? ''),
            trim($this->config[Helper::ENDPOINT_TYPE_AZURE][Config::FIELD_DEPLOYMENT_ID]['value'] ?? ''),
            trim($this->config[Helper::ENDPOINT_TYPE_AZURE][Config::FIELD_DEPLOYMENT_MODEL]['value'] ?? ''),
            trim($this->config[Helper::ENDPOINT_TYPE_GENERAL][Config::FIELD_REASONING_EFFORT]['value'] ?? '') ?: Config::REASONING_EFFORT_OPTION_DEFAULT,
            trim($this->config[Helper::ENDPOINT_TYPE_GENERAL][Config::FIELD_TEXT_VERBOSITY]['value'] ?? '') ?: Config::TEXT_VERBOSITY_OPTION_DEFAULT,
        )->generate($interactionFeed);

        $log = $this->client->createLog(
            $payload,
            null, // no meaningful input text unique to this log atm, it's all in the payload if you need to debug
            $user,
            \Schoolbox\OpenAi\Feature::AI_MODERATION_AGENT,
            $sessionId,
            null, // These requests can't be restored in the AI Usage Log yet
        );

        $moderationResponse = $this->client->createResponse($payload, $log);

        return $this->parseResponse($moderationResponse->getBody()->getContents());
    }


    /**
     * Handle the response from the AI for a request
     * @param string $moderationResponseData
     * @return Result
     * @throws SchoolboxException
     */
    private function parseResponse(string $moderationResponseData): Result
    {
        // This response used to need special handling of its return, because it
        // was not guaranteed to be valid JSON.
        // That no longer seems to be required, but the original comment was:
        // Send it and decode the result (if any: sometimes it returns null)
        // and dodge around all its weird encoding business with a double-decode,
        // and ditching all its training markdown (lol) that it loves to use
        //
        // https://community.openai.com/t/json-returning-with-json/584818/6
        $data         = json_decode($moderationResponseData, true);
        $relevantData = new ResponseParser()->extractContentText($data);

        if (!isset($relevantData)) {
            throw new SchoolboxException('Invalid response');
        }

        try {
            /* if this didn't decode correctly, then some weird response came from the AI:
             * send that on... so we can figure out what happened
             */
            $moderationResult = json_decode(
                $relevantData,
                true,
                512,
                JSON_THROW_ON_ERROR,
            );
        } catch (\JsonException $e) {
            throw new SchoolboxException('Invalid response', 0, $e);
        }


        try {
            /* theoretically the structured output from the AI should always align with
             * the spec since strict=true, a ValueError would only be thrown if somehow
             * an enum value didn't match
             */
            return Result::fromArray($moderationResult);
        } catch (\ValueError $e) {
            throw new SchoolboxException('Invalid response format', 0, $e);
        }
    }
}
