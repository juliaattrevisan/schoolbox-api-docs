declare(strict_types=1);

namespace Schoolbox\OpenAi\Agent;

use Psr\Http\Client\ClientExceptionInterface;
use Schoolbox\Admin\DialogAgent\Scenario\Model as Scenario;
use Schoolbox\Admin\OpenAI\Config;
use Schoolbox\Editor\OpenAI\Helper;
use Schoolbox\Editor\OpenAI\Log;
use Schoolbox\Editor\OpenAI\Payload\DialogAgentFeedback as PayloadGenerator;
use Schoolbox\Learning\Assessment\DialogAgent\Response\Model as Response;
use Schoolbox\OpenAi\IClient;
use Schoolbox\User;

/**
 * Summative review agent for reviewing a chat interaction from DialogAgentChat and
 * and generating feedback that the teacher can access
 */
class DialogAgentFeedback
{
    /**
     * Constructor
     *
     * @param IClient $client An AI provider client: needs to point to the Responses endpoint of the client
     *                        (e.g. https://platform.openai.com/docs/api-reference/responses/create).
     * @param array   $config Configuration for the agent: generated by `\Schoolbox\Admin\OpenAI\Config::decode`.
     * @param Log\Mapper $aiLogMapper
     */
    public function __construct(
        private IClient $client,
        private array $config,
        private Log\Mapper $aiLogMapper,
    ) {
    }

    /**
     * Request feedback for a dialog agent response to be generated.
     *
     * @param ?User    $user      The user making the request, if any.
     * @param string   $sessionId The session ID against which this request should be logged.
     * @param Scenario $scenario
     * @param Response $response
     * @return string
     * @throws ClientExceptionInterface
     */
    public function request(
        ?User $user,
        string $sessionId,
        Scenario $scenario,
        Response $response
    ): string {
        $payload = new PayloadGenerator(
            trim($this->config[Config::FIELD_PROVIDER]['value']),
            trim($this->config[Helper::ENDPOINT_TYPE_OPENAI][Config::FIELD_MODEL]['value'] ?? ''),
            trim($this->config[Helper::ENDPOINT_TYPE_AZURE][Config::FIELD_DEPLOYMENT_ID]['value'] ?? ''),
            trim($this->config[Helper::ENDPOINT_TYPE_GENERAL][Config::FIELD_SYSTEM_PROMPT]['value'] ?? ''),
            $this->aiLogMapper,
        )->generate($scenario, $response);

        $log = $this->client->createLog(
            $payload,
            $response->getId(), // for debugging purposes, this links the log back to the response ID
            $user,
            Helper::FEATURE_DIALOGAGENT,
            $sessionId,
            null, // These requests can't be restored in the AI Usage Log yet
        );

        $response = $this->client->createResponse($payload, $log);

        return $response->getBody()->getContents();
    }
}
