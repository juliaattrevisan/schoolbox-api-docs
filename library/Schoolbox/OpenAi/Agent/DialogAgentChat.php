use Schoolbox\OpenAi\LogHandler\Composite;
use Schoolbox\User;

/**
 * Agent for having a conversation with the AI in a Dialog Agent activity
 */
class DialogAgentChat
{
    /**
     * The message to display when a guardrail check fails for a learner's request
     */
    public const string GUARDRAIL_FAIL_LEARNER_MESSAGE = "Your response didn't meet the discussion guidelines, so it has been locked.

Your teacher has been notified.";

    /**
     * Constructor
     *
     * @param IClient               $client                An AI provider client: needs to point to the Responses
     *                                                     endpoint of the client, e.g.
     *                                                     https://platform.openai.com/docs/api-reference/responses/create
     * @param ?IClient              $moderationClient      An AI provider client: if "AI Moderation" config is enabled.
     *                                                     Needs to point to the Moderation endpoint of the client, e.g.
     *                                                     https://platform.openai.com/docs/api-reference/moderations/create
     * @param array                 $config                Configuration for the agent:
     *                                                     generated by `\Schoolbox\Admin\OpenAI\Config::decode`.
     * @param ResponseMapper $responseMapper               Mapper for saving dialog agent responses.
     * @param ResponseMessageMapper $responseMessageMapper Mapper for saving response messages.
     */
    public function __construct(
        private IClient $client,
        private ?IClient $moderationClient,
        private array $config,
        private ResponseMapper $responseMapper,
        private ResponseMessageMapper $responseMessageMapper,
    ) {
    }


    /**
     * Build the guardrails pipeline for this agent
     *
     * @param User        $user
     * @param string      $sessionId
     * @param null|string $previousResponseId
     * @return Guardrails\Pipeline
     */
    private function buildGuardrails(User $user, string $sessionId, ?string $previousResponseId): Guardrails\Pipeline
    {
        $pipeline = new Guardrails\Pipeline(
            $this->client,
            $user,
            Helper::FEATURE_DIALOGAGENT,
            $sessionId,
        );

        $pipeline->addInputCheck(new Guardrails\Check\CharacterLimit());

        if (null !== $this->moderationClient) {
            $pipeline->addInputCheck(new Guardrails\Check\Moderation($this->moderationClient));
        }

        // $pipeline->addInputCheck(new Guardrails\Check\TopicalAlignment(
        //     $this->client,
        //     $this->config[Helper::ENDPOINT_TYPE_OPENAI][Config::FIELD_MODEL]['value'],
        //     // TODO: placeholder system prompt, this should include better context
        //     "You are a helpful assistant. Keep responses focused on the user's questions and avoid going off-topic.",
        //     previousResponseId: $previousResponseId,
        // ));

        return $pipeline;
    }


    /**
     * Streams a dialog agent chat.
     *
     * @param User               $user                   The user making the request.
     * @param DialogAgent        $assessment             The dialog agent activity.
     * @param string|null        $differentiationProfile The learner's differentiation profile, ready to be used in the prompt directly.
     * @param string             $userPrompt             The user's input prompt.
     * @param string             $sessionId              The session ID against which this request should be logged.
     * @param string|null        $previousResponseId     If provided: the ID of a previous request made to OpenAI.
     * @param ResponseModel|null $responseModel          If provided: store messages sent and received in this response.
     * @return iterable<string>
     * @throws ClientExceptionInterface
     * @throws GuardrailFlagged
     */
    public function requestStream(
        User $user,
        DialogAgent $assessment,
        string $userPrompt,
        ?string $differentiationProfile,
        string $sessionId,
        ?string $previousResponseId = null,
        ?ResponseModel $responseModel = null,
    ): iterable {
        // TODO: In ALL AI endpoints, we should validate the prompt length to avoid malicious token usage

        /* If there's a response model, add a message for the user's request */
        if ($responseModel) {
            // $responseModel is a domain object: translate to data model
            $responseMessageModel = $this->responseMessageMapper->createModel()
                ->setDialogAgentResponse(new ResponseDataModel()->setId($responseModel->getId()))
                ->setRole(Role::User->value)
                ->setStatus(Status::Ok->value)
                ->setContent($userPrompt);
            $this->responseMessageMapper->save($responseMessageModel);
        }

        $pipeline = $this->buildGuardrails($user, $sessionId, $previousResponseId);

        try {
            $pipeline->checkInputGuardrails($userPrompt);
        } catch (GuardrailFlagged $e) {
            // guardrail triggered, the request should not proceed
            return $this->handleGuardrailFailure($e, $responseModel);
        }

        $payload = new PayloadGenerator(
            trim($this->config[Config::FIELD_PROVIDER]['value']),
            trim($this->config[Helper::ENDPOINT_TYPE_OPENAI][Config::FIELD_MODEL]['value'] ?? ''),
            trim($this->config[Helper::ENDPOINT_TYPE_AZURE][Config::FIELD_DEPLOYMENT_ID]['value'] ?? ''),
            trim($this->config[Helper::ENDPOINT_TYPE_GENERAL][Config::FIELD_SYSTEM_PROMPT]['value'] ?? ''),
            trim($this->config[Helper::ENDPOINT_TYPE_GENERAL][Config::FIELD_REASONING_EFFORT]['value'] ?? '') ?: Config::REASONING_EFFORT_DEFAULT,
            trim($this->config[Helper::ENDPOINT_TYPE_GENERAL][Config::FIELD_TEXT_VERBOSITY]['value'] ?? ''),
        )->generate(
            $assessment,
            $userPrompt,
            $previousResponseId,
            $differentiationProfile,
        );

        $logListener = new LogOutputText();

        /* If there's a response,
         * also listen for the completed response from the agent, and add a message once it's done
         */
        if ($responseModel) {
            $logListener = new Composite(
                $logListener,
                new DialogAgentChat\SaveMessageLogListener($this->responseMessageMapper, $responseModel),
            );
        }

        $log = $this->client->createLog(
            $payload,
            $userPrompt,
            $user,
            Helper::FEATURE_DIALOGAGENT,
            $sessionId,
            Log\Translator\Format\AgentChat::getLogFormat(),
        );

        /** Immediately save the log so the dialog agent response can be associated without failing a foreign key constraint */
        $this->client->saveLog($log);

        return $this->client->createResponseStream(
            $payload,
            $log,
            null,
            new ResponseListener(requireFinalImage: false),
            $logListener,
        );
    }

    /**
     * When a guardrail fails, handle the flagged message
     * @param GuardrailFlagged $e
     * @param ?ResponseModel $responseModel
     * @return iterable<string>
     */
    private function handleGuardrailFailure(GuardrailFlagged $e, ?ResponseModel $responseModel): iterable
    {
        $message = $e->getMessage();

        /**
         * If there's a response model, then this is a request as part of a learner's attempt.
         * - show the learner a custom message due to the failure and log it to the response so we can show it again later
         * - lock the response as it failed guardrails
         */
        if ($responseModel) {
            $responseMessageModel = $this->responseMessageMapper->createModel()
                ->setDialogAgentResponse(new ResponseDataModel()->setId($responseModel->getId()))
                ->setRole(Role::Assistant->value)
                ->setStatus(Status::GuardrailFlagged->value)
                ->setContent(json_encode($e->getOutcome()->asArray(), JSON_THROW_ON_ERROR))
                // Set the creation time to the current time,
                // instead of the request time:
                // this more accurately reflects when the response was received.
                ->setCreatedAt(\Alaress_Date_Format::newFromTimestamp(time()));
            $this->responseMessageMapper->save($responseMessageModel);

            // override the message to a generic one for the learner
            $message = self::GUARDRAIL_FAIL_LEARNER_MESSAGE;

            // lock the response
            $responseModel->setLockedAt(\Alaress_Date_Format::now());
            $this->responseMapper->save($responseModel);
        }

        $outputMessage = new Message(
            json_encode(['message' => $message], JSON_THROW_ON_ERROR),
            MessageEventType::GUARDRAIL_FLAGGED->value
        );

        yield $outputMessage->__toString();
    }
}
