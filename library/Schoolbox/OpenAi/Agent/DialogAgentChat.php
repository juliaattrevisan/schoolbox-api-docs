declare(strict_types=1);

namespace Schoolbox\OpenAi\Agent;

use Psr\Http\Client\ClientExceptionInterface;
use Schoolbox\Admin\OpenAI\Config;
use Schoolbox\Editor\OpenAI\Helper;
use Schoolbox\Editor\OpenAI\Log;
use Schoolbox\Editor\OpenAI\Payload\DialogAgentChat as PayloadGenerator;
use Schoolbox\GenericCollection;
use Schoolbox\Learning\Assessment\DataModel\DialogAgent\Response\Message\Role;
use Schoolbox\Learning\Assessment\DataModel\DialogAgent\Response\Message\Status;
use Schoolbox\Learning\Assessment\DialogAgent\Response\Model as ResponseModel;
use Schoolbox\Learning\Assessment\DataModel\DialogAgent\Response\Model as ResponseDataModel;
use Schoolbox\Learning\Assessment\DataModel\DialogAgent\Response\Message\Mapper as ResponseMessageMapper;
use Schoolbox\Learning\Assessment\DialogAgent\Model as DialogAgent;
use Schoolbox\OpenAi\AgentChat\EventStream\ResponseListener;
use Schoolbox\OpenAi\AgentChat\LogHandler\LogOutputText;
use Schoolbox\OpenAi\Exception\GuardrailFlagged;
use Schoolbox\OpenAi\Guardrails;
use Schoolbox\OpenAi\IClient;
use Schoolbox\OpenAi\LogHandler\Composite;
use Schoolbox\User;

/**
 * Agent for having a conversation with the AI in a Dialog Agent activity
 */
class DialogAgentChat
{
    /**
     * Guardrail config for the Moderation check
     * @see Schoolbox\OpenAi\Guardrails\Check\Moderation
     */
    private const array GUARDRAIL_CONFIG_MODERATION = [
        'categories' => [
            "sexual",
            "sexual/minors",
            "hate",
            "hate/threatening",
            "harassment",
            "harassment/threatening",
            "self-harm",
            "self-harm/intent",
            "self-harm/instructions",
            "violence",
            "violence/graphic",
            "illicit",
            "illicit/violent",
        ]
    ];

    /**
     * Guardrail config for the Topical Alignment check
     * @see Schoolbox\OpenAi\Guardrails\Check\TopicalAlignment
     */
    private const array GUARDRAIL_CONFIG_TOPICAL_ALIGNMENT = [
        // TODO: placeholder system prompt, this should include better context
        'system_prompt_details' => "You are a helpful assistant. Keep responses focused on the user's questions and avoid going off-topic.",
    ];

    /**
     * Constructor
     *
     * @param IClient               $client                An AI provider client: needs to point to the Responses
     *                                                     endpoint of the client, e.g.
     *                                                     https://platform.openai.com/docs/api-reference/responses/create
     * @param IClient               $moderationClient      An AI provider client: needs to point to the Moderation
     *                                                     endpoint of the client, e.g.
     *                                                     https://platform.openai.com/docs/api-reference/moderations/create
     * @param array                 $config                Configuration for the agent:
     *                                                     generated by `\Schoolbox\Admin\OpenAI\Config::decode`.
     * @param ResponseMessageMapper $responseMessageMapper Mapper for saving response messages.
     */
    public function __construct(
        private IClient $client,
        private IClient $moderationClient,
        private array $config,
        private ResponseMessageMapper $responseMessageMapper,
    ) {
    }

    /**
     * Streams a dialog agent chat.
     *
     * @param User               $user                   The user making the request.
     * @param DialogAgent        $assessment             The dialog agent activity.
     * @param string|null        $differentiationProfile The learner's differentiation profile, ready to be used in the prompt directly.
     * @param string             $userPrompt             The user's input prompt.
     * @param string             $sessionId              The session ID against which this request should be logged.
     * @param string|null        $previousResponseId     If provided: the ID of a previous request made to OpenAI.
     * @param ResponseModel|null $responseModel          If provided: store messages sent and received in this response.
     * @return iterable<string>
     * @throws ClientExceptionInterface
     * @throws GuardrailFlagged
     */
    public function requestStream(
        User $user,
        DialogAgent $assessment,
        string $userPrompt,
        ?string $differentiationProfile,
        string $sessionId,
        ?string $previousResponseId = null,
        ?ResponseModel $responseModel = null,
    ): iterable {
        $payload = new PayloadGenerator(
            trim($this->config[Config::FIELD_PROVIDER]['value']),
            trim($this->config[Helper::ENDPOINT_TYPE_OPENAI][Config::FIELD_MODEL]['value'] ?? ''),
            trim($this->config[Helper::ENDPOINT_TYPE_AZURE][Config::FIELD_DEPLOYMENT_ID]['value'] ?? ''),
            trim($this->config[Helper::ENDPOINT_TYPE_GENERAL][Config::FIELD_SYSTEM_PROMPT]['value'] ?? ''),
        )->generate(
            $assessment,
            $userPrompt,
            $previousResponseId,
            $differentiationProfile,
        );

        $logListener = new LogOutputText();

        // Is there a response model?
        // If so, add a message for the response.
        if ($responseModel) {
            // $responseModel is a domain object: translate to data model
            $responseMessageModel = $this->responseMessageMapper->createModel()
                ->setDialogAgentResponse(new ResponseDataModel()->setId($responseModel->getId()))
                ->setRole(Role::User->value)
                ->setStatus(Status::Ok->value)
                ->setContent($userPrompt);
            $this->responseMessageMapper->save($responseMessageModel);

            // Also: listen for the completed response from the agent, and add
            // a message once it's done
            $logListener = new Composite(
                $logListener,
                new DialogAgentChat\SaveMessageLogListener($this->responseMessageMapper, $responseModel),
            );
        }

        $log = $this->client->createLog(
            $payload,
            $userPrompt,
            $user,
            Helper::FEATURE_DIALOGAGENT,
            $sessionId,
            Log\Translator\Format\AgentChat::getLogFormat(),
        );

        /** Immediately save the log so the dialog agent response can be associated without failing a foreign key constraint */
        $this->client->saveLog($log);

        // TODO: this should be in its own handler class
        /** Guardrails: Preflight checks run first */
        /** @var GenericCollection<Guardrails\Check\ICheck> $preflightChecks */
        $preflightChecks = new GenericCollection(Guardrails\Check\ICheck::class);
        $preflightChecks->add(new Guardrails\Check\Moderation(
            $this->moderationClient,
            self::GUARDRAIL_CONFIG_MODERATION,
            $user,
            Helper::FEATURE_DIALOGAGENT,
            $sessionId,
        ));

        foreach ($preflightChecks as $check) {
            $outcome = $check->check($userPrompt);

            if ($outcome->isFlagged()) {
                throw new GuardrailFlagged($check, json_encode($outcome->getMetadata()));
            }
        }


        // Apply pre-flight modifications
        // TODO


        /** Guardrails: Input checks */
        // TODO These could be called concurrently?
        /** @var GenericCollection<Guardrails\Check\ICheck> $inputChecks */
        $inputChecks = new GenericCollection(Guardrails\Check\ICheck::class);
        $inputChecks->add(new Guardrails\Check\TopicalAlignment(
            $this->client,
            [
                ...self::GUARDRAIL_CONFIG_TOPICAL_ALIGNMENT,
                'model' => $this->config[Helper::ENDPOINT_TYPE_OPENAI][Config::FIELD_MODEL]['value'],
                'previous_response_id' => $previousResponseId,
            ],
            $user,
            Helper::FEATURE_DIALOGAGENT,
            $sessionId,
        ));

        foreach ($inputChecks as $check) {
            $outcome = $check->check($userPrompt); // TODO: surely TopicalAlignment needs more context than just the user's message...

            if ($outcome->isFlagged()) {
                throw new GuardrailFlagged($check, json_encode($outcome->getMetadata()));
            }
        }


        return $this->client->createResponseStream(
            $payload,
            $log,
            null,
            new ResponseListener(requireFinalImage: false),
            $logListener,
        );

        /** Guardrails: Output checks */
        // TODO
    }
}
