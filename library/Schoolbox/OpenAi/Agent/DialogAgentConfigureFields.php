declare(strict_types=1);

namespace Schoolbox\OpenAi\Agent;

use Psr\Http\Client\ClientExceptionInterface;
use Schoolbox\Application\Exception\Exception as SchoolboxException;
use Schoolbox\Admin\DialogAgent\Scenario\Model as Scenario;
use Schoolbox\Admin\OpenAI\Config;
use Schoolbox\Editor\OpenAI\Helper;
use Schoolbox\Editor\OpenAI\Payload\DialogAgentConfigureFields as PayloadGenerator;
use Schoolbox\Learning\Assessment\DialogAgent\Model as DialogAgent;
use Schoolbox\OpenAi\IClient;
use Schoolbox\Collection;
use Schoolbox\User;

/**
 * Agent to assist with configuring the initial fields of a new Dialog Agent activity
 * This occurs right after the activity is created, before the instructor starts configuring the agent
 */
class DialogAgentConfigureFields
{
    /**
     * Constructor
     *
     * @param IClient $client An AI provider client: needs to point to the Responses endpoint of the client
     *                        (e.g. https://platform.openai.com/docs/api-reference/responses/create).
     * @param array   $config Configuration for the agent: generated by `\Schoolbox\Admin\OpenAI\Config::decode`.
     */
    public function __construct(
        private IClient $client,
        private array $config,
    ) {
    }

    /**
     * Request for an initial field configuration for a dialog agent activity to be generated
     *
     * @param User     $user      The user making the request
     * @param string   $sessionId The session ID against which this request should be logged.
     * @param Scenario $scenario
     * @param DialogAgent $assessment
     * @return array{openingMessage:string|null,fields:Collection<int,string|null>} Response data, fields are a map of field ID to generated value
     * @throws ClientExceptionInterface
     * @throws SchoolboxException
     */
    public function request(
        User $user,
        string $sessionId,
        Scenario $scenario,
        DialogAgent $assessment,
    ): array {
        $payload = new PayloadGenerator(
            trim($this->config[Config::FIELD_PROVIDER]['value']),
            trim($this->config[Helper::ENDPOINT_TYPE_OPENAI][Config::FIELD_MODEL]['value'] ?? ''),
            trim($this->config[Helper::ENDPOINT_TYPE_AZURE][Config::FIELD_DEPLOYMENT_ID]['value'] ?? ''),
            trim($this->config[Helper::ENDPOINT_TYPE_GENERAL][Config::FIELD_SYSTEM_PROMPT]['value'] ?? ''),
        )->generate($scenario, $assessment);

        $log = $this->client->createLog(
            $payload,
            (string)$assessment->getId(), // for debugging purposes, this links the log back to the assessment ID
            $user,
            Helper::FEATURE_DIALOGAGENT,
            $sessionId,
            null, // These requests can't be restored in the AI Usage Log yet
        );

        $feedbackResponse = $this->client->createResponse($payload, $log);

        return $this->parseResponse($scenario, $feedbackResponse->getBody()->getContents());
    }


    /**
     * Handle the response from the AI for a request
     * @param Scenario $scenario
     * @param string $feedbackResponseData
     * @return array{openingMessage:string|null,fields:Collection<int,string|null>} Response data, fields are a map of field ID to generated value
     * @throws SchoolboxException
     */
    private function parseResponse(Scenario $scenario, string $feedbackResponseData): array
    {
        $data         = json_decode($feedbackResponseData, true);
        $relevantData = new ResponseParser()->extractRelevantData($data);
        if (!isset($relevantData)) {
            throw new SchoolboxException('Invalid response');
        }

        try {
            /* if this didn't decode correctly, then some weird response came from the AI:
             * send that on... so we can figure out what happened
             */
            $fieldsData = json_decode(
                $relevantData,
                true,
                512,
                JSON_THROW_ON_ERROR,
            );
        } catch (\JsonException $e) {
            throw new SchoolboxException('Invalid response', 0, $e);
        }

        /* Retrieve the output for each field that was requested */
        $resultData = [
            'openingMessage' => $fieldsData['openingMessage'] ?? null,
            'fields' => new Collection(),
        ];

        foreach ($scenario->getFields() as $field) {
            // maybe the AI didn't return stuff for this field... ignore if so
            $body = $fieldsData['fields'][PayloadGenerator::getPayloadFieldKey($field)] ?? null;
            $resultData['fields']->setOffset($field->getId(), $body);
        }

        return $resultData;
    }
}
