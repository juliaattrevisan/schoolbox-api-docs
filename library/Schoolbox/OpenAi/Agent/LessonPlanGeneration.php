declare(strict_types=1);

namespace Schoolbox\OpenAi\Agent;

use Psr\Http\Message\ResponseInterface;
use Schoolbox\Admin\OpenAI\Config;
use Schoolbox\Curriculum\Node\Mapper;
use Schoolbox\Editor\OpenAI\Helper;
use Schoolbox\Editor\OpenAI\Payload\LessonPlan;
use Schoolbox\OpenAi\IClient;
use Schoolbox\User;

/**
 * Agent for generating lesson plans via OpenAI.
 */
class LessonPlanGeneration
{
    /**
     * Constructor
     *
     * @param IClient $client An AI provider client.
     * @param array   $config Configuration for the agent: generated by `\Schoolbox\Admin\OpenAI\Config::decode`.
     */
    public function __construct(
        private IClient $client,
        private array $config,
        private string $spellcheckLanguage,
        private Mapper $curriculumNodeMapper,
    ) {
    }

    /**
     * Request a lesson plan be generated.
     *
     * @param User        $user              The user making the request: will be logged.
     * @param string      $templateTitle     The name of the template which is being used to create the lesson plan.
     * @param string      $lessonPlanTitle   The proposed name for the lesson plan.
     * @param string      $context           Basic context provided for the lesson plan.
     *                                       Seems to be the name of the folder the lesson plan is being created in.
     * @param array<array{
     *     id: int,
     *     title: string,
     *     description: string,
     *     body: string,
     *     template: string,
     *     visibility: string,
     * }>                 $fields            Each field within the lesson plan, and its title and description.
     * @param string      $duration          How long is the lesson plan expected to take?
     *                                       This should be a time-like value.
     * @param array<int>  $curriculumNodeIds List of related nodes to provide context for.
     * @param string      $additionalContext Any additional context provided for the lesson plan.
     * @param string|null $generateForField  If provided: generate context for this field only.
     * @param string|null $aiSessionId       If provided: associate the log with this session ID.
     * @return ResponseInterface
     * @throws \JsonException
     * @throws \Psr\Http\Client\ClientExceptionInterface
     * @throws \Schoolbox\Mapper\Exception
     * @throws \Schoolbox\Mapper\Exception\Deleted
     */
    public function request(
        User $user,
        string $templateTitle,
        string $lessonPlanTitle,
        string $context,
        array $fields,
        string $duration,
        array $curriculumNodeIds,
        string $additionalContext,
        ?string $generateForField,
        ?string $aiSessionId = null
    ): ResponseInterface {
        // Use existing payload generation to create payload:
        // however, it should not json_encode
        $payloadGenerator = new LessonPlan(
            trim($this->config[Config::FIELD_PROVIDER]['value']),
            trim($this->config[Helper::ENDPOINT_TYPE_OPENAI][Config::FIELD_MODEL]['value'] ?? ''),
            trim($this->config[Helper::ENDPOINT_TYPE_AZURE][Config::FIELD_DEPLOYMENT_ID]['value'] ?? ''),
            trim($this->config[Helper::ENDPOINT_TYPE_GENERAL][Config::FIELD_SYSTEM_PROMPT]['value'] ?? ''),
            $this->spellcheckLanguage,
            $this->curriculumNodeMapper,
        );
        $payload = $payloadGenerator->generate(
            $templateTitle,
            $lessonPlanTitle,
            $context,
            $fields,
            $duration,
            $curriculumNodeIds,
            $additionalContext,
            $generateForField,
        );

        return $this->client->createResponse(
            $payload,
            $user,
            Helper::FEATURE_LESSONPLAN,
            $aiSessionId,
        );
    }
}
