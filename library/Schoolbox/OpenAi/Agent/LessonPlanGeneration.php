declare(strict_types=1);

namespace Schoolbox\OpenAi\Agent;

use JsonException;
use Psr\Http\Client\ClientExceptionInterface;
use Schoolbox\Admin\OpenAI\Config;
use Schoolbox\Curriculum\Node\Mapper;
use Schoolbox\Editor\OpenAI\Helper;
use Schoolbox\Editor\OpenAI\Payload\LessonPlan;
use Schoolbox\Mapper\Exception as MapperException;
use Schoolbox\OpenAi\IClient;
use Schoolbox\User;
use Scrub;

/**
 * Agent for generating lesson plans via OpenAI.
 */
class LessonPlanGeneration
{
    /**
     * Constructor
     *
     * @param IClient $client An AI provider client.
     * @param array   $config Configuration for the agent: generated by `\Schoolbox\Admin\OpenAI\Config::decode`.
     */
    public function __construct(
        private IClient $client,
        private array $config,
        private string $spellcheckLanguage,
        private Mapper $curriculumNodeMapper,
    ) {
    }

    /**
     * Request a lesson plan be generated.
     *
     * @param User        $user              The user making the request: will be logged.
     * @param string      $templateTitle     The name of the template which is being used to create the lesson plan.
     * @param string      $lessonPlanTitle   The proposed name for the lesson plan.
     * @param string      $context           Basic context provided for the lesson plan.
     *                                       Seems to be the name of the folder the lesson plan is being created in.
     * @param array<array{
     *     id: int,
     *     title: string,
     *     description: string,
     *     body: string,
     *     template: string,
     *     visibility: string,
     * }>                 $fields            Each field within the lesson plan, and its title and description.
     * @param string      $duration          How long is the lesson plan expected to take?
     *                                       This should be a time-like value.
     * @param array<int>  $curriculumNodeIds List of related nodes to provide context for.
     * @param string      $additionalContext Any additional context provided for the lesson plan.
     * @param string|null $generateForField  If provided: generate context for this field only.
     * @param string|null $aiSessionId       If provided: associate the log with this session ID.
     * @return array{0: array, 1: int} 0: response body, 1: status
     * @throws ClientExceptionInterface
     * @throws MapperException
     */
    public function request(
        User $user,
        string $templateTitle,
        string $lessonPlanTitle,
        string $context,
        array $fields,
        string $duration,
        array $curriculumNodeIds,
        string $additionalContext,
        ?string $generateForField,
        ?string $aiSessionId = null
    ): array {
        $payloadGenerator = new LessonPlan(
            trim($this->config[Config::FIELD_PROVIDER]['value']),
            trim($this->config[Helper::ENDPOINT_TYPE_OPENAI][Config::FIELD_MODEL]['value'] ?? ''),
            trim($this->config[Helper::ENDPOINT_TYPE_AZURE][Config::FIELD_DEPLOYMENT_ID]['value'] ?? ''),
            trim($this->config[Helper::ENDPOINT_TYPE_GENERAL][Config::FIELD_SYSTEM_PROMPT]['value'] ?? ''),
            $this->spellcheckLanguage,
            $this->curriculumNodeMapper,
        );
        $payload = $payloadGenerator->generate(
            $templateTitle,
            $lessonPlanTitle,
            $context,
            $fields,
            $duration,
            $curriculumNodeIds,
            $additionalContext,
            $generateForField,
        );

        // No meaningful input text, so don't send it to the AI.
        $log = $this->client->createLog(
            $payload,
            null,
            $user,
            Helper::FEATURE_LESSONPLAN,
            $aiSessionId,
            null, // These requests can't be restored in the AI Usage Log yet
        );
        $response = $this->client->createResponse($payload, $log);

        // This response used to need special handling of its return, because it
        // was not guaranteed to be valid JSON.
        // That no longer seems to be required, but the original comment was:
        // Send it and decode the result (if any: sometimes it returns null)
        // and dodge around all its weird encoding business with a double-decode,
        // and ditching all its training markdown (lol) that it loves to use
        //
        // https://community.openai.com/t/json-returning-with-json/584818/6
        $data = json_decode($response->getBody()->getContents(), true);

        // Some models may contain reasoning as their first output:
        // need to check each output to see if it actually contains text.
        // (For now, assume there's only one)
        $relevantData = null;
        foreach ($data['output'] ?? [] as $output) {
            if (isset($output['content'])) {
                foreach ($output['content'] as $content) {
                    if (isset($content['text'])) {
                        $relevantData = $content['text'];
                        break 2;
                    }
                }
            }
        }
        if (!isset($relevantData)) {
            return [$data['output'] ?? null, 500];
        }
        try {
            /* if this didn't decode correctly, then some weird response came from the AI:
             * send that on... so we can figure out what happened
             */
            $newFieldData = json_decode(
                $relevantData,
                true,
                512,
                JSON_THROW_ON_ERROR,
            );
        } catch (JsonException $e) {
            return [$data['output'] ?? null, 500];
        }

        /* Since we request the fields to be keyed by their title, not ID for AI reasons,
         * translate it back to IDs for frontend sanity
         */
        $fieldsById = [];
        foreach ($fields as $field) {
            // maybe the AI didn't return stuff for this field... if so, the frontend will handle that.
            $fieldKey = $payloadGenerator->getPayloadFieldKey($fields, $field['id']);
            if (isset($newFieldData[$fieldKey])) {
                $fieldsById[$field['id']] = Scrub::html($newFieldData[$fieldKey]);
            }
        }

        /* if the AI didn't return anything, then we don't want to send an empty field back
         * just send whatever on earth the AI sent back to us, it'll be wrong... but it'll be something
         */
        if (empty($fieldsById)) {
            $fieldsById = $newFieldData;
        }

        return [$fieldsById, 200];
    }
}
