declare(strict_types=1);

namespace Schoolbox\Gotenberg;

use Gotenberg\Modules\Chromium;
use Gotenberg\Modules\PdfEngines;
use Http\Client\HttpClient;
use Psr\Http\Client\ClientExceptionInterface;
use Psr\Http\Message\RequestInterface;
use Psr\Http\Message\ResponseInterface;
use Schoolbox\Realtime\Pipe\PipeManager;

/**
 * Wrapper around Gotenberg's API.
 *
 * This class provides:
 * - factory methods for the Gotenberg API's modules (e.g. Chromium for
 *   converting HTML or URLs to PDF, PDF Engines for merging PDFs)
 * - a send method for actually sending the request objects created by those
 *   modules
 */
class Client
{
    /**
     * The version of the Gotenberg API which is being communicated with.
     */
    private const GOTENBERG_VERSION = 7;

    /**
     * The name of the HTTP header used for authorization of Gotenberg requests.
     *
     * `$this->apiKey` will be set as the value of this header in all requests
     * to the Gotenberg container.
     */
    public const AUTH_HTTP_HEADER = 'SBAuth';

    /**
     * Default wait for Javascript to complete rendering a page retrieved by a
     * URL request generated by this factory.
     *
     * @see https://github.com/gotenberg/gotenberg-php#wait-delay
     */
    public const DEFAULT_WAIT_DELAY = 1;

    /**
     * Default wait for a page retrieved by a URL request generated by this
     * factory to load.
     *
     * @see https://gotenberg.dev/docs/modules/api#timeout-all-routes
     */
    public const DEFAULT_WAIT_TIMEOUT = 30;

    /**
     * Constructor
     *
     * @param HttpClient  $httpClient The HTTP client used for sending requests.
     * @param string      $apiHost    The URL which hosts the Gotenberg API.
     * @param string|null $apiKey     The Gotenberg API key (if required).
     */
    public function __construct(
        private HttpClient $httpClient,
        private string $apiHost,
        private ?string $apiKey,
    ) {
    }

    /**
     * Build an instance of Gotenberg's Chromium-based HTML to PDF converter.
     *
     * @param string|null $sessionHash if provided: a session hash to send along
     *                                 with the request.
     *                                 May contain an authenticated Schoolbox
     *                                 user?
     * @return Chromium
     */
    public function buildHtmlToPdfConverter(?string $sessionHash): Chromium
    {
        $params = [];
        if (isset($sessionHash)) {
            $params['Cookie'] = sprintf('%s=%s', PipeManager::PHP_SESSION_PREFIX, $sessionHash);
        }
        return (new Chromium($this->apiHost))->extraHttpHeaders($params);
    }

    /**
     * Build an instance of Gotenberg's PDF engine, as used for merging two or
     * more pre-generated PDF documents.
     *
     * @return PdfEngines
     */
    public function buildPdfMerger(): PdfEngines
    {
        return (new PdfEngines($this->apiHost));
    }

    /**
     * Send a request created with one of this object's `build*` methods.
     *
     * @param RequestInterface $request
     * @return ResponseInterface
     * @throws ClientExceptionInterface if for some reason it couldn't be sent
     */
    public function send(RequestInterface $request): ResponseInterface
    {
        // Add API version here
        $request = $request->withHeader('x-api-version', self::GOTENBERG_VERSION);

        // Add webhook API key here:
        // I'm not yet sure whether `x-api-key` or the hijacked
        // `Gotenberg-WebhookUrl` header is correct?
        if (isset($this->apiKey)) {
            $request = $request
                ->withHeader('x-api-key', $this->apiKey)
                ->withHeader('Gotenberg-Webhookurl-' . self::AUTH_HTTP_HEADER, $this->apiKey)
            ;
        }
        return $this->httpClient->sendRequest($request);
    }
}
