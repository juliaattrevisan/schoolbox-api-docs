declare(strict_types=1);

namespace Schoolbox\Gotenberg;

use Schoolbox\Realtime\Pipe\PipeManager;
use TheCodingMachine\Gotenberg;

/**
 * Factory for Gotenberg request objects.
 */
class RequestFactory
{
    /**
     * The name of the HTTP header used for authorization of Gotenberg requests.
     *
     * `$this->apiKey` will be set as the value of this header in all requests
     * to the Gotenberg container.
     */
    public const AUTH_HTTP_HEADER = 'SBAuth';

    /**
     * Default wait for Javascript to complete rendering a page retrieved by a
     * URL request generated by this factory.
     *
     * @see https://thecodingmachine.github.io/gotenberg/#html.wait_delay
     */
    public const DEFAULT_WAIT_DELAY = 1;

    /**
     * Default wait for a page retrieved by a URL request generated by this
     * factory to load.
     *
     * @see https://thecodingmachine.github.io/gotenberg/#timeout
     */
    public const DEFAULT_WAIT_TIMEOUT = 30;

    /**
     * Gotenberg API key
     */
    private string $apiKey;

    /**
     * Constructor
     *
     * @param string $apiKey
     */
    public function __construct(string $apiKey)
    {
        $this->apiKey = $apiKey;
    }

    /**
     * Builds a URL request object.
     *
     * @param string      $url         The URL to generate a PDF for.
     * @param float|null  $waitDelay   Wait this many seconds for the URL's JS
     *                                 to execute before generating PDF
     * @param float|null  $waitTimeout Wait this many seconds for the URL's page
     *                                 to load.
     * @param string|null $sessionHash If not null: set this as the session
     *                                 cookie value, thus generating the PDF for
     *                                 the user which is authenticated with this
     *                                 hash.
     *                                 TODO consider switching to user tokens
     *                                 (cannot do this until SA-11077 is done)
     * @return Gotenberg\URLRequest
     */
    public function buildUrlRequest(
        string $url,
        ?float $waitDelay,
        ?float $waitTimeout,
        ?string $sessionHash = null
    ): Gotenberg\URLRequest {
        $request = new Gotenberg\URLRequest($url);
        $request->addWebhookURLHTTPHeader(self::AUTH_HTTP_HEADER, $this->apiKey);
        $request->setWaitDelay($waitDelay);
        $request->setWaitTimeout($waitTimeout);
        if (isset($sessionHash)) {
            $request->addRemoteURLHTTPHeader(
                'Cookie',
                sprintf('%s=%s', PipeManager::PHP_SESSION_PREFIX, $sessionHash)
            );
        }
        return $request;
    }
}
