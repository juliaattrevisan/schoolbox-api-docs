namespace Schoolbox\Assessment\Course\Import;

use Schoolbox\GenericCollection;
use Schoolbox\Learning\Assessment\IAssessable;
use Schoolbox\Learning\Assessment\Project;
use Schoolbox\Learning\AssessmentContext;
use Schoolbox\Learning\Course\DataModel\Implementation\Unit\Model as UnitImplementation;
use Alaress_Date_Format;

/**
 * Provides a consistent interface to transfer import data from DB all the way to twig.
 *
 * Objects of this class should be immutable after initial construction.
 */
class DataTransferObject
{

    /**
     * Is this an import modification (rather than new import) ?
     *
     * This determines the logic for assigning suggested assessment dates
     *
     * @var bool
     */
    private $isImportModify;

    /**
     * All UnitImpls must link to their UnitSpec.
     * If the UnitImpl does not yet exist, its ID will be null.
     *
     * @var UnitImplementation[]|GenericCollection<UnitImplementation>
     */
    private $unitImplementations;

    /**
     * A Collection of IAssessable pairs, each Collection indexed by UnitSpec.id
     *
     * Only contains top-level (ie in unit) assessments. Top-level assessments may be projects that contain sub-assessments.
     *
     * Each pair may contain:
     * 1. Just an AssessmentSpec               => UnitSpec not imported, or AssessmentSpec not imported, or Impl deleted.
     * 2. Both AssessmentSpec + AssessmentImpl => UnitSpec imported and AssessmentSpec imported. Spec may be deleted.
     * 3. Just an AssessmentImpl               => Assessment was created directly in UnitImpl. Impl cannot be deleted.
     *
     * @var IAssessable[][][]|AssessmentPair[][] $unitSpecAssessments
     * @var IAssessable|null                     $unitSpecAssessments [unitSpec.id][]['spec']
     * @var IAssessable|null                     $unitSpecAssessments [unitSpec.id][]['impl']
     */
    private $unitSpecAssessments;

    /**
     * Maps AssessmentImpl IDs to AssessmentSpecs ID.
     *
     * AssessmentSpec ID will be null if AssessmentImpl was created directly in UnitImpl
     *
     * @var int[]
     */
    private $assessmentImplToSpecMap;


    /**
     * Maps the IDs AssessmentSpecs to ID of an AssessmentImpl
     *
     * We need this for efficient O(1) lookup.
     *
     * Only contains those specs that have been implemented.
     *
     * @var int[]
     */
    private $assessmentSpecToImplMap;

    /**
     * Number of Assessments available for selection per UnitSpec, indexed by UnitSpec.id
     *
     * @var int[]
     */
    private $availableAssessmentCounts;

    /**
     * Number of Assessments selection per UnitSpec, indexed by UnitSpec.id
     *
     * @var int[]
     */
    private $selectedAssessmentCounts;

    /**
     * @var string|null
     */
    private $defaultDueTime;

    /**
     * Accepts and validates all data generated by factory, builds internal data structures
     *
     * @param bool                                 $isImportModify
     * @param int[]|null[]                         $assessmentImplToSpecMap Maps extant Impl Ids to Spec Id (null if Impl created in UnitImpl)
     * @param UnitImplementation|GenericCollection $unitImpls
     * @param IAssessable|GenericCollection        $assessmentSpecs         Grouped by UnitSpecId
     * @param IAssessable|GenericCollection        $assessmentImpls         Grouped by UnitSpecId
     * @param AssessmentPair[]|GenericCollection   $assessmentPairs         Grouped by UnitSpecId
     * @param string|null                          $defaultDueTime          Adjust due date time to this, if set in H:i format
     * @throws \DomainException If an invalid assessment context is encountered, or invalid data detected.
     */
    public function __construct(
        bool $isImportModify,
        array $assessmentImplToSpecMap,
        GenericCollection $unitImpls,
        GenericCollection $assessmentSpecs,
        GenericCollection $assessmentImpls,
        GenericCollection $assessmentPairs,
        ?string $defaultDueTime
    ) {
        $this->isImportModify          = $isImportModify;
        $this->defaultDueTime          = $defaultDueTime;
        $this->assessmentImplToSpecMap = $assessmentImplToSpecMap;
        $this->unitImplementations     = new GenericCollection(UnitImplementation::class);
        $this->unitSpecAssessments     = new GenericCollection(GenericCollection::class);

        // Suppress warnings. We expect some values may be null. That's cool, we don't need 'em.
        $this->assessmentSpecToImplMap = @array_flip($assessmentImplToSpecMap);

        // Start Building
        $this->addUnitImplementations($unitImpls);

        // Convert all to AssessmentPairs
        $this->addAssessmentSpecs($assessmentSpecs);
        $this->addAssessmentImpls($assessmentImpls);
        $this->addAssessmentPairs($assessmentPairs);

        // Sort Assessment Pairs for Display
        $this->sortAssessmentPairsDriver();

        // Add Suggested Dates to Assessment Specs
        $this->addAssessmentSpecDatesDriver();

        // Calculate totals for display
        $this->calculateAvailableAssessmentCounts();
        $this->calculateSelectedAssessmentCounts();
    }


    /**
     * Recursive driver to sort Assessment Pairs.
     */
    private function sortAssessmentPairsDriver()
    {
        foreach ($this->unitSpecAssessments as $unitSpecId => $assessmentPairs) {
            $this->sortAssessmentPairsRecursive($assessmentPairs);
        }
    }


    /**
     * Recursively sort Assessment Pairs.
     *
     * Sorts by:
     * * AssessmentImpl.sequence, then
     * * AssessmentSpec.sequence
     *
     * @param GenericCollection|AssessmentPair[] $assessmentPairs
     */
    private function sortAssessmentPairsRecursive(GenericCollection $assessmentPairs)
    {
        // Base Case
        $assessmentPairs->sortByCallback($this->getSortForDisplayCallback());

        // Recursive Case
        foreach ($assessmentPairs as $assessmentPair) {
            $this->sortAssessmentPairsRecursive($assessmentPair->getSubPairs());
        }
    }


    /**
     * Get a Callback for sorting AssessmentPairs for date assignment
     *
     * @return \Closure
     */
    private function getSortForDateAssignmentCallback()
    {
        return function (AssessmentPair $leftPair, AssessmentPair $rightPair) {
            $leftImpl  = $leftPair->getImplementation();
            $leftSpec  = $leftPair->getSpecification();
            $rightImpl = $rightPair->getImplementation();
            $rightSpec = $rightPair->getSpecification();

            // Both implemented ?
            if ($leftImpl && $rightImpl) {
                $rightSeq = $rightImpl->getSequence();
                $leftSeq  = $leftImpl->getSequence();
                if ($leftSeq > $rightSeq) {
                    return 1;
                }
                return  $leftSeq < $rightSeq ? -1 : 0;
            }
            // Just the left?
            if ($leftImpl) {
                return -1;
            }
            // Just the right?
            if ($rightImpl) {
                return 1;
            }
            // Neither
            $rightSeq = $rightSpec->getSequence();
            $leftSeq  = $leftSpec->getSequence();
            if ($leftSeq > $rightSeq) {
                return 1;
            }
            return $leftSeq < $rightSeq ? -1 : 0;
        };
    }


    /**
     * Get a callback to sort AssessmentPairs for display
     *
     * @return \Closure
     */
    private function getSortForDisplayCallback()
    {
        /* For now, both sorting is the same. But we could alter the display
         * sorting by inserting a new sort function here.
         */
        return $this->getSortForDateAssignmentCallback();
    }


    /**
     * Applies suggested dates to AssessmentSpecs.
     *
     * Recursive driver
     *
     * @throws \DomainException If an invalid assessment context is passed
     */
    private function addAssessmentSpecDatesDriver()
    {

        foreach ($this->unitSpecAssessments as $unitSpecId => $assessmentPairs) {
            $unitImpl = $this->unitImplementations[$unitSpecId];

            /* $nextAvailable time is always set to 00:00:00
             * eg, openSpan = 1 day, $nextAvailable = 20/12/2010 00:00:00 => 21/12/2010 00:00:00
             * for end dates, we clone and minus 1 second to ensure end date is 20/12/2010 23:59:59
             */
            $nextAvailable = clone $unitImpl->getOpenDate();
            $nextAvailable = $nextAvailable->startOfDay();

            $unitClose = $unitImpl->getDueDate();
            $this->addAssessmentSpecDatesRecursive($unitImpl, $assessmentPairs, $nextAvailable, $unitClose);
        }
    }


    /**
     * Depth-first (cf. level-first) recursive function to add suggested dates to AssessmentPairs in the specified context.
     *
     * If a UnitImpl's Assessments's are partially imported (ie. this is an import-modify), then un-imported Assessments are scheduled from
     * the start till end of the UnitImpl - regardless of default open span.
     *
     * If a Project's Assessments are partially imported, then un-imported Assessments are scheduled from
     * the open to due dates of the Project - regardless of default open span.
     *
     * @param AssessmentContext|UnitImplementation|Project $context
     * @param AssessmentPair[]|GenericCollection           $assessmentPairs - Already sorted by assessment.sequence
     * @param Alaress_Date_Format                          $unitClose       - Cannot assign dates past this point
     * @param Alaress_Date_Format                          $nextAvailable   - Next available date to assign to specs (time always 00:00:00)
     * @throws \DomainException If an assessmentSpec's context is unrecognised
     */
    private function addAssessmentSpecDatesRecursive(
        AssessmentContext $context,
        GenericCollection $assessmentPairs,
        Alaress_Date_Format $nextAvailable,
        Alaress_Date_Format $unitClose
    ) {
        if ($this->isImportModify) {
            // Don't bother sorting if an import-modify
            $sortedPairs = $assessmentPairs;
        } else {
            /* Shallow clone collection of pairs to cater for case if display sorting
             * differs from date-assignment sorting.
             * Use the clone for assigning dates, then throw away. Original collection retains its sorting.
             */
            $sortedPairs = clone $assessmentPairs;
            $sortedPairs->sortByCallback($this->getSortForDateAssignmentCallback());
        }


        foreach ($sortedPairs as $pair) {
            // Is this a new-import?
            if (!$this->isImportModify) {
                /* New-Import:
                 * * All pairs are spec-only. We can ignore impls.
                 * * Respect AssessmentSpec.defaultOpenSpans
                 * * Respect $nextAvailable date concept
                 */
                $spec = $pair->getSpecification();

                $start = clone $nextAvailable;

                // Base case: non-project
                if (!$spec instanceof Project) {
                    $openSpan = $spec->getDefaultOpenSpan();
                } // Recursive case: Project
                else {
                    // Does any assessment inside this project have a null open_span?
                    $openSpan = $this->recursiveGetDefaultOpenSpan($spec);
                }

                // Does it not have a open span?
                if (null === $openSpan) {
                    $end = $unitClose;
                } // Else it does have an open span
                else {
                    $tempEnd = clone $nextAvailable;
                    $tempEnd->addDays($openSpan);
                    $tempEnd->addSeconds(-1);

                    // Would this open_span extend past the end of the unit?
                    if (1 === $tempEnd->compareDateOnly($unitClose)) {
                        // Set both next available and assessment end to last day of unit
                        $nextAvailable = clone $unitClose;
                        $nextAvailable = $nextAvailable->startOfDay();
                        $end           = $unitClose;
                    } // Else assessment ends before end of unit
                    else {
                        // Increment next and set assessment end
                        $nextAvailable->addDays($spec->getDefaultOpenSpan());
                        $end = $tempEnd;
                    }
                }

                $spec->setPublishAt($start);
                $spec->setOpenAt($start);
                // generate default due date from unit close date
                $due = clone $end;
                $due->endOfDay();
                $spec->setDueAt($due->setTimeFromString($this->defaultDueTime));
                $spec->setCloseAt($end);
            } // Else this is an import-modify.
            else {
                /* Import-modify:
                 * * Pairs may be spec-only, impl-only, or pair
                 * * Ignore AssessmentSpec.defaultOpenSpans
                 * * Ignore $nextAvailable date concept
                 */

                // If impl only, we can ignore (even if project). It already has dates explicitly set.
                if ($pair->isImplOnly()) {
                    continue;
                }

                /* Regardless if spec-only or pair, assign dates to the spec.
                 * If a pair, they will be ignored later in preference to the impl dates.
                 */
                $spec = $pair->getSpecification();

                // Ignore $nextAvailable, and simply take parent dates.
                if ($context instanceof UnitImplementation) {
                    $spec->setPublishAt($context->getOpenDate());
                    $spec->setOpenAt($context->getOpenDate());
                    // generate default due date from context due date
                    $due = clone $context->getDueDate();
                    $due->endOfDay();
                    $spec->setDueAt($due->setTimeFromString($this->defaultDueTime));
                    $spec->setCloseAt($context->getDueDate());
                } elseif ($context instanceof Project) {
                    $spec->setPublishAt($context->getPublishAt());
                    $spec->setOpenAt($context->getOpenAt());
                    // generate default due date from context due date
                    $due = clone $context->getDueAt();
                    $due->endOfDay();
                    $spec->setDueAt($due->setTimeFromString($this->defaultDueTime));
                    $spec->setCloseAt($context->getCloseAt());
                } else {
                    throw new \DomainException('Unknown assessment context: ' . get_class($context));
                }
            }

            // Recursive Case: Project Spec (we can ignore impl-only - they already have dates)
            $spec = $pair->getSpecification();
            if ($spec && $spec instanceof Project) {
                $nextAvailable = clone $spec->getOpenAt();
                $nextAvailable = $nextAvailable->startOfDay();
                /* @var Project $impl */
                $impl          = $pair->getImplementation();
                // Prefer Impl if it's available
                $subContext = $impl ?: $spec;
                $this->addAssessmentSpecDatesRecursive($subContext, $pair->getSubPairs(), $nextAvailable, $unitClose);
            }
        }
    }


    /**
     * Recursively examine a Project spec.
     *
     * If any sub-assessments have a null open_span, return null.
     * Otherwise return the sum of all sub-assessment open_spans
     *
     * @param Project $projectSpec
     * @return null|int
     */
    private function recursiveGetDefaultOpenSpan(Project $projectSpec)
    {
        /* Empty projects don't have any sub-assessment open_spans
         *
         * An open span is known as the Activity Duration in the frontend, so I guess this is supposed
         * to elucidate or infer an ending date as an offset from its start.
         *
         * If you don't have any open_spans, it means you don't have any activities inside this project
         * from which you can infer an ending date, so just use the unit date instead.
         */
        if (!$projectSpec->getAssessables()->count()) {
            return null;
        }

        $totalOpenSpan = 0;
        foreach ($projectSpec->getAssessables() as $subAssessment) {
            // Base Case: non-project
            if (!$subAssessment instanceof Project) {
                if (null === $subAssessment->getDefaultOpenSpan()) {
                    return null;
                }
                $totalOpenSpan += $subAssessment->getDefaultOpenSpan();
            } // Recursive Case: project
            else {
                $openSpan = $this->recursiveGetDefaultOpenSpan($subAssessment);
                if (null === $openSpan) {
                    return null;
                }
                $totalOpenSpan += $openSpan;
            }
        }
        return $totalOpenSpan;
    }


    /**
     * Call from TWIG to get a list of UnitImpls to traverse
     *
     * @return UnitImplementation[]|GenericCollection<UnitImplementation>
     */
    public function getUnitImplementations()
    {
        return $this->unitImplementations;
    }


    /**
     * Call from TWIG to get sets of IAssessable pairs, grouped by UnitSpec
     *
     * Outer set indexed by UnitSpec.id
     * Inner set unordered
     *
     * @return IAssessable[][][]|AssessmentPair[][]|GenericCollection[]|GenericCollection Sets of sets of IAssessable pairs
     */
    public function getAssessmentPairs()
    {
        return $this->unitSpecAssessments;
    }


    /**
     * Call from TWIG to get counts of IAssessable pairs, grouped by UnitSpec
     *
     * @return int[]
     */
    public function getAvailableAssessmentCounts()
    {
        return $this->availableAssessmentCounts;
    }


    /**
     * Call from TWIG to get counts of selected Assessments, grouped by UnitSpec
     *
     * @return int[]
     */
    public function getSelectedAssessmentCounts()
    {
        return $this->selectedAssessmentCounts;
    }


    /**
     * @param GenericCollection $unitImpls
     */
    private function addUnitImplementations(GenericCollection $unitImpls)
    {
        foreach ($unitImpls as $unitImpl) {
            $this->addUnitImplementation($unitImpl);
        }
    }


    /**
     * Verify and add AssessmentSpecs that have no corresponding AssessmentImpl
     *
     * @param GenericCollection|GenericCollection[]|IAssessable[][] $assessmentSpecs
     * @throws \DomainException If logic error detected when adding pairs
     */
    private function addAssessmentSpecs(GenericCollection $assessmentSpecs)
    {
        foreach ($assessmentSpecs as $unitSpecId => $unitSpecAssessmentSpecs) {
            foreach ($unitSpecAssessmentSpecs as $assessmentSpec) {
                $this->addAssessmentSpec($unitSpecId, $assessmentSpec);
            }
        }
    }


    /**
     * Verify and add AssessmentImpls that have no corresponding AssessmentSpec
     *
     * @param GenericCollection|GenericCollection[]|IAssessable[][] $assessmentImpls
     * @throws \DomainException If logic error detected when adding pairs
     */
    private function addAssessmentImpls(GenericCollection $assessmentImpls)
    {
        foreach ($assessmentImpls as $unitSpecId => $unitSpecAssessmentImpls) {
            foreach ($unitSpecAssessmentImpls as $assessmentImpl) {
                $this->addAssessmentImpl($unitSpecId, $assessmentImpl);
            }
        }
    }


    /**
     * Verify and add pairs of AssessmentSpecs + AssessmentImpls
     *
     * @param GenericCollection|GenericCollection[]|AssessmentPair[][] $assessmentPairs
     * @throws \DomainException If logic error detected when adding pairs
     */
    private function addAssessmentPairs(GenericCollection $assessmentPairs)
    {
        foreach ($assessmentPairs as $unitSpecId => $unitSpecAssessmentPairs) {
            foreach ($unitSpecAssessmentPairs as $assessmentPair) {
                $this->addAssessmentPair($unitSpecId, $assessmentPair);
            }
        }
    }


    /**
     * Calculate how many Assessments are available for selection for each UnitSpec
     *
     * @return bool
     */
    private function calculateAvailableAssessmentCounts()
    {
        $this->availableAssessmentCounts = [];

        /** @var AssessmentPair[] $assessmentPairs */
        foreach ($this->unitSpecAssessments as $unitSpecId => $assessmentPairs) {
            $count = 0;
            foreach ($assessmentPairs as $assessmentPair) {
                $count += $assessmentPair->getAssessmentCount();
            }
            $this->availableAssessmentCounts[$unitSpecId] = $count;
        }
        return true;
    }


    /**
     * Calculate how many Assessments are selected for each UnitSpec
     *
     * Assessments are selected if:
     * * UnitImpl not exists (ie a new unit import), or
     * * AssessmentImpl exists (ie assessment already imported)
     *
     * @return bool
     */
    private function calculateSelectedAssessmentCounts()
    {
        $this->selectedAssessmentCounts = [];

        /** @var AssessmentPair[] $assessmentPairs */
        foreach ($this->unitSpecAssessments as $unitSpecId => $assessmentPairs) {
            // Is this a fresh unit import?
            if (!$this->unitImplementations[$unitSpecId]->getId()) {
                $this->selectedAssessmentCounts[$unitSpecId] = $this->availableAssessmentCounts[$unitSpecId];
            } // Else modification of existing unit import.
            else {
                $count = 0;
                foreach ($assessmentPairs as $assessmentPair) {
                    $count += $assessmentPair->getAssessmentImplCount();
                }
                $this->selectedAssessmentCounts[$unitSpecId] = $count;
            }
        }
        return true;
    }


    /**
     * @param UnitImplementation $unitImpl
     * @return bool Whether it was added. False if already existed.
     * @throws \UnexpectedValueException
     */
    private function addUnitImplementation(UnitImplementation $unitImpl)
    {
        $unitSpecId = $unitImpl->getSpecification()->getId();
        if ($this->unitImplementations->getOffset($unitSpecId) instanceof UnitImplementation) {
            return false;
        }
        $this->unitImplementations->setOffset($unitSpecId, $unitImpl);
        return true;
    }


    /**
     * Adds an AssessmentSpec that has no non-deleted AssessmentImpl
     *
     * @param int         $unitSpecId
     * @param IAssessable $assessmentSpec
     * @param bool        $isNested
     * @return AssessmentPair
     * @throws \DomainException If attempting to register a spec with an impl as a spec only
     * @throws \UnexpectedValueException
     */
    private function addAssessmentSpec($unitSpecId, IAssessable $assessmentSpec, $isNested = false)
    {
        // Ensure this AssessmentSpec is being added correctly
        if (array_key_exists($assessmentSpec->getId(), $this->assessmentSpecToImplMap)) {
            throw new \DomainException(
                sprintf(
                    'Unable to import assessment #%d, as it has already been imported',
                    $assessmentSpec->getId()
                )
            );
        }
        $this->checkUnitSpecCollection($unitSpecId);

        // Recurse
        $subPairs = null;
        if ($assessmentSpec instanceof Project) {
            $subPairs = new GenericCollection(AssessmentPair::class);
            foreach ($assessmentSpec->getAssessables() as $assessable) {
                $subPairs->add($this->addAssessmentSpec($unitSpecId, $assessable, true));
            }
        }
        $pair = new AssessmentPair($assessmentSpec, null, $subPairs);
        if (!$isNested) {
            $this->unitSpecAssessments->getOffset($unitSpecId)->add($pair);
        }
        return $pair;
    }


    /**
     * Adds an AssessmentImpl that was created directly in UnitImpl
     *
     * @param int         $unitSpecId
     * @param IAssessable $assessmentImpl
     * @param bool        $isNested
     * @return AssessmentPair
     * @throws \DomainException If attempting to register a impl with a spec as an impl-only
     */
    private function addAssessmentImpl($unitSpecId, IAssessable $assessmentImpl, $isNested = false)
    {
        $implId = $assessmentImpl->getId();
        // Ensure this AssessmentImpl does not have a Spec
        if (array_key_exists($implId, $this->assessmentImplToSpecMap) && null !== $this->assessmentImplToSpecMap[$implId]) {
            throw new \DomainException(
                sprintf(
                    'Unable to save implementation-only assessment #%d, as it has a specification',
                    $assessmentImpl->getId()
                )
            );
        }
        $this->checkUnitSpecCollection($unitSpecId);

        // Recurse
        $subPairs = null;
        if ($assessmentImpl instanceof Project) {
            $subPairs = new GenericCollection(AssessmentPair::class);
            foreach ($assessmentImpl->getAssessables() as $assessable) {
                $subPairs->add($this->addAssessmentImpl($unitSpecId, $assessable, true));
            }
        }
        $pair = new AssessmentPair(null, $assessmentImpl, $subPairs);
        if (!$isNested) {
            $this->unitSpecAssessments->getOffset($unitSpecId)->add($pair);
        }

        return $pair;
    }


    /**
     * Adds matching pair AssessmentSpec and AssessmentImpl
     *
     * @param int            $unitSpecId
     * @param AssessmentPair $pair
     * @param bool           $isNested
     * @return AssessmentPair
     * @throws \DomainException If attempting to register a pair without a valid spec and impl
     * @throws \UnexpectedValueException
     */
    private function addAssessmentPair($unitSpecId, AssessmentPair $pair, $isNested = false)
    {
        $assessmentImpl = $pair->getImplementation();
        $assessmentSpec = $pair->getSpecification();

        // Ensure these Assessments are a valid pair
        if ($this->assessmentImplToSpecMap[$assessmentImpl->getId()] !== $assessmentSpec->getId()) {
            $specId = $assessmentSpec->getId();
            $implId = $assessmentImpl->getId();
            throw new \DomainException("Assessments not a valid pair: Spec: $specId, Impl: $implId");
        }
        $this->checkUnitSpecCollection($unitSpecId);

        // Recurse
        $subPairs = null;
        if ($assessmentImpl instanceof Project) {
            /**
             * Index by assessment.id. (spec.id if spec exists, otherwise impl.id)
             */
            $subPairs = new GenericCollection(AssessmentPair::class);
            foreach ($assessmentImpl->getAssessables() as $impl) {
                $spec = $impl->getSpecificationAssessment();
                if ($spec) {
                    $subPair = new AssessmentPair($spec, $impl);
                    $subPairs->setOffset($spec->getId(), $this->addAssessmentPair($unitSpecId, $subPair, true));
                } else {
                    $subPairs->setOffset($impl->getId(), $this->addAssessmentImpl($unitSpecId, $impl, true));
                }
            }

            foreach ($assessmentSpec->getAssessables() as $spec) {
                // Have we already added this spec as part of a pair?
                if ($subPairs->offsetExists($spec->getId())) {
                    continue;
                }
                $subPairs->setOffset($spec->getId(), $this->addAssessmentSpec($unitSpecId, $spec, true));
            }
        }
        $pair = new AssessmentPair($assessmentSpec, $assessmentImpl, $subPairs);
        if (!$isNested) {
            $this->unitSpecAssessments->getOffset($unitSpecId)->add($pair);
        }
        return $pair;
    }


    /**
     * Ensures an AssessmentPair collection exists for the specified UnitSpec
     *
     * @param int $unitSpecId
     * @return bool
     * @throws \UnexpectedValueException
     */
    private function checkUnitSpecCollection($unitSpecId)
    {
        // Ensure AssessmentPair collection exists for this UnitSpec
        if (!$this->unitSpecAssessments->getOffset($unitSpecId) instanceof GenericCollection) {
            $this->unitSpecAssessments->setOffset($unitSpecId, new GenericCollection(AssessmentPair::class));
            return true;
        }
        return false;
    }
}
