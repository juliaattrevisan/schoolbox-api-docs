namespace Schoolbox\Assessment\Component\OnlineAssessment;


use Alaress\Async\Notification\Instance\Builder;
use Alaress\Async\Notification\Parameter\Param;
use Monolog\Logger;
use Schoolbox\Assessment\Component\OnlineAssessment;
use Schoolbox\Assessment\Component\OnlineAssessmentMapper;
use Schoolbox\Mapper;
use Schoolbox\Realtime\Message\NSMapper;
use Schoolbox\Realtime\Notification\Envelope;
use Schoolbox\Realtime\Notification\Parameter\CategoryParam;
use Schoolbox\Realtime\Notification\Parameter\UserParam;
use Schoolbox\Realtime\Schedule\Module\AbstractModuleNotifier;
use Schoolbox\Realtime\Schedule\Trigger\TriggerBundleInterface;
use Schoolbox\Resource\CategoryMapper;
use Schoolbox\User;

class AttemptNotifier extends AbstractModuleNotifier {

	const TRIGGER_ATTEMPTED = 'attempted';
	const TRIGGER_MARKED    = 'marked';

	/** @var OnlineAssessmentMapper */
	protected $assessMapper;

    /** @var CategoryMapper */
    protected $categoryMapper;

	/**
	 * @param array $dependencies
	 */
	public function loadDependencies($dependencies = null) {
		if(empty($dependencies['assessMapper'])) {
			$dependencies['assessMapper'] = OnlineAssessmentMapper::getInstance();
		}
        if (empty($dependencies['categoryMapper'])) {
            $dependencies['categoryMapper'] = CategoryMapper::getInstance();
        }
		parent::loadDependencies($dependencies); // TODO: Change the autogenerated stub
	}


	/**
	 * @param Mapper $mapper
	 */
	protected function setAssessMapper($mapper) {
		$this->assessMapper = $mapper;
	}


    /**
     * @param CategoryMapper $categoryMapper
     * @return self
     */
    protected function setCategoryMapper($categoryMapper)
    {
        $this->categoryMapper = $categoryMapper;
        return $this;
    }




	/**
	 * @return string
	 */
	protected function getSlug() {
		return NSMapper::NS_ONLINE_ASSESS;
	}


    /**
     * @param TriggerBundleInterface $bundle
     * @return void
     */
    public function bundleTriggers($bundle) {
        if ($bundle->getMethod() == Mapper::METHOD_UPDATE) {
            if (array_key_exists('finish', $bundle->getEvent()->getDiff())) {
                $bundle->attach(self::TRIGGER_ATTEMPTED, self::IMMEDIATELY);

            } else {
                $bundle->attach(self::TRIGGER_MARKED, self::IMMEDIATELY);
            }
        }
    }


	/* ASYNC */

	/**
	 * @param Attempt $attempt
	 * @param User $student
	 * @return Envelope
	 */
	public function notifyStaffAttempted($attempt, $student) {
		$envelope = new Envelope();
		$bob = new Builder();

		$assessId = $attempt->getAssessment()->getId();
		/** @var OnlineAssessment $assess */
		$assess   = $this->assessMapper->findById($assessId);
        $category = $this->categoryMapper->findById($assess->getCategory()->getId());

		$href = "/assess/results/".$attempt->getAssessment()->getId();

		$bob->setTitle(':student attempted :quiz in :category')
			->setParams(array(
				'student'  => new UserParam($student),
				'quiz'     => new Param($assess->getTitle(), $href),
				'category' => new CategoryParam($category)
			))
			->setNamespace($this->getSlug())
			->setSeverity(Logger::NOTICE)
			->setIcon("/portrait?size={$this->iconSize}&userId=".$student->getExternalId())
			->setHref($href)
			->addTopic("assess.$assessId.attempted");

		$envelope->targetToUser($assess->getUser(), $bob->build());

		return $envelope;
	}


	/**
	 * @param Attempt $attempt
	 * @param User    $teacher
	 * @param array   $diff
	 * @return Envelope
	 */
	public function notifyStudentMarked($attempt, $teacher, $diff = null) {
		$envelope = new Envelope();
		$bob = new Builder();

		$assessId = $attempt->getAssessment()->getId();
		/** @var OnlineAssessment $assess */
		$assess   = $this->assessMapper->findById($assessId);
        $category = $this->categoryMapper->findById($assess->getCategory()->getId());

		$studentId = $attempt->getUser()->getId();

		$href = "/assess/attempts/$assessId/$studentId";

		$bob->setSeverity(Logger::NOTICE)
			->setNamespace($this->getSlug())
			->setHref($href)
			->setIcon("/portrait?size={$this->iconSize}&userId=".$teacher->getExternalId())
			->setTitle(":staff has marked your attempt of :quiz in :cat")
			->setParams(array(
				'staff' => new UserParam($teacher),
				'quiz'  => new Param($assess->getTitle(), $href),
				'cat'   => new CategoryParam($category)
			))
			->addTopic("assess.$assessId.marked");

		$envelope->targetToUser($attempt->getUser(), $bob->build());

		return $envelope;
	}


	/**
	 * @param Attempt $attempt
	 * @param User    $teacher
	 * @param array   $diff
	 * @return Envelope
	 */
	public function notifyParentMarked($attempt, $teacher, $diff = null) {
		$envelope = new Envelope();

		if($this->conf->get('restrict_parent_duework_access')) {
			return $envelope;
		}

		$assessId = $attempt->getAssessment()->getId();
		/** @var OnlineAssessment $assess */
		$assess   = $this->assessMapper->findById($assessId);
        $category = $this->categoryMapper->findById($assess->getCategory()->getId());

		$studentId = $attempt->getUser()->getId();

		$href = "/assess/attempts/$assessId/$studentId";

		$bob = new Builder();
		$bob->setSeverity(Logger::NOTICE)
		    ->setNamespace($this->getSlug())
		    ->setHref($href)
		    ->setIcon("/portrait?size={$this->iconSize}&userId=".$teacher->getExternalId())
		    ->setTitle(":staff has marked :child's attempt of :quiz in :cat")
		    ->setParams(array(
			    'staff' => new UserParam($teacher),
			    'child' => new UserParam($attempt->getUser(), Param::STACKING_REPLACE, '{firstname}'),
			    'quiz'  => new Param($assess->getTitle(), $href),
			    'cat'   => new CategoryParam($category)
		    ))
		    ->addTopic("assess.$assessId.marked");

		$envelope->targetToParent($attempt->getUser(), $bob->build());

		return $envelope;
	}

}