    /**
     * @throws \GuzzleHttp\Exception\InvalidArgumentException
     */
    public function __construct()
    {
        $this->client = $this->initClient(self::DEFAULT_TIMEOUT);
    }


    /**
     * Set up guzzle client
     *
     * @param int $timeout
     * @return Client
     * @throws \GuzzleHttp\Exception\InvalidArgumentException
     */
    private function initClient(int $timeout): Client
    {
        $headers = [
            'Content-Type' => 'application/json'
        ];

        return new Client([
            'headers' => $headers,
            'base_uri' => self::HOST,
            'timeout' => $timeout,
            'http_errors' => false,
        ]);
    }


    /**
     * @param string $endpoint
     * @return array
     * @throws \DomainException
     * @throws \RuntimeException
     */
    private function retrieve(string $endpoint): array
    {
        $method   = 'GET';
        $response = null;

        /* Mine out an error message if you try to access a thing that doesn't exist
         */
        $fails = 0;

        /* Try multiple times in case sis dies for a random reason
         */
        while ($fails < self::NUM_RETRY) {
            /* Any exception thrown by guzzle might as well be a reason to nap and retry
             */
            try {
                $response = $this->client->request($method, $endpoint);

                /* Debugging:
                 * Find out what guzzle calculated as the endpoint + query string params
                 */
//                $options['on_stats'] = function (TransferStats $stats) use (&$url) {
//                    $url = $stats->getEffectiveUri();
//                };
            } catch (\GuzzleHttp\Exception\GuzzleException $e) {
                $fails++;

                sleep(self::NAP_TIMEOUT);

                continue;
            }

            /* Successful response from server, but it might not send a valid data payload back
             * so try to decode it. If it can't decode properly, return null
             */
            if ($response->getStatusCode() === 200) {
                try {
                    $content = $response->getBody()->getContents();

                    if ('' === $content) {
                        return [];
                    }

                    return json_decode($content, true, 512, JSON_THROW_ON_ERROR);
                } catch (\JsonException $e) {
                    /* Couldn't decode json, or server refused something, or something else died
                     * noop; just increase the $fails counter
                     */
                }
            }

            $fails++;
        }

        /* We tried multiple times and failed multiple times
         * This might as well have died
         */
        if ($response) {
            throw new \RuntimeException(
                sprintf(
                    'Bad endpoint %s: %s %s after %s retries.',
                    $method,
                    $response->getStatusCode(),
                    $response->getReasonPhrase(),
                    self::NUM_RETRY,
                ),
                $response->getStatusCode(),
                $e ?? null
            );
        }

        /* Couldn't decode json, or server refused something, or something else died
         * Guzzle repeatedly failed too many times and kept throwing exceptions when $response
         * was being requested, so I guess you ended up here
         */
        throw new \DomainException('Could not access server, or bad json payload returned.', 0, $e ?? null);
    }


    /**
     * Collate the WA curriculum csv from the json source files
     *
     * @return void
     * @throws \DomainException
     * @throws \RuntimeException
     */
    private function build(): void
    {
        $curriculumRootNode = 1;
        $sharedLearningAreaId = null;

        /* Presumed hierarchy
         * WA Curriculum > learning area > subject > level > strand > substrand + metadata
         */
        $learningAreaId = 2;

        $this->csvPayload[] = [
            'id' => $curriculumRootNode,
            'curriculum_node_parent_id' => '',
            'name' => 'Western Australia Curriculum',
            'code' => '',
            'order' => 0,
            'description' => ''
        ];

        /* Increment arbitrary node counter every time a node spawns
         */
        $this->i++;

        foreach (self::MANIFEST as $url => $struct) {
            $learningArea = $this->retrieve($url);

            $learningAreaRow = [
                'id' => $learningAreaId,
                'curriculum_node_parent_id' => $curriculumRootNode,
                'name' => $learningArea['title'],
                'code' => '',
                'order' => 0,
                'description' => ''
            ];

            /* When we start processing languages,
             * Put all their nodes under a common node that hasn't yet existed
             *
             * SEQUENTIAL DEPENDENCY FOLLOWS
             */
            if ($struct['learningArea'] && !$sharedLearningAreaId) {
                $learningAreaRow['id']    = $learningAreaId;
                $learningAreaRow['name'] = 'Languages';
            }

            /* Reuse this crazy if it was ever defined
             */
            if (!$sharedLearningAreaId) {
                /* Build hierarchy
                 * id,curriculum_node_parent_id,name,code,order,description
                 */
                $this->csvPayload[] = $learningAreaRow;

                /* Increment arbitrary node counter every time a node spawns
                 */
                $this->i++;
            }

            /* Recycle this identifier down the hierarchy
             */
            if ($struct['learningArea'] && !$sharedLearningAreaId) {
                $sharedLearningAreaId = $learningAreaId;
            }

            /* English/HPE/HSS skips the Subject piece in the hierarchy for some reason
             * and the xls suggests it's just a clone of what we just made for the Learning Area
             * so I guess we just...noobscript a way out of this heresy
             */
            if ($struct['hasSubject']) {
                $this->processWithSubject($sharedLearningAreaId ?? $learningAreaId, $learningArea);
            } else {
                $this->processWithoutSubject($sharedLearningAreaId ?? $learningAreaId, $learningArea);
            }

            $learningAreaId = $this->i;
        }
    }


    /**
     * Spawn a csv
     *
     * @return string
     * @throws \DomainException
     * @throws \RuntimeException
     */
    public function generate(): string
    {
        $this->build();

        /* Header row
         */
        $headings = [
            'id',
            'curriculum_node_parent_id',
            'name',
            'code',
            'order',
            'description'
        ];

        $fp = fopen('php://temp', 'w');
        fputcsv($fp, $headings, escape: '');

        foreach ($this->csvPayload as $row) {
            fputcsv($fp, $row, escape: '');
        }

        rewind($fp);

        $contents = stream_get_contents($fp);

        fclose($fp);

        return $contents;
    }


    /**
     * Some json files come with a subject node in their json
     * If so, process them with the full presumed hierarchy
     *
     * @param int   $learningAreaId
     * @param array $learningArea
     * @return void
     */
    private function processWithSubject(int $learningAreaId, array $learningArea): void
    {
        foreach ($learningArea['curriculumStatements'] as $subject) {
            $subjectId = $this->i;

            $this->csvPayload[] = [
                'id' => $subjectId,
                'curriculum_node_parent_id' => $learningAreaId,
                'name' => $this->cleanse($subject['title'] ?? ''),
                'code' => '',
                'order' => 0,
                'description' => ''
            ];

            /* Increment arbitrary node counter every time a node spawns
             */
            $this->i++;

            /* Level
             */
            foreach ($subject['curriculumStatements'] as $level) {
                $levelId = $this->i;

                $this->csvPayload[] = [
                    'id' => $levelId,
                    'curriculum_node_parent_id' => $subjectId,
                    'name' => $this->cleanse($level['title'] ?? ''),
                    'code' => '',
                    'order' => 0,
                    'description' => ''
                ];

                /* Increment arbitrary node counter every time a node spawns
                 */
                $this->i++;

                /* English skips the Subject node, so artificially ram one in
                 * that is the same as the node we just spawned
                 */

                /* Strand
                 */
                foreach ($level['curriculumStatements'] as $strand) {
                    $strandId = $this->i;

                    $this->csvPayload[] = [
                        'id' => $strandId,
                        'curriculum_node_parent_id' => $levelId,
                        'name' => $this->cleanse($strand['title'] ?? ''),
                        'code' => '',
                        'order' => 0,
                        'description' => ''
                    ];

                    /* Increment arbitrary node counter every time a node spawns
                     */
                    $this->i++;

                    /* Substrand
                     */
                    foreach ($strand['curriculumStatements'] as $substrand) {
                        $substrandId = $this->i;

                        /* Arts doesn't always have a substrand contents
                         */
                        if (isset($substrand['curriculumStatements'])) {
                            $this->csvPayload[] = [
                                'id' => $substrandId,
                                'curriculum_node_parent_id' => $strandId,
                                'name' => $this->cleanse($substrand['title'] ?? ''),
                                'code' => '',
                                'order' => 0,
                                'description' => ''
                            ];

                            /* Increment arbitrary node counter every time a node spawns
                             */
                            $this->i++;

                            /* Node
                             */
                            $this->processSubstrandMeta($substrandId, $substrand);
                        } else {
                            $nodeId = $this->i;

                            /* Arts: Peculiarly different than everything else ;(
                             * (That should come as no surprise...)
                             */
                            $code = $this->cleanseCode($substrand['notations']);

                            $this->csvPayload[] = [
                                'id' => $nodeId,
                                'curriculum_node_parent_id' => $strandId,
                                'name' => $this->cleanse($substrand['description'] ?? ''),
                                'code' => $code,
                                'order' => 0,
                                'description' => ''
                            ];

                            /* Keep track that we found a code
                             */
                            unset($this->missingCodes[$code]);

                            /* Increment arbitrary node counter every time a node spawns
                             */
                            $this->i++;
                        }
                    }
                }
            }
        }
    }


