namespace Schoolbox\Mapper\Traits\Model;

trait Title
{
    /**
     * @var string|null
     */
    protected $title;

    /**
     * @return string|null
     */
    public function getTitle(): ?string
    {
        return $this->title;
    }

    /**
     * @param string|null $title
     *
     * @return self
     */
    public function setTitle(?string $title): self
    {
        $this->title = $title;
        return $this;
    }
}
