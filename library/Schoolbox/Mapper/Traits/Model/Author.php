namespace Schoolbox\Mapper\Traits\Model;

use Schoolbox\User;

trait Author
{
    /**
     * @var User|null
     */
    protected $author;

    /**
     * @return User|null
     */
    public function getAuthor(): ?User
    {
        return $this->author;
    }

    /**
     * @param User|null $author
     *
     * @return self|$this
     */
    public function setAuthor(?User $author): self
    {
        $this->author = $author;
        return $this;
    }
}
