declare(strict_types=1);

namespace Schoolbox\Learning\Student;

use Alaress\Color\ColorFactory;
use Alaress\Database\Connector\IConnector;
use Alaress\Web\Controller\Base;
use Schoolbox\GenericCollection;
use Schoolbox\Mapper\Exception as MapperException;
use Schoolbox\Resource\Folder;
use Schoolbox\Permission\Access\Access;
use Schoolbox\Permission\Access\UserAccess;
use Schoolbox\Resource\Folder\Mapper as FolderMapper;
use Schoolbox\User;
use Timetable_ColourMapper;

class Controller extends Base
{
    private FolderMapper $folderMapper;

    private IConnector $database;

    private Timetable_ColourMapper $timetableColourMapper;

    private Access $access;

    /**
     * Controller constructor.
     *
     * @param FolderMapper           $folderMapper
     * @param IConnector             $database
     * @param Timetable_ColourMapper $timetableColourMapper
     */
    public function __construct(FolderMapper $folderMapper, IConnector $database, Timetable_ColourMapper $timetableColourMapper, Access $access)
    {
        $this->folderMapper = $folderMapper;
        $this->database = $database;
        $this->timetableColourMapper = $timetableColourMapper;
        $this->access = $access;
    }


    /**
     * Display the students course list
     * The list of courses will be generated by getting the students classes, finding each course that has been imported.
     * Only show the course if the viewing user has permission to see via the folder.
     *
     * @param User $user
     * @throws MapperException
     */
    public function getCourses(User $user)
    {
        $homepageList   = $this->folderMapper->createCollection();
        $homepageUrls = [];
        $courseListIds = [];

        // Iterate all subjects from the SIS and try to find folders with that class code
        foreach ($user->getSubjectCollection() as $subject) {
            $folder = $this->folderMapper->findForCampusAndClass($subject['campusCode'] ?? '', $subject['code']);
            if (!$folder) {
                continue;
            }
            $homepageList = $homepageList->mergeUnique(new GenericCollection(Folder\Model::class, [$folder]), 'id');
        }

        //if the student is enrolled in classes, then search for courses...
        if ($homepageList->count()) {
            //get courses imported onto pages
            $pb          = $this->database
                ->buildPredicateBuilder('')
                ->in('f.id', $homepageList->getPropertyValues('id'));
            $whereClause = implode(' AND ', $pb->getWhere());
            $query       = "
            SELECT f.id AS 'f.id', cs.id AS 'cs.id', cs.folder_id as 'cs.fd.id', csf.name as 'cs.title'
            FROM folder f
            JOIN course_implementation ci ON ci.folder_id = f.id
            JOIN course_specification cs ON ci.course_specification_id = cs.id
            JOIN folder csf ON csf.id = cs.folder_id
            JOIN course_unit_implementation cui ON ci.id = cui.course_implementation_id
            JOIN assessment_course_unit_implementation acui ON acui.course_unit_implementation_id = cui.id
            JOIN assessment a ON acui.assessment_id = a.id
            WHERE {$whereClause}
            GROUP BY f.id, ci.course_specification_id;
            ";
            $statement   = $this->database->executeQuery($query, $pb->getParams());

            while ($row = $statement->fetch()) {
                $courseListIds[] = $row['cs.fd.id'];
            }
        }

        //build the folder objects for the course list
        $courseList = $this->folderMapper->findByColumnList(['id' => $courseListIds])->indexBy('id');

        //make colours for courses
        $folderColours = new Folder\FolderColour($this->timetableColourMapper, new ColorFactory());
        $folderColours->applyFolderColours($courseList);

        // Only set those homepage URLs that the viewing user has access permission for
        foreach ($courseList as $folder) {
            if ($this->access->getFolderAccess($this->getUser(), $folder->getId()) >= UserAccess::ACCESS_READ) {
                $homepageUrls[$folder->getId()] = "/homepage/{$folder->getId()}";
            } else {
                $homepageUrls[$folder->getId()] = false;
            }
        }

        //sort the courses by name naturally
        $courseList->sortByCallback(static function (Folder\Model $a, Folder\Model $b): int {
            return \strnatcasecmp($a->getNameWithCodes(), $b->getNameWithCodes());
        }, true);

        //render the things
        $this->getResponse()->content->set($this->buildHtmlOutput('@learningStudentCourses/courses.twig', [
            'courseList'    => $courseList,
            'homepageUrls' => $homepageUrls,
            ])->setTab('classes'));
    }
}
