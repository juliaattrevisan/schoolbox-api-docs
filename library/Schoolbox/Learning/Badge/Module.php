declare(strict_types=1);

namespace Schoolbox\Learning\Badge;

use Alaress\Authorizer\Rule;
use Alaress\Module\Module as BaseModule;
use Alaress\Twig\Loader\IChainLoader;
use Aura\Di\ContainerInterface;
use Closure;
use Schoolbox\Curriculum\Node\Mapper as CurriculumNodeMapper;
use Schoolbox\Filter;
use Schoolbox\Mapper\Exception\NotFound;
use Schoolbox\Resource\Storage\Mapper as StorageMapper;
use Schoolbox\Role;
use Schoolbox\UserMapper;

/**
 * Module for badge requests.
 */
class Module extends BaseModule
{
    protected $basename = 'learningBadge';


    /**
     * @inheritdoc
     */
    public function registerRoutes(): void
    {
        $baseRule = new Rule\All(
            new Rule\IsLoggedIn(),
            new Rule\Any(
                new Rule\IsSuperuser(),
                new Rule\HasRole(Role::STAFF),
            ),
        );

        $viewAwardedBadges = new Rule\All(
            new Rule\IsLoggedIn(),
            new Rule\Any(
                new Rule\IsSuperuser(),
                new Rule\HasRole(Role::STAFF),
                new Rule\IsUserOrParentOfUser(
                    $this->getExternalUser(),
                    UserMapper::getInstance(),
                    'userId'
                )
            ),
        );

        /* Get a list of badges that are available in the instance
         */
        $this->register(
            self::METHOD_GET,
            '',
            'getBadges',
            $baseRule
        );

        /* Get a list of badges that were awarded to a particular person
         */
        $this->register(
            self::METHOD_GET,
            '/{userId}/awarded',
            'getAwardedBadges',
            $viewAwardedBadges,
            Closure::fromCallable([$this, 'preloadUser']),
        );

        /* Get a list of people who have received an Achievement Badge
         */
        $this->register(
            self::METHOD_GET,
            '/{badgeId}/achievement/recipients',
            'getAchievementRecipients',
            $baseRule,
            Closure::fromCallable([$this, 'preloadBadge']),
        );

        /* Withdraw Achievements from awardees
         */
        $this->register(
            self::METHOD_POST,
            '/{badgeId}/achievement/withdraw',
            'postAchievementWithdraw',
            $baseRule,
            Closure::fromCallable([$this, 'preloadBadge']),
        );

        /* Get a list of people who have received a Goal Badge
         */
        $this->register(
            self::METHOD_GET,
            '/{badgeId}/goal/recipients',
            'getGoalRecipients',
            $baseRule,
            Closure::fromCallable([$this, 'preloadBadge']),
        );

        /* Withdraw Goals from awardees
         */
        $this->register(
            self::METHOD_POST,
            '/{badgeId}/goal/withdraw',
            'postGoalWithdraw',
            $baseRule,
            Closure::fromCallable([$this, 'preloadBadge']),
        );

        /* The form that people use to Create a Badge
         */
        $this->register(
            self::METHOD_GET,
            '/create',
            'getCreateForm',
            $baseRule
        );

        /* The form that people use to Update a Badge
         */
        $this->register(
            self::METHOD_GET,
            '/{badgeId}/update',
            'getUpdateForm',
            $baseRule,
            Closure::fromCallable([$this, 'preloadBadge']),
        );

        /* Update a Badge
         */
        $this->register(
            self::METHOD_POST,
            '/{badgeId}/update',
            'postUpdate',
            $baseRule,
            Closure::fromCallable([$this, 'preloadBadge']),
        );

        // Create a badge
        $this->register(
            self::METHOD_POST,
            '',
            'postBadge',
            $baseRule
        );

        // Awarding a badge: only staff may do this
        // POST learning/badge/$badgeId/award/{userId}
        // POST learning/badge/$badgeId/award/{userIds}
        // POST learning/badge/$badgeId/award/, users in data

        // {userId}:
        // + Simpler to understand and write permissions for
        //   POST /learning/evidence/{userId[0]} ...
        // + Hypothetically possible to put in _links, as it can be generated by routeLookup
        // - Multiple calls required to award the same badge to multiple students

        // Advantage of {userIds}:
        // + More difficult, but possible, to write perms for (done in evidence create)
        //   POST /learning/evidence/{userIds}
        // + Can create multiple records in a single call
        // - Can't put into _links, as the user list is unknown, and thus the
        //   permissions are unknown

        // Advantage of users in POST:
        // + Can easily put in _links
        //   POST /learning/evidence
        // + Can create multiple records in single call
        // - Can't write perms in route: can only check perms in controller
        //   (could be an issue when writing the set as goal endpoint)

        // I'm leaning toward users in POST for simplicity:
        // I think the disadvantage of {userIds} not being able to put in _links
        // overrules the advantage of checking permissions.

        $preloadBadge = Closure::fromCallable([$this, 'preloadBadge']);
        $this->register(
            self::METHOD_POST,
            '/{badgeId}/achievement',
            'awardAsAchievement',
            $baseRule,
            $preloadBadge
        );

        // Only staff may set goals for arbitrary users:
        // any user may set goals for themselves
        $this->register(
            self::METHOD_POST,
            '/{badgeId}/goal',
            'setAsGoal',
            $baseRule,
            $preloadBadge
        );
        $this->register(
            self::METHOD_POST,
            '/{badgeId}/setGoalForSelf',
            'setAsGoalForSelf',
            new Rule\IsLoggedIn(),
            $preloadBadge
        );


        // Forms for mass creation of goals/achievements
        // /learning/badge/user/{userIds}/{achievement|goal}
        $preloadUsers = Closure::fromCallable([$this, 'preloadUsers']);
        $this->register(
            self::METHOD_GET,
            '/user/{userIds}/achievement',
            'getBadgeAwardAsAchievementForm',
            $baseRule,
            $preloadUsers
        );

        $this->register(
            self::METHOD_GET,
            '/user/{userIds}/goal',
            'getBadgeSetAsGoalForm',
            $baseRule,
            $preloadUsers
        );
    }


    /**
     * Preload the requested student
     *
     * @param array $params
     * @return array
     * @throws \Schoolbox\Mapper\Exception
     */
    private function preloadUser(array $params): array
    {
        return [
            'user' => $this->getMapperFactory()
                           ->get(UserMapper::class)
                           ->findById($params['userId']),
        ];
    }


    /**
     * Preload the requested badge
     *
     * @param array $params
     * @return array
     * @throws \InvalidArgumentException
     * @throws \Schoolbox\Mapper\Exception
     * @throws \Schoolbox\Mapper\Exception\Deleted
     */
    private function preloadBadge(array $params): array
    {
        return [
            'badge' => $this->getMapperFactory()
                ->get(Mapper::class)
                ->findById($params['badgeId']),
        ];
    }


    /**
     * Preload the requested users.
     *
     * This is the same preloader that the learning moments form uses.
     *
     * @param array $params
     * @return array
     * @throws \Schoolbox\Mapper\Exception
     */
    private function preloadUsers(array $params): array
    {
        $userIds = array_unique(explode(',', $params['userIds']));
        $users   = $this->getMapperFactory()
                        ->get(UserMapper::class)
                        ->findByColumn('id', $userIds);

        // Not found if any of the users in the list were not found
        if (count($users) !== count($userIds)) {
            throw new NotFound();
        }

        return ['users' => $users,];
    }


    /**
     * @return \External_UserInterface
     */
    protected function getExternalUser()
    {
        return $this->getInjector()->get('externalUser');
    }


    /**
     * @inheritdoc
     */
    public function initTemplatePaths(IChainLoader $templateLoader): void
    {
        $this->addTemplatePath($templateLoader, __DIR__ . '/templates');
    }


    /**
     * @inheritdoc
     */
    public function initControllers(ContainerInterface $injector): void
    {
        $injector->set(
            'controller:' . $this->basename,
            $injector->lazyNew(
                Controller::class,
                [
                    'mapper'                => $this->getMapperFactory()->getLazy(Mapper::class),
                    'awardMapper'           => $this->getMapperFactory()->getLazy(Award\Mapper::class),
                    'filterFactoryFactory'  => $injector->lazyGet('filters.factoryFactory'),
                    'filterMapper'          => $this->getMapperFactory()->getLazy(Filter\Mapper::class),
                    'filterSelectionMapper' => $this->getMapperFactory()->getLazy(Filter\Selection\Mapper::class),
                    'storageMapper'         => $this->getMapperFactory()->getLazy(StorageMapper::class),
                    'userMapper'            => $this->getMapperFactory()->getLazy(UserMapper::class),
                    'categoryMapper'        => $this->getMapperFactory()->getLazy(Category\Mapper::class),
                    'curriculumNodeMapper'  => $this->getMapperFactory()->getLazy(CurriculumNodeMapper::class),
                ]
            )
        );
    }
}
