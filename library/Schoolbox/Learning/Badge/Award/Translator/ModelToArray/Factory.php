declare(strict_types=1);

namespace Schoolbox\Learning\Badge\Award\Translator\ModelToArray;

use Alaress\Authorizer\Authorizer;
use Alaress\HTMLPurifier\Adapter\ScrubAdapter;
use Aura\Router\Generator;
use Schoolbox\Cdn\PrefixGenerator;
use Schoolbox\Learning\Badge\Award\Translator\Links as BadgeAwardLinksTranslator;
use Schoolbox\Learning\Badge\Award\Translator\ModelToArray;
use Schoolbox\Learning\Badge\Translator\Links as BadgeLinksTranslator;
use Schoolbox\User;

/**
 * Factory for building a badge award model-to-array translator.
 *
 * Encapsulates the setup of the translator.
 */
class Factory
{
    /**
     * The router used to build links to evidence.
     */
    private Generator $routeGenerator;


    /**
     * The router used to determine links to evidence.
     *
     * Required for determining permissions to links created by the router.
     */
    private Authorizer $authorizer;


    /**
     * The user to build a translator for.
     *
     * Required for determining permissions to links created by the router.
     */
    private User $user;


    /**
     * Prefix generator: for attaching a prefix to the mime icon generated by
     * storage links.
     */
    private PrefixGenerator $prefixGenerator;


    /**
     * Constructor
     *
     * @param Generator       $routeGenerator
     * @param Authorizer      $authorizer
     * @param User            $user
     * @param PrefixGenerator $prefixGenerator
     */
    public function __construct(Generator $routeGenerator, Authorizer $authorizer, User $user, PrefixGenerator $prefixGenerator)
    {
        $this->routeGenerator  = $routeGenerator;
        $this->authorizer      = $authorizer;
        $this->user            = $user;
        $this->prefixGenerator = $prefixGenerator;
    }


    /**
     * Create the translator for badge awards.
     *
     * @return ModelToArray
     */
    public function build(): ModelToArray
    {
        return new ModelToArray(
            new User\Translator\Author\ModelToArray(),
            new \Schoolbox\Learning\Badge\Translator\ModelToArray(
                new User\Translator\Author\ModelToArray(),
                new \Schoolbox\Resource\Storage\Translator\ModelToArray($this->prefixGenerator),
                new ScrubAdapter(),
                new BadgeLinksTranslator($this->routeGenerator, $this->authorizer, $this->user, $this->prefixGenerator)
            ),
            new BadgeAwardLinksTranslator($this->routeGenerator, $this->authorizer, $this->user)
        );
    }
}
