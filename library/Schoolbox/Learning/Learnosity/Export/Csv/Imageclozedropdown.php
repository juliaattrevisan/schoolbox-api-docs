declare(strict_types=1);

namespace Schoolbox\Learning\Learnosity\Export\Csv;

class Imageclozedropdown implements IStrategy
{
    /**
     * @inheritDoc
     *
     * @param array $question
     * @return array|null
     */
    public function findMeaning(array $question): ?array
    {
        $lookup = [];

        foreach ($question['data']['possible_responses'] as $key => $val) {
            $lookup[$key] = $val;
        }

        return $lookup;
    }


    /**
     * @inheritDoc
     *
     * @param array $response
     * @return string|null
     */
    public function findHumanReadable(array $structure, array $response): ?string
    {
        return implode(', ', $response['response']['value'] ?? []);
    }
}
