namespace Schoolbox\Learning\Quiz\Attempt;

use Alaress\Async\Notification\Instance\Builder;
use Alaress\Async\Notification\Parameter\Param;
use Monolog\Logger;
use Schoolbox\Assessment\Term\Mapper as TermMapper;
use Schoolbox\Config\ConfigMapper;
use Schoolbox\Learning\Quiz\Model as Quiz;
use Schoolbox\Learning\Quiz\Mapper as QuizMapper;
use Schoolbox\Mapper as BaseMapper;
use Schoolbox\Permission\Access\UserAccess;
use Schoolbox\Permission\Access\UserAccessMapper;
use Schoolbox\Realtime\Message\NSMapper;
use Schoolbox\Realtime\Notification\Envelope;
use Schoolbox\Realtime\Notification\Parameter\CategoryParam;
use Schoolbox\Realtime\Notification\Parameter\ChildParam;
use Schoolbox\Realtime\Notification\Parameter\UserParam;
use Schoolbox\Realtime\Schedule\Module\AbstractModuleNotifier;
use Schoolbox\Realtime\Schedule\Trigger\TriggerBundleInterface;
use Schoolbox\Resource\Folder\Mapper as FolderMapper;
use Schoolbox\Role;
use Schoolbox\User;
use Schoolbox\UserMapper;

class Notifier extends AbstractModuleNotifier
{
    const TRIGGER_ATTEMPTED = 'attempted';
    const TRIGGER_MARKED    = 'marked';

    const LOG_MARK_PATTERN = "Quiz %d mark visibility is %d: %s %s messages";

    /** @var QuizMapper */
    protected $quizMapper;

    /** @var FolderMapper */
    protected $folderMapper;

    /** @var UserAccessMapper */
    protected $userAccessMapper;

    /** @var UserMapper */
    protected $userMapper;

    /** @var TermMapper */
    protected $termMapper;

    /**
     * @param array $dependencies
     */
    public function loadDependencies($dependencies = null)
    {
        if (empty($dependencies['quizMapper'])) {
            $dependencies['quizMapper'] = QuizMapper::getInstance();
        }
        if (empty($dependencies['folderMapper'])) {
            $dependencies['folderMapper'] = FolderMapper::getInstance();
        }
        if (empty($dependencies['userAccessMapper'])) {
            $dependencies['userAccessMapper'] = UserAccessMapper::getInstance();
        }
        if (empty($dependencies['userMapper'])) {
            $dependencies['userMapper'] = UserMapper::getInstance();
        }
        if (empty($dependencies['termMapper'])) {
            $dependencies['termMapper'] = TermMapper::getInstance();
        }

        parent::loadDependencies($dependencies); // TODO: Change the autogenerated stub
    }


    /**
     * @param QuizMapper $mapper
     * @return static
     */
    protected function setQuizMapper($mapper)
    {
        $this->quizMapper = $mapper;
        return $this;
    }


    /**
     * @param FolderMapper $folderMapper
     * @return static
     */
    protected function setFolderMapper(FolderMapper $folderMapper)
    {
        $this->folderMapper = $folderMapper;
        return $this;
    }


    /**
     * @param UserAccessMapper $userAccessMapper
     * @return static
     */
    protected function setUserAccessMapper($userAccessMapper)
    {
        $this->userAccessMapper = $userAccessMapper;
        return $this;
    }


    /**
     * @param UserMapper $userMapper
     * @return static
     */
    protected function setUserMapper($userMapper)
    {
        $this->userMapper = $userMapper;
        return $this;
    }

    /**
     * @param TermMapper $termMapper
     * @return $this
     */
    protected function setTermMapper($termMapper)
    {
        $this->termMapper = $termMapper;
        return $this;
    }

    /**
     * @return string
     */
    protected function getSlug()
    {
        return NSMapper::NS_ONLINE_ASSESS;
    }


    /**
     * @param TriggerBundleInterface $bundle
     * @return void
     */
    public function bundleTriggers($bundle)
    {
        if ($bundle->getMethod() == BaseMapper::METHOD_UPDATE) {
            $diff = $bundle->getEvent()->getDiff();
            if (isset($diff['finish'])) {
                $bundle->attach(self::TRIGGER_ATTEMPTED, self::IMMEDIATELY);
            } else {
                $bundle->attach(self::TRIGGER_MARKED, self::IMMEDIATELY);
            }
        }
    }


    /* ASYNC */

    /**
     * @param Model $attempt
     * @param User  $student
     * @return Envelope
     */
    public function notifyStaffAttempted($attempt, $student)
    {
        $envelope = new Envelope();
        $bob      = new Builder();

        $assessId = $attempt->getQuiz()->getId();
        /** @var Quiz $assess */
        try {
            $assess = $this->quizMapper->findById($assessId);
            $category = $this->folderMapper->findById($assess->getCategory()->getId());
        } catch (BaseMapper\Exception\Deleted $e) {
            return $envelope;
        } catch (BaseMapper\Exception $e) {
            return $envelope;
        }

        $href = "/learning/assessments/{$assess->getAssessmentModel()->getId()}/status";

        $bob->setTitle(':student attempted :quiz in :category')
            ->setParams([
                'student'  => new UserParam($student),
                'quiz'     => new Param($assess->getTitle(), $href),
                'category' => new CategoryParam($category),
            ])
            ->setNamespace($this->getSlug())
            ->setSeverity(Logger::NOTICE)
            ->setIcon($this->getUserIcon($student))
            ->setHref($href)
            ->addTopic("assess.$assessId.attempted")
            ->setFilter([
                'roletype' => Role::STAFF,
            ]);

        // send this to all staff with write access
        $envelope->broadcastToCategory($category, UserAccess::ACCESS_WRITE, $bob->build());

        return $envelope;
    }


    /**
     * @param Model $attempt
     * @param User  $teacher
     * @param array $diff
     * @return Envelope
     */
    public function notifyStudentMarked($attempt, $teacher, $diff = null)
    {
        $envelope = new Envelope();
        $bob      = new Builder();

        $assessId = $attempt->getQuiz()->getId();
        /** @var Quiz $assess */
        try {
            $assess = $this->quizMapper->findById($assessId);
        } catch (BaseMapper\Exception $e) {
            return $envelope;
        }

        if (!$assess->isMarkShownToStudents()) {
            $this->log->debug(sprintf(self::LOG_MARK_PATTERN, $assessId, $assess->getMarkVisibility(), 'suppressing', 'student'));
            return $envelope;
        } else {
            $this->log->debug(sprintf(self::LOG_MARK_PATTERN, $assessId, $assess->getMarkVisibility(), 'sending', 'student'));
        }

        try {
            $category = $this->folderMapper->findById($assess->getCategory()->getId());
        } catch (BaseMapper\Exception\Deleted $e) {
            return $envelope;
        } catch (BaseMapper\Exception $e) {
            return $envelope;
        }

        $studentId = $attempt->getUser()->getId();

        $href = "/learning/assessments/{$assess->getAssessmentModel()->getId()}/$studentId";

        $bob->setSeverity(Logger::NOTICE)
            ->setNamespace($this->getSlug())
            ->setHref($href)
            ->setIcon($this->getUserIcon($teacher))
            ->setTitle(":staff has marked your attempt of :quiz in :cat")
            ->setParams([
                'staff' => new UserParam($teacher),
                'quiz'  => new Param($assess->getTitle(), $href),
                'cat'   => new CategoryParam($category),
            ])
            ->addTopic("assess.$assessId.marked");

        $envelope->targetToUser($attempt->getUser(), $bob->build());

        return $envelope;
    }


    /**
     * @param Model $attempt
     * @param User  $teacher
     * @param array $diff
     * @return Envelope
     */
    public function notifyParentMarked($attempt, $teacher, $diff = null)
    {
        $envelope = new Envelope();

        $assessId = $attempt->getQuiz()->getId();
        /** @var Quiz $assess */
        try {
            $assess = $this->quizMapper->findById($assessId);
        } catch (BaseMapper\Exception $e) {
            return $envelope;
        }

        $restrictGrades = $this->conf->get('restrict_parent_grades')
            || !$this->conf->get(ConfigMapper::NAME_GRADES_ENABLED);
        if (
            $this->conf->get('restrict_parent_duework_access')
            || ($restrictGrades && $this->conf->get('restrict_student_submissions'))
            || !$assess->isMarkShownToParents()
        ) {
            $this->log->debug(sprintf(self::LOG_MARK_PATTERN, $assessId, $assess->getMarkVisibility(), 'suppressing', 'parent'));
            return $envelope;
        } else {
            $this->log->debug(sprintf(self::LOG_MARK_PATTERN, $assessId, $assess->getMarkVisibility(), 'sending', 'parent'));
        }

        try {
            $category = $this->folderMapper->findById($assess->getCategory()->getId());
            $restrictGrades = $restrictGrades || !$category->isGradePageEnabled();
            $studentId = $attempt->getUser()->getId();
            $student = $this->userMapper->findById($studentId);
        } catch (BaseMapper\Exception\Deleted $e) {
            return $envelope;
        } catch (BaseMapper\Exception $e) {
            return $envelope;
        }

        $term      = $this->termMapper->findForDate($assess->getFinish());
        $hrefGrade = $restrictGrades ? '' : "/learning/grades/{$student->getId()}/{$term->getCode()}/{$assess->getCategory()->getId()}";
        $href      = $this->conf->get('restrict_student_submissions') ? $hrefGrade : "/learning/assessments/{$assess->getAssessmentModel()->getId()}/$studentId";

        $bob = new Builder();
        $bob->setSeverity(Logger::NOTICE)
            ->setNamespace($this->getSlug())
            ->setHref($href)
            ->setIcon($this->getUserIcon($teacher))
            ->setTitle(":staff has marked :child's attempt of :quiz in :cat")
            ->setParams([
                'staff' => new UserParam($teacher),
                'child' => new ChildParam($student, Param::STACKING_REPLACE),
                'quiz'  => new Param($assess->getTitle(), $href),
                'cat'   => new CategoryParam($category),
            ])
            ->addTopic("assess.$assessId.marked");

        $envelope->targetToParent($attempt->getUser(), $bob->build());

        return $envelope;
    }
}
