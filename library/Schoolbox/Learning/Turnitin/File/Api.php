declare(strict_types=1);

namespace Schoolbox\Learning\Turnitin\File;

use Alaress\Jitter\Jitter;
use Alaress\Random\FloatGenerator;
use JsonException;
use Psr\Http\Client\ClientExceptionInterface;
use Psr\Http\Message\ResponseInterface;
use Schoolbox\Learning\Turnitin\Api as BaseApi;
use Schoolbox\Learning\Turnitin\Exception\Exception;
use Schoolbox\User;

/**
 * Specialised API for dealing directly with files uploaded to Turnitin.
 *
 * @see https://github.com/turnitin/turnitin-core-api/blob/main/tca-openapi.yaml
 *      for publicly available TII endpoint information.
 */
class Api
{
    /* A specially-hardcoded value to have programmatically accepted the eula
     * It's part of our T&C with turnitin
     */
    private const EULA_ACCEPTANCE_DATE = '2021-01-01T00:00:00.000Z';

    /**
     * Turnitin API endpoint for fetching a viewer URL.
     */
    private const VIEWER_URL = '/api/v1/submissions/%s/viewer-url';

    /**
     * Turnitin API endpoint for requesting a PDF to be generated.
     */
    private const REQUEST_PDF_URL = '/api/v1/submissions/%s/similarity/pdf';

    /**
     * Turnitin API endpoint for downloading a PDF once it has been requested.
     */
    private const DOWNLOAD_PDF_URL = '/api/v1/submissions/%s/similarity/pdf/%s';

    /**
     * Constructor
     *
     * @param BaseApi $baseApi Base Turnitin API
     */
    public function __construct(private BaseApi $baseApi)
    {
    }

    /**
     * Generate the URL via which the current user may view a TII report.
     *
     * @param Model  $turnitin            The TII report model.
     * @param User   $viewer              The user viewing the report.
     * @param string $viewerPermissionSet The permission set: one of the
     *                                    `Process\Report::VIEWER_PERMISSION_SET_*`
     *                                    constants
     * @param bool   $allowSaveChanges    May the user save changes to the
     *                                    report?
     * @return string|null
     * @throws \GuzzleHttp\Exception\GuzzleException
     * @throws JsonException
     */
    public function generateViewerUrl(
        Model $turnitin,
        User $viewer,
        string $viewerPermissionSet,
        bool $allowSaveChanges,
    ): ?string {
        /* Choose a viewer permission set based on your role
         * Staff members get a different set than students or parents
         *
         * Start with the lowest-permission settings
         */
        $payload = [
            'viewer_user_id'                => $viewer->getId(),
            'locale'                        => 'en',
            'viewer_default_permission_set' => $viewerPermissionSet,
            'eula'                          => [
                'version'            => 'v1beta',
                'accepted_timestamp' => self::EULA_ACCEPTANCE_DATE,
                'language'           => 'en-US',
            ],
        ];

        /* Then decide if you're a staff and you need more stuff
         */
        if ($allowSaveChanges) {
            $payload = array_merge(
                $payload,
                [
                    'similarity' => [
                        'view_settings' => [
                            'save_changes' => true,
                        ],
                    ],
                ]
            );
        }

        /* TODO Apparently localisation is a thing, set via locale tuple;
         *  but I have assumed en for now
         */
        $result = $this->baseApi->retrieve(
            'POST',
            sprintf(self::VIEWER_URL, $turnitin->getTurnitinSubmissionId()),
            $payload,
        );
        return isset($result['viewer_url'])
            ? (string)$result['viewer_url']
            : null;
    }

    /**
     * Request a PDF of a Turnitin document.
     *
     * This doesn't return a PDF: it simply queues the generation of one. Use
     * `downloadPdf` to download it.
     *
     * @param Model $turnitin
     * @return string|null
     * @throws \GuzzleHttp\Exception\GuzzleException
     * @throws JsonException
     */
    public function generatePdfRequest(Model $turnitin): ?string
    {
        $result = $this->baseApi->retrieve(
            'POST',
            sprintf(self::REQUEST_PDF_URL, $turnitin->getTurnitinSubmissionId()),
            [],
        );
        return isset($result['id'])
            ? (string)$result['id']
            : null;
    }

    /**
     * Download a PDF generated by `generatePdfRequest`.
     *
     * Periodically polls the download PDF endpoint until it returns a response
     * that is actually a PDF.
     *
     * @param Model  $turnitin    The Turnitin file to generate a PDF for.
     * @param string $id          Download the PDF with this ID.
     * @param int    $maxAttempts Maximum attempts to download the PDF.
     * @param int    $baseTimeout Base wait between download PDF attempts: this
     *                            method applies a jitter between attempts.
     * @return ResponseInterface
     */
    public function downloadPdf(Model $turnitin, string $id, int $maxAttempts, int $baseTimeout): ResponseInterface
    {
        $jitter     = new Jitter(new FloatGenerator(), $maxAttempts, $baseTimeout);
        $attemptNum = 1;

        // Poll the download PDF URL until it actually returns a PDF.
        // Possible responses:
        // * 200: response contains PDF
        // * 202: PDF is still generating; response contains a status
        while (!$jitter->tooManyAttempts($attemptNum)) {
            try {
                $pdfResponse = $this->baseApi->retrieveRawResponse(
                    'GET',
                    sprintf(self::DOWNLOAD_PDF_URL, $turnitin->getTurnitinSubmissionId(), $id),
                    [],
                );
            } catch (ClientExceptionInterface $e) {
                throw new Exception('PDF generation status request failed', 0, $e);
            }

            $pdfResponseStatus = $pdfResponse->getStatusCode();
            if ($pdfResponseStatus === 200) {
                // PDF is generated and part of the response: break
                return $pdfResponse;
            }

            if ($pdfResponseStatus === 202) {
                // PDF is being processed
                try {
                    $body = json_decode($pdfResponse->getBody()->getContents(), true, 512, JSON_THROW_ON_ERROR);
                } catch (JsonException $e) {
                    throw new Exception('Failed to parse PDF generation status response', 0, $e);
                }
                $pdfStatus = $body['status'] ?? null;
                if ($pdfStatus === 'FAILED') {
                    // raise some error
                    throw new Exception('Failed to generate PDF');
                }
            }

            // Any other response: continue and try again
            $wait = $jitter->calculateJitter($attemptNum);
            usleep((int)($wait * 1000));
            $attemptNum++;
        }
        throw new Exception(
            sprintf('Could not generate PDF after %d attempts', $maxAttempts)
        );
    }
}
