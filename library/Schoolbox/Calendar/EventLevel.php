namespace Schoolbox\Calendar;

class EventLevel
{

    /**
     * Id of the event level
     *
     * @var int
     */
    private $id = '';

    /**
     * Name of the event level
     *
     * @var string
     */
    private $name = '';

    /**
     * Constructor
     *
     * @param int $id
     * @param string $name
     */
    public function __construct($id, $name)
    {
        $this->setId($id);
        $this->setName($name);
    }

    /**
     * Set id
     *
     * @param int $id
     */
    public function setId($id)
    {
        $this->id = $id;
    }

    /**
     * Get id
     *
     * @return int
     */
    public function getId()
    {
        return $this->id;
    }

    /**
     * Set name
     *
     * @param string $name
     */
    public function setName($name)
    {
        $this->name = $name;
    }

    /**
     * Get name
     *
     * @return string
     */
    public function getName()
    {
        return $this->name;
    }
}
