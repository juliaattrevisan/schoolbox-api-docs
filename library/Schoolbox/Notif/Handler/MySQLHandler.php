namespace Schoolbox\Notif\Handler;


use Monolog\Handler\AbstractProcessingHandler;
use Monolog\Logger;
use Schoolbox\Notif\NotifException;

class MySQLHandler extends AbstractProcessingHandler {

	protected $sql;

	public function __construct($level = Logger::DEBUG, $bubble = true) {
		parent::__construct($level, $bubble); // TODO: Change the autogenerated stub
	}

	public function setQuery($sql) {
		$this->sql = $sql;
	}

	/**
	 * Writes the record down to the log of the implementing handler
	 *
	 * @param  array $record
	 * @throws \Schoolbox\Notif\NotifException
	 * @return void
	 */
	protected function write(array $record) {
		if(empty($this->sql)) {
			throw new NotifException("No query provided for MySQL handler");
		}

		// TODO DEGLOBALISE
		$stmt = \Database::getInstance()->prepare($this->sql);

		try {
			$stmt->execute($record['context']);
		}
		catch(\PDOException $e) {
			throw new NotifException("Could not log to database.", 0, $e);
		}

	}

}