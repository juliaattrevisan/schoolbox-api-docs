namespace Schoolbox\Notif\Message;


use Monolog\Logger;
use PhpAmqpLib\Message\AMQPMessage;
use React\Stomp\Protocol\Frame;
use Schoolbox\Collection;
use Schoolbox\Mapper;
use Schoolbox\Notif\MQ\Connector;
use Schoolbox\Notif\Notif;
use Schoolbox\Realtime\Message\Reroute;
use Schoolbox\Realtime\Message\RerouteMapper;
use Schoolbox\User;
use Schoolbox\UserMapper;

class Interceptor {

	/** @var Connector */
	protected $conn;

	/** @var UserMapper */
	protected $userMapper;

	/** @var Mapper */
	protected $rerouteMapper;

	/**
	 * @param Connector $connector
	 */
	function __construct($connector) {
		$this->conn = $connector;
		$this->rerouteMapper = RerouteMapper::getInstance();
		$this->userMapper = UserMapper::getInstance();
	}


	/**
	 * @param int $userId
	 * @param AMQPMessage $msg
	 * @return bool
	 */
	public function hasReroute($userId, $msg) {

		$body = $this->unwrapMessageBody($msg);
		$level = $body['level'];

		// try this test first, save ourselves some db calls
		if($this->canDismiss($userId, $msg)) {
			return true;
		}

		$newLevel = $this->getReroutedLevel($userId, $body['channel'], $level);

		return $level != $newLevel;
	}


	/**
	 * @param int $userId
	 * @param Frame $frame
	 * @return bool
	 */
	public function reroute($userId, $frame) {

		$body = json_decode($frame->body, true);

		/** @var External $external */
		$external = unserialize($body['message']);

		if(!$external instanceof External) {
			echo "INCORRECT FORMAT: DISMISS!\n";
			return false;
		}

		// fail fast: if it's already been rerouted, don't try again
		if(isset($body['extra']['rerouted'])) {
			echo "ALREADY REROUTED, SHOULDN'T HAVE ENDED UP BACK HERE!\n";
			return false;
		}

		// yes we are "rerouting" this message...rerouting it to /dev/null! *mwa ha ha*
		if($this->canDismiss($userId, $body)) {
			echo "SELF-SEND: DISMISS!\n";
			return true;
		}

		$newLevel = $this->getReroutedLevel($userId, $body['channel'], $body['level']);

		switch($newLevel) {
			// total suppression
			case 0:
				echo "NEW LEVEL IS ZERO: DISMISS!\n";
				return true;

			// digest
			case Logger::INFO:
				$method = 'digest';
				break;

			// instant
			case Logger::NOTICE:
				$method = 'instant';
				break;

			// instant + email
			case Logger::WARNING:
			case Logger::ERROR:
				$method = 'instant';
				break;

			default:
				echo "UNACCEPTABLE LEVEL: DISMISS!\n";
				return true;
		}

		try {
			// aaand republish our modified message
			$external->resend(new Notif(), $newLevel, "$method.user.$userId");

			// return true to dismiss the old message
			echo "I REROUTED YOUR MESSAGE to '$method.user.$userId' at level $newLevel!\n";
		}
		catch(\Exception $e) {
			echo $e;
		}

		return true;
	}


	/**
	 * @param int $userId
	 * @param string $channel
	 * @param string $level
	 * @return int
	 */
	protected function getReroutedLevel($userId, $channel, $level) {

//		print_r(func_get_args());

		/** @var User $user */
		$user = $this->userMapper->findById($userId);

		/** @var Collection|Reroute[] $coll */
		$coll = new Collection();

		$checks = array(
			'user'   => $user->getId(),
			'role'   => $user->getRole()->getId(),
			'campus' => $user->getDefaultCampus()->getId()
		);

		foreach($checks as $type => $id) {
			if(!$id) {
				continue;
			}
			$coll->merge($this->rerouteMapper->findByColumnList(array(
				'relation_id'    => $id,
				'relation_type'  => $type,
//				'incoming_level' => $level
			)));
		}

		if(!$coll->count()) {
			// just return the old level if there are no reroutes
			return $level;
		}

		foreach($coll as $offset => $reroute) {
			$regex = array(
				'`\*`' => '[^.]+',
				'`#`'  => '(?:[^.]+.?)*',
				'`\.`' => '\.'
			);

			$routingRegex = '`' . preg_replace(
				array_keys($regex), array_values($regex),
				$reroute->getRoutingKey()
			) . '`';

			if(!preg_match($routingRegex, $channel)) {
				$coll->offsetUnset($offset);
			}
		}

		if($coll->count()) {
			// set the new level to the highest value found in the reroute
			return max($coll->getColumnValues('outgoingLevel'));
		}

		// if in doubt, return the original level
		return $level;
	}


	/**
	 * If this message was generated by myself, I don't want to see it
	 *
	 * @param int $userId
	 * @param AMQPMessage|array $body
	 * @return bool
	 */
	protected function canDismiss($userId, $body) {
		// unwrap if AMQP
		if($body instanceof AMQPMessage) {
			$body = $this->unwrapMessageBody($body);
		}
		$context = $body['context'];
		if(isset($context['user']) && $context['user'] == $userId) {
			return true;
		}
		return false;
	}


	/**
	 * @param AMQPMessage $m
	 * @return array
	 */
	public function unwrapMessageBody($m) {
		return json_decode($m->body, true);
	}

}
