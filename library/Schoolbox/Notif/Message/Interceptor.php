namespace Schoolbox\Notif\Message;


use Monolog\Logger;
use PhpAmqpLib\Message\AMQPMessage;
use Schoolbox\Collection;
use Schoolbox\Mapper;
use Schoolbox\Notif\MQ\Connector;
use Schoolbox\Notif\Reroute\Reroute;
use Schoolbox\Notif\Reroute\RerouteMapper;
use Schoolbox\User;
use Schoolbox\UserMapper;

class Interceptor {

	/** @var Connector */
	protected $conn;

	/** @var UserMapper */
	protected $userMapper;

	/** @var Mapper */
	protected $rerouteMapper;

	/**
	 * @param Connector $connector
	 */
	function __construct($connector) {
		$this->conn = $connector;
		$this->rerouteMapper = RerouteMapper::getInstance();
		$this->userMapper = UserMapper::getInstance();
	}


	/**
	 * @param int $userId
	 * @param AMQPMessage $msg
	 * @return bool
	 */
	public function hasReroute($userId, $msg) {

		$body = $this->unwrapMessageBody($msg);
		$level = $body['level'];

		// try this test first, save ourselves some db calls
		if($this->canDismiss($userId, $msg)) {
			return true;
		}

		$newLevel = $this->getReroutedLevel($userId, $body['channel'], $level);

		return $level != $newLevel;
	}


	/**
	 * @param int $userId
	 * @param AMQPMessage $msg
	 * @return bool
	 */
	public function reroute($userId, $msg) {
		if($msg->has('extra')) {
			// fail fast: if it's already been rerouted, don't try again
			if(array_key_exists('rerouted', $msg->get('extra'))) {
				return false;
			}
		}

		// yes we are "rerouting" this message...rerouting it to /dev/null! *mwa ha ha*
		if($this->canDismiss($userId, $msg)) {
			return true;
		}

		$body = $this->unwrapMessageBody($msg);
		$level = $body['level'];

		$newLevel = $this->getReroutedLevel($userId, $body['channel'], $level);

		// total suppression
		if($newLevel == 0) {
			// just say that we did it; the message will be acknowledged
			return true;
		}
		elseif($newLevel == $level) {
			// same level, or no reroute specified: not rerouting
			return false;
		}

		// perform the reroute
		$newChannel = 'notify.user.' . $userId;
		$newLevelName = Logger::getLevelName($newLevel);

		$msg->set('extra', array_merge($msg->has('extra') ? $msg->get('extra') : array(), array(
			'rerouted' => $msg->get('channel')
		)));

		$msg->set('channel', $newChannel);
		$msg->set('level', $newLevel);
		$msg->set('level_name', $newLevelName);

		// aaand republish our modified message
		$this->conn->publish($msg, sprintf('%s.%s',
			substr($newLevelName, 0, 4), $newChannel
		));

		// return true to dismiss the old message
		return true;
	}


	/**
	 * @param int $userId
	 * @param string $channel
	 * @param string $level
	 * @return int
	 */
	protected function getReroutedLevel($userId, $channel, $level) {

		/** @var User $user */
		$user = $this->userMapper->findById($userId);

		/** @var Collection|Reroute[] $coll */
		$coll = new Collection();

		$checks = array(
			'user'   => $user->getId(),
			'role'   => $user->getRole()->getId(),
			'campus' => $user->getDefaultCampus()->getId()
		);

		foreach($checks as $type => $id) {
			if(!$id) {
				continue;
			}
			$coll->merge($this->rerouteMapper->findByColumnList(array(
				'relation_id'    => $id,
				'relation_type'  => $type,
				'incoming_level' => $level
			)));
		}

		if(!$coll->count()) {
			// just return the old level if there are no reroutes
			return $level;
		}

		foreach($coll as $offset => $reroute) {
			$regex = array(
				'`\.?\*`' => '\.?[^\.]',
				'`\.?#`' => '\.?.+'
			);

			$routingRegex = '`' . preg_replace(
				array_keys($regex), array_values($regex),
				$reroute->getRoutingKey()
			) . '`';

			if(!preg_match($routingRegex, $channel)) {
				$coll->offsetUnset($offset);
			}
		}

		// set the new level to the highest value found in the reroute
		return max($coll->getColumnValues('outgoingLevel'));
	}


	/**
	 * @param int $userId
	 * @param AMQPMessage $m
	 * @return bool
	 */
	protected function canDismiss($userId, $m) {
		// if it was generated by myself, I don't want to see it
		$body = $this->unwrapMessageBody($m);
		$context = $body['context'];
		if(isset($context['user']) && $context['user'] == $userId) {
			return true;
		}
		return false;
	}


	/**
	 * @param AMQPMessage $m
	 * @return array
	 */
	public function unwrapMessageBody($m) {
		$body = json_decode($m->body, true);
		$body['message'] = unserialize($body['message']);
		return $body;
	}

}
