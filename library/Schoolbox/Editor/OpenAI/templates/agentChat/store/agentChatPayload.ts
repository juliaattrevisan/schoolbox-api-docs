import { sseApiRequest } from "@js/util/sbx/apiUtils";
import type { ApiBaseResponse, SseMessageEvent, SseMessageCallback } from "@js/util/sbx/apiUtils";
import type { AiSession } from "@schoolboxLibrary/Admin/OpenAI/Usage/templates/payload";
import type { AgentChatImage } from "../agentChatTypes";

/**
 * The possible event types that agentChat expects to receive during an event stream
 * @see /library/Schoolbox/OpenAi/AgentChat/MessageEventType.php
 */
export enum AgentChatMessageEventType {
    /**
     * Intermediate event - The response was created and we recieved some sign of life back from the AI
     * Includes the response ID for tracking
     */
    CREATED = "created",
    /**
     * Intermediate event - A partial image generated by the AI
     */
    PARTIAL_IMAGE = "partial_image",
    /**
     * Intermediate event - A delta of text output from the AI
     * Will be appended to the current message to show the user that something is happening
     */
    DELTA = "delta",
    /**
     * A final response with a valid image/text to be shown
     * The frontend will terminate the stream after receiving this event
     */
    COMPLETE = "complete",
    /**
     * Something went wrong during the event stream, whether an internal error or an error from OpenAI
     * The data payload should contain error details following the format of RFC 9457 "API Problem" (title/detail)
     * The frontend will terminate the stream after receiving this event
     */
    ERROR = "error",
}

export type AgentChatApiPayload = {
    userPrompt: string;
    attributes: Record<string, string | null>;
    imageUrl: string | null;
    previousResponseId: string | null;
    /**
     * To keep track of the current ai conversation thread
     * This should be unique for a new unique conversation
     *
     * image generation (required)
     * - on each load of the tab (in the dropzone modal) this will regen from the backend
     *
     * dialog agent chat (optional)
     * - when messaging against a response, this is unused as the session ID is stored against the response already
     * - when testing the chat agent, this will be generated on load from the backend
     */
    aiSessionId: AiSession["id"] | null;
};

type AgentChatApiResponseCompleted = {
    responseId: string;
    message: string;
    image: AgentChatImage | null;
};

/** @see /library/Schoolbox/OpenAi/AgentChat/MessageHandler.php */
type AgentChatApiMessageEvent =
    | SseMessageEvent<AgentChatMessageEventType.CREATED, { responseId: string }>
    | SseMessageEvent<AgentChatMessageEventType.PARTIAL_IMAGE, { responseId: string; image: AgentChatImage }>
    | SseMessageEvent<AgentChatMessageEventType.DELTA, { responseId: string; delta: string }>;

/**
 * Generate an image using the image generation API
 * @param url - The endpoint to fetch
 * @param body - The data to send in the request
 * @param signal - AbortSignal to cancel the request if needed
 * @param onMessage - The callback to handle each message from the server
 * @returns The response from the fetch
 */
export async function generateImage(
    url: string,
    body: AgentChatApiPayload,
    signal: AbortSignal | null,
    onMessage: SseMessageCallback<AgentChatApiMessageEvent>,
): Promise<ApiBaseResponse<AgentChatApiResponseCompleted>> {
    return sseApiRequest<AgentChatApiMessageEvent, AgentChatApiResponseCompleted, AgentChatApiPayload>({
        url,
        method: "POST",
        body,
        onMessage,
        finalEventType: AgentChatMessageEventType.COMPLETE,
        signal: signal || undefined,
    });
}
