import type { FileDropFile } from "@js/resource/fileDropTypes";
import type { ImageGeneratorApiPayload } from "./store/agentChatPayload";

type Image = {
    b64: string;
    name: string;
    mime: "image/png"; // currently always PNG, but here if we want to support other formats in the future
};

export type AgentChatRequest = {
    type: "request";
    entryKey: number;
    user: Pick<typeof window.schoolboxUser, "id" | "externalId" | "name">;
    payload: ImageGeneratorApiPayload;
    file: FileDropFile | null;
};

type AgentChatResponseSuccess = {
    type: "response";
    status: "success";
    entryKey: number;
    /* the openai response ID so we can reference it in the next chat */
    responseId: string;
    /* a base64-encoded image generated by the AI, if any */
    image: Image | null;
    /* a message from the AI, if any */
    message: string;
};

type AgentChatResponseError = {
    type: "response";
    status: "error";
    entryKey: number;
    responseId: string | null;
    message: string;
};

export type AgentChatResponseInProgress = {
    type: "response";
    status: "in_progress";
    entryKey: `loading-${number}`;
    responseId: string | null;
    image: Image | null;
    message: string;
};

export type AgentChatResponse = AgentChatResponseSuccess | AgentChatResponseInProgress | AgentChatResponseError;

export type AgentChatFeedMessage = AgentChatRequest | AgentChatResponse;

export type AgentChatPromptAttribute = {
    id: string;
    title: string;
    options: Record<string, string>;
    required: boolean;
};
