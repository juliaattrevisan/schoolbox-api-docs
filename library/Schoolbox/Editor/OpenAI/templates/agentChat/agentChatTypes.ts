import type { DateRFC3339 } from "@js/util/dateUtils";
import type { FileDropFile } from "@js/resource/fileDropTypes";
import type { UserAuthor } from "@schoolboxLibrary/types/User";
import type { AgentChatApiPayload } from "./store/agentChatPayload";

/**
 * Aligned with the "CharacterLimit" guardrail, this prevents a learner from triggering the guardrail
 * unless they edit the request and bypass the frontend logic themselves.
 */
export const AGENT_CHAT_MAX_PROMPT_CHARS = 5000;

export enum AgentChatMessageType {
    REQUEST = "request",
    RESPONSE = "response",
    ALERT = "alert",
}

export type AgentChatImage = {
    b64: string;
    name: string;
    mime: "image/png"; // currently always PNG, but here if we want to support other formats in the future
};

/** Severity level to use for a guardrail alert */
export const AgentChatGuardrailSeverity = "warning" satisfies FeedItemDataAlert["severity"];

type FeedItemDataRequest = string;
type FeedItemDataResponse = {
    status: "success" | "error" | "in_progress";
    /** The AI's response ID so we can reference it in the next chat message sent */
    responseId: string | null;
    /**
     * A base64-encoded image generated by the AI, if any
     * - If this is from the current session, image data can be present
     * - If this is from a log from the past, this will be `false` if the image was there but omitted from the log
     * - otherwise undefined/null if no image was generated
     */
    image?: AgentChatImage | false | null;
    /**
     * A message from the AI, if any
     * WARNING: Response messages can be rendered with v-html, so must be properly purified with Scrub before being sent to the frontend
     */
    message: string;
};
type FeedItemDataAlert = {
    side: AgentChatMessageType.RESPONSE | AgentChatMessageType.REQUEST;
    /**
     * TODO: this aligns with a CSS class for now, but we probably need to think about this whole struct anyway
     *
     * Currently used for:
     * - highlight: dialog agent stopped requesting assistance
     * - warning: guardrails alert
     * - warning-tint: dialog agent started requesting assistance
     * - alert: X (although AgentChatFeedMessage<AgentChatMessageType.RESPONSE> is essentially the same thing)
     */
    severity: "highlight" | "warning" | "warning-tint" | "alert";
    title?: string; // optional title for the alert (shows in bold)
    message: string;
};

type FeedItemDataMap = {
    [AgentChatMessageType.REQUEST]: FeedItemDataRequest;
    [AgentChatMessageType.RESPONSE]: FeedItemDataResponse;
    [AgentChatMessageType.ALERT]: FeedItemDataAlert;
};

type FeedItemMetadataRequest = {
    user?: Pick<UserAuthor, "id" | "fullName" | "_links"> | null;
    payload: AgentChatApiPayload;
    file: FileDropFile | null;
};

type FeedItemMetaMap = {
    [AgentChatMessageType.REQUEST]: FeedItemMetadataRequest;
    [AgentChatMessageType.RESPONSE]: null;
    [AgentChatMessageType.ALERT]: null;
};

/**
 * Similar to AgentChatFeedMessage, but only the data recieved when restoring from a log
 */
export type AgentChatLogEntry = { createdAt: DateRFC3339 } & {
    [K in AgentChatMessageType]: { type: K; data: FeedItemDataMap[K] };
}[AgentChatMessageType];

/**
 * An individual item in the agent chat feed
 */
export interface AgentChatFeedMessage<TType extends AgentChatMessageType> {
    type: TType;
    data: FeedItemDataMap[TType];
    /**
     * Extra metadata about the message that isn't restored from logs
     * and only exists when the request was made in the current session
     */
    meta: FeedItemMetaMap[TType];
    createdAt: DateRFC3339;
    /**
     * Any new entry in the feed must have a unique entry key
     * This ensures that Vue can keep track of the items properly, especially if changing the type
     */
    entryKey: number;
}

/**
 * A union type of all possible AgentChatFeedMessage types
 * This is useful for type narrowing when dealing with feed messages of an unknown type
 */
export type AnyAgentChatFeedMessage = {
    [K in AgentChatMessageType]: AgentChatFeedMessage<K>;
}[AgentChatMessageType];

export type AgentChatPromptAttribute = {
    id: string;
    title: string;
    options: Record<string, string>;
    required: boolean;
};
