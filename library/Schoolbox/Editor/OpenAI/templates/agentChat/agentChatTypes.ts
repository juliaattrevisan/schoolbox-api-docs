import type { DateRFC3339 } from "@js/util/dateUtils";
import type { FileDropFile } from "@js/resource/fileDropTypes";
import type { UserAuthor } from "@schoolboxLibrary/types/User";
import type { AgentChatApiPayload } from "./store/agentChatPayload";

export enum AgentChatMessageType {
    REQUEST = "request",
    RESPONSE = "response",
    ALERT = "alert",
}

/** The expected data type for this feature that the AI log will restore */
type AgentChatLogDataRequest = string;
type AgentChatLogDataResponse =
    | Pick<AgentChatResponseError, "status" | "responseId" | "message">
    | Pick<AgentChatResponseSuccess, "status" | "responseId" | "image" | "message">;
type AgentChatLogDataAlert = Pick<AgentChatAlert, "side" | "severity" | "message">;

export type AgentChatLogEntry =
    | { type: AgentChatMessageType.REQUEST; data: AgentChatLogDataRequest; createdAt: DateRFC3339 }
    | { type: AgentChatMessageType.RESPONSE; data: AgentChatLogDataResponse; createdAt: DateRFC3339 }
    | { type: AgentChatMessageType.ALERT; data: AgentChatLogDataAlert; createdAt: DateRFC3339 };

export type AgentChatImage = {
    b64: string;
    name: string;
    mime: "image/png"; // currently always PNG, but here if we want to support other formats in the future
};

export type AgentChatRequest = {
    type: AgentChatMessageType.REQUEST;
    entryKey: number;
    user?: Pick<UserAuthor, "id" | "fullName" | "_links"> | null;
    payload: AgentChatApiPayload;
    file: FileDropFile | null;
};

type AgentChatResponseSuccess = {
    type: AgentChatMessageType.RESPONSE;
    status: "success";
    entryKey: number;
    /* the openai response ID so we can reference it in the next chat */
    responseId: string | null;
    /**
     * A base64-encoded image generated by the AI, if any
     * - If this is from the current session, image data can be present
     * - If this is from a log from the past, this will be `false` if the image was there but omitted from the log
     * - otherwise `null` if no image was generated
     */
    image: AgentChatImage | false | null;
    /**
     * A message from the AI, if any
     * WARNING: Response messages can be rendered with v-html, so must be properly purified with Scrub before being sent to the frontend
     */
    message: string;
};

type AgentChatResponseError = {
    type: AgentChatMessageType.RESPONSE;
    status: "error";
    entryKey: number;
    responseId: string | null;
    /**
     * WARNING: Response messages can be rendered with v-html, so must be properly purified with Scrub before being sent to the frontend
     */
    message: string;
};

export type AgentChatResponseInProgress = {
    type: AgentChatMessageType.RESPONSE;
    status: "in_progress";
    entryKey: `loading-${number}`;
    responseId: string | null;
    image: AgentChatImage | null;
    /**
     * WARNING: Response messages can be rendered with v-html, so must be properly purified with Scrub before being sent to the frontend
     */
    message: string;
};

export type AgentChatAlert = {
    type: AgentChatMessageType.ALERT;
    side: AgentChatMessageType.RESPONSE | AgentChatMessageType.REQUEST;
    /**
     * TODO: this aligns with a CSS class for now, but we probably need to think about this whole struct anyway
     *
     * Currently used for:
     * - highlight: dialog agent stopped requesting assistance
     * - warning: guardrails alert
     * - warning-tint: dialog agent started requesting assistance
     * - alert: X (although AgentChatResponseError is essentially the same thing)
     */
    severity: "highlight" | "warning" | "warning-tint" | "alert";
    entryKey: number;
    message: string;
};

export type AgentChatResponse = AgentChatResponseSuccess | AgentChatResponseInProgress | AgentChatResponseError;

export type AgentChatFeedMessage = AgentChatRequest | AgentChatResponse | AgentChatAlert;

export type AgentChatPromptAttribute = {
    id: string;
    title: string;
    options: Record<string, string>;
    required: boolean;
};
