namespace Schoolbox\LearningAnalytics;

use Alaress\Web\Controller\Base;

use Schoolbox\Resource\Category as Folder;
use Schoolbox\Collection;
use Schoolbox\LearningAnalytics\Progress\Overall;
use Schoolbox\LearningAnalytics\Progress\AllUnits as AllUnitProgress;
use Schoolbox\LearningAnalytics\Results\Averages;
use Schoolbox\LearningAnalytics\Results\TaskList;
use Schoolbox\LearningAnalytics\Results\TaskResults;
use Schoolbox\LearningAnalytics\Metadata\Base as Metadata;
use Schoolbox\LearningAnalytics\Metadata\Course as MetadataCourse;
use Schoolbox\LearningAnalytics\Metadata\Folder as MetadataFolder;

class Controller extends Base {

    /**
     * Same calculations as process(), just for a different set of units
     *
     * @param array $params
     * @param Collection $allUnitInstances
     */
    public function course($params, Collection $allUnitInstances) {
        $this->process($allUnitInstances, new MetadataCourse($params, $allUnitInstances));
    }

    /**
     * Same calculations as process(), just for a different set of units
     *
     * @param array $params
     * @param Collection $allUnitInstances
     */
    public function folder($params, Collection $allUnitInstances) {
        $this->process($allUnitInstances, new MetadataFolder($params, $allUnitInstances));
    }

    /**
     * Calculate all data about $allUnitInstances
     *
     * $allUnitInstances will be:
     *
     * + either all the units relevant to the course belonging to the
     * "learningAnalytics/$param['folderId']/course" route
     *
     * + or all the units relevant to a particular folder in the
     * "learningAnalytics/$param['folderId']" route
     *
     * Both are processed identically as data is grouped based on task
     * instances' originating task id, not the individual instance id
     *
     * @param Collection $allUnitInstances
     * @param Metadata $metadata
     */
    private function process(Collection $allUnitInstances, Metadata $metadata) {

        /* Get a list of all the students involved in each unit
         * and a list of units involved. This gets reused everywhere
         * so just hit the external db once
         */
        $registry = new Registry($allUnitInstances);

        /**
         * Overall Progress
         */
        $overallProgress = new Overall($registry);

        /**
         * Results for all the units in each $folder contained in $allFolders
         * (generated by Registry)
         */
        $taskList = new TaskList($registry);
        $taskResults = new TaskResults($registry);

        /**
         * Grade Averages for student rankings
         */
        $allAverages = new Averages($taskResults->getAllResults());

        /**
         * Individual Unit Progress for all the units in each $folder
         * contained in $allFolders (generated by Registry)
         */
        $stackedUnitProgress = new AllUnitProgress($registry);

        /**
         * Rubrics
         */
        $rubricHandler = new \DueWork_Rubric_Handler();

        /* A list of all the criteria for this folder
         */
        $allCriteria = $rubricHandler->getAvailableCriteria($metadata->getSelectedFolder());

        /* All the students' values
         */
        $groupedMarks = array();

        foreach($registry->getAllStudentRegistry() as $unitId => $allStudents) {
            foreach ($allStudents as $currentStudent) {

                /* TODO: Probably put folders in a collection for iteration
                 * Oddly enough this method gets the students' marks for a
                 * criterion spanning across the entire course, which is
                 * nice and convenient
                 */
                $allMarks = $rubricHandler->getStudentMarksByCriteriaInCategory($currentStudent->getId(), $metadata->getSelectedFolder());

                foreach($allMarks as $criterionId => $currentMark) {
                    $groupedMarks[$criterionId][] = array(
                        'user' => $currentStudent->getId(),
                        'value' => $currentMark,
                    );
                }
            }
        }

        /* Recombine and preserve criterion grouping
         */
        $allRubrics = array();

        foreach ($allCriteria as $criteriaGroup => $currentCriterion) {
            foreach ($currentCriterion as $criterionId => $details) {
                $reforged = $details;
                $reforged['allValues'] = $groupedMarks[$reforged['id']];

                $allRubrics[$criteriaGroup][$criterionId] = $reforged;
            }

            /* Sort in order of spawn
             */
            asort($allRubrics[$criteriaGroup]);
        }

        /* Twig data
         */
        $this->getResponse()->content->set(
            array(
                'template' => '@learningAnalytics/course.twig',
                'data' => array(
                    'metadata' => array(
                        'pageTitle' => $metadata->getPageTitle(),
                        'allFolders' => $metadata->getAllFolders(),
                        'selectedFolder' => $metadata->getSelectedFolder(),
                        'route' => $metadata->getRoute(),
                    ),
                    'overallProgress' => array(
                        'mostAdvancedStudent' => $overallProgress->getMostAdvancedStudent(),
                        'classCompletions' => $overallProgress->getClassCompletions(),
                    ),
                    'results' => array(
                        'allTasks' => $taskList->getAllTasks(),
                        'allResults' => $taskResults->getAllResults(),
                        'topStudents' => $allAverages->findDescending('average'),
                        'bottomStudents' => $allAverages->findAscending('average'),
                    ),
                    'progress' => array(
                        'allUnits' => $stackedUnitProgress->getStackedUnitProgress(),
                    ),
                    'rubrics' => array(
                        'allRubrics' => $allRubrics,
                    )
                )
            )
        );
    }
}