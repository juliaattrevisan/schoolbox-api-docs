namespace Schoolbox\LearningAnalytics;

use Alaress\Web\Controller\Base;

use Schoolbox\Resource\Category as Folder;
use Schoolbox\Assessment\Course\UnitInstance;
use Schoolbox\Collection;
use Schoolbox\LearningAnalytics\Progress\Overall;
use Schoolbox\LearningAnalytics\Progress\Unit;
use Schoolbox\LearningAnalytics\Results\Results;
use Schoolbox\LearningAnalytics\Results\Averages;

class Controller extends Base {

    /**
     * Do everything
     *
     * $folder is the Folder for which the Units/Courses are relevant
     *
     * $unit is the currently selected unit for $folder. That is used for
     * all the boxplots, rankings etc.
     *
     * $allFolderts is all the folders in the course. That is used to
     * calculate overall progress etc. To make it relevant to only one
     * folder, fill it with only one folder instead of all the folders.
     * This is done in Module.
     *
     * @param Collection $allUnitInstances
     */
    public function course(Collection $allUnitInstances) {

        /* Get a list of all the students involved in each unit
         * and a list of units involved. This gets reused everywhere
         * so just hit the external db once
         */
        $registry = new Registry($allUnitInstances);
        $everyone = $registry->getAllStudentRegistry();

        /**
         * Overall Progress
         */
        $overallProgress = new Overall($registry);

        /**
         * Results for all the units in each $folder contained in $allFolders
         * (generated by Registry)
         */

        /* A unique list of all tasks
         */
        $allTasks = array();

        foreach ($registry->getAllUnitRegistry() as $currentUnit) {

            /* Task List Union
             * All the tasks in all the units
             *
             * Group by the originating task id, not the task instance id
             * This is so you can stack results from multiple classes
             */
            foreach ($currentUnit->getTasks() as $currentTask) {
                $allTasks[$currentTask->getTask()->getId()] = $currentTask;
            }
        }

        $allTasks = array_values($allTasks);

        /* Boxplot values
         */
        $allResults = array();

        foreach ($registry->getAllUnitRegistry() as $currentUnit) {
            $allStudents = $everyone[$currentUnit->getId()];

            /* Merge and stack results for each unit
             */
            $results = new Results($allStudents, $currentUnit);

            foreach ($results->getAllValues() as $unitId => $currentResultValue) {
                if ($allResults[$unitId] instanceof Collection) {
                    $allResults[$unitId]->merge($currentResultValue->getAll());
                }
                else {
                    $allResults[$unitId] = $currentResultValue->getAll();
                }
            }
        }

        /**
         * Grade Averages for student rankings
         */
        $allAverages = new Averages($allResults);

        /**
         * Individual Unit Progress for all the units in each $folder
         * contained in $allFolders (generated by Registry)
         */
        $allUnitProgress = array();

        foreach ($registry->getAllUnitRegistry() as $currentUnit) {
            $allStudents = $everyone[$currentUnit->getId()];

            $unitProgress = new Unit($allStudents, $currentUnit);

            $allUnitProgress[] = array(
                'unit' => $currentUnit,
                'mostAdvancedStudent' => $unitProgress->getMostAdvancedStudent(),
                'classCompletions' => $unitProgress->getClassCompletions()
            );
        }

        /* Combine them, averaging stacked results
         * Alternatively to display all the units in their original separated
         * states, just use $allUnitProgress instead of $stackedUnitProgress
         */
        $stackedUnitProgress = array();

        foreach ($allUnitProgress as $currentUnitProgress) {
            $key = $currentUnitProgress['unit']->getUnitCategory()->getId();

            /* Insert new values
             */
            if (!isset($stackedUnitProgress[$key])) {
                $stackedUnitProgress[$key] = $currentUnitProgress;
            }
            /* Average between this set of values and the existing ones for
             * class completion; use greatest value for most advanced student
             */
            else {
                /* Max most advanced student
                 */
                $existingMostAdvancedStudent = $stackedUnitProgress[$key]['mostAdvancedStudent'];
                $otherMostadvancedStudent = $currentUnitProgress['mostAdvancedStudent'];

                $stackedUnitProgress[$key]['mostAdvancedStudent'] = max($existingMostAdvancedStudent, $otherMostadvancedStudent);

                /* Class Completion average
                 */
                $existingClassCompletions = $stackedUnitProgress[$key]['classCompletions'];
                $otherClassCompletions = $currentUnitProgress['classCompletions'];

                $stackedUnitProgress[$key]['classCompletions'] = 0.5 * ($existingClassCompletions + $otherClassCompletions);
            }
        }

        /* Twig data
         */
        $this->getResponse()->content->set(
            array(
                'template' => '@learningAnalytics/course.twig',
                'data' => array(
                    'overallProgress' => array(
                        'mostAdvancedStudent' => $overallProgress->getMostAdvancedStudent(),
                        'classCompletions' => $overallProgress->getClassCompletions(),
                    ),
                    'results' => array(
                        'title' => 'All folders in a course',
                        'allTasks' => $allTasks,
                        'allValues' => $allResults,
                        'topStudents' => $allAverages->findDescending('average'),
                        'bottomStudents' => $allAverages->findAscending('average'),
                    ),
                    'progress' => array(
                        'allUnits' => $stackedUnitProgress,
                    ),
                )
            )
        );
    }

    /**
     * Same calculations as course(), just for a different set of units
     *
     * @param Collection $allUnitInstances
     */
    public function subject(Collection $allUnitInstances) {
        $this->course($allUnitInstances);
    }
}