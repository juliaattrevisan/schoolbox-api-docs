namespace Schoolbox\LearningAnalytics;

use Schoolbox\Resource\Folder\Model as Folder;
use Config;
use Schoolbox\UserMapper;
use Group;
use Schoolbox\Assessment\Course\UnitInstance;
use Schoolbox\Collection;

class StudentList {

    /**
     * Folder instance
     *
     * @var Folder
     */
    private $folder = null;

    /**
     * Unit instance
     *
     * @var UnitInstance
     */
    private $unit = null;

    /**
     * UserMapper
     *
     * @var UserMapper
     */
    private $userMapper = null;

    /**
     * A collection of User instances
     *
     * @var Collection
     */
    private $studentList = null;

    /**
     * A list of Schoolbox user ids who were previously
     * associated with $folder and $unit but are no longer
     * in it
     *
     * @var array
     */
    private $removedStudentIdList = array();

    /**
     * Constructor
     *
     * @param Folder $folder
     * @param UnitInstance $unit
     */
    public function __construct(Folder $folder, UnitInstance $unit) {
        $this->setFolder($folder);
        $this->setUnit($unit);
        $this->setUserMapper(new UserMapper());

        $this->process();
    }

    /**
     * Get list of students for this class, and group if it has one.
     */
    private function process() {
        $code = $this->getFolder()->getCodeString();

        /* A list of students as generated by external db connector
         */
        $student_list = array();

        /* A list of schoolbox user ids corresponding to everyone
         * in $student_list
         */
        $classStudentIdList   = array();

        /* A lsit of schoolbox accounts who have been added to this
         * folder. This may not be exactly the same as $student_list
         * due to students arriving and leaving
         */
        $groupStudentIdList   = array();

        /* A list of students who have participated in this folder but
         * have since been removed
         */
        $removedStudentIdList = array();

        /* From external db, get a list of students associated with
         * the current folder's code
         */
        if ($code && Config::get('external_enable')) {
            $class_handler = new \External_Class();
            $class_list    = $class_handler->getStudents($code);

            /* Get a list of externalIds
             */
            if (is_array($student_list) && is_array($class_list)) {
                $externalIdList = array_map(
                    function($student) {
                        return $student['synergy_id'];
                    },
                    $class_list
                );

                /* With those externalIds, get a list of Schoolbox
                 * user ids
                 */
                $classStudentIdList = $this->getUserMapper()->findIdsByColumn('synergy_id', $externalIdList);
            }
        }

        /* A list of students involved in this folder, as
         * known by schoolbox
         */
        $group_handler = new Group();
        $group_list    = $group_handler->getMemberList($this->getFolder()->getId());

        /* Uniquify results
         */
        if (is_array($group_list)) {
            $groupStudentIdList = array_unique(
                array_map(
                    function($student) {
                        return $student['uid'];
                    },
                    $group_list
                )
            );
        }

        /* Try loading all the students who have completed a task for this group, but
         * may no longer be in the class.
         */
        foreach ($this->getUnit()->getTasks() as $task) {
            foreach ($task->getCompletionList() as $completion) {
                $studentId = $completion->getStudent()->getId();

                if (!(in_array($studentId, $classStudentIdList) || in_array($studentId, $groupStudentIdList))) {
                    $removedStudentIdList[] = $completion->getStudent()->getId();
                }
            }
        }

        $this->setRemovedStudentIdList($removedStudentIdList);

        /* Finally get a list of all the schoolbox user accounts who
         * are currently, or have been previously, associated with
         * this folder and unit
         */
        $userCollection = $this->getUserMapper()->findByColumn(
            'id',
            array_merge($classStudentIdList, $groupStudentIdList, $this->getRemovedStudentIdList()),
            array('order' => array('lastname' => 'asc', 'firstname' => 'asc'))
        );

        $this->setStudentList($userCollection);
    }

    /* Getters/Setters
     */

    /**
     * Set folder
     *
     * @param Folder $folder
     */
    private function setFolder($folder)
    {
        $this->folder = $folder;
    }

    /**
     * Get folder
     *
     * @return Folder
     */
    private function getFolder()
    {
        return $this->folder;
    }

    /**
     * Set unit
     *
     * @param UnitInstance $unit
     */
    private function setUnit($unit)
    {
        $this->unit = $unit;
    }

    /**
     * Get unit
     *
     * @return UnitInstance
     */
    private function getUnit()
    {
        return $this->unit;
    }

    /**
     * Set user mapper
     *
     * @param UserMapper $userMapper
     */
    private function setUserMapper($userMapper)
    {
        $this->userMapper = $userMapper;
    }

    /**
     * Get user mapper
     *
     * @return UserMapper
     */
    private function getUserMapper()
    {
        return $this->userMapper;
    }

    /**
     * Set student list
     *
     * @param \Schoolbox\Collection $studentList
     */
    private function setStudentList($studentList)
    {
        $this->studentList = $studentList;
    }

    /**
     * Get student list
     *
     * @return \Schoolbox\Collection
     */
    public function getStudentList()
    {
        return $this->studentList;
    }

    /**
     * Set removed student id list
     *
     * @param array $removedStudentIdList
     */
    private function setRemovedStudentIdList($removedStudentIdList)
    {
        $this->removedStudentIdList = $removedStudentIdList;
    }

    /**
     * Get removed student id list
     *
     * @return array
     */
    public function getRemovedStudentIdList()
    {
        return $this->removedStudentIdList;
    }
}