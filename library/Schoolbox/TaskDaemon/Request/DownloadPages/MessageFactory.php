declare(strict_types=1);

namespace Schoolbox\TaskDaemon\Request\DownloadPages;

use Alaress_Date_Format;
use Schoolbox\API\Token\Jwt;
use Schoolbox\Instance;
use Schoolbox\TaskDaemon\Request\Message;
use Schoolbox\User;

/**
 * Factory for building download pages taskd requests.
 */
class MessageFactory
{
    /**
     * The identifier for this task.
     */
    private const TASK = 'download-pages';

    /**
     * Callback URL, if this task invocation has one.
     */
    private ?string $callbackUrl = null;

    /**
     * Callback params, if this task invocation has any.
     */
    private ?array $callbackParams = null;

    /**
     * The user invoking the task, if there is one.
     */
    private ?User $effector = null;

    /**
     * Content to download.
     *
     * @var array<array{filename: string, urls?: string[], source?: string}>
     */
    private array $content = [];

    /**
     * The footer to add to any PDFs generated by this task.
     */
    private ?string $pdfFooter = null;

    /**
     * Constructor
     *
     * @param Instance    $instance            Information about the Schoolbox instance.
     * @param Jwt         $tokenBuilder        Used to generate a JWT for use by taskd when:
     *                                         * calling the callback URL
     *                                         * initiating a session for Gotenberg when generating PDFs from Schoolbox
     * @param string|null $gotenbergUrl        The URL of the Gotenberg container.
     * @param string|null $gotenbergKey        The API key which the Gotenberg container requires, if any.
     * @param string|null $gotenbergHttpHeader The header in which `$gotenbergKey` will be passed.
     */
    public function __construct(
        private Instance $instance,
        private Jwt $tokenBuilder,
        private ?string $gotenbergUrl,
        private ?string $gotenbergKey,
        private ?string $gotenbergHttpHeader,
    ) {
    }

    /**
     * Set a callback URL for this call to taskd.
     *
     * This URL will be called when taskd completes.
     *
     * @param string|null $callbackUrl
     * @return self
     */
    public function withCallbackUrl(?string $callbackUrl): self
    {
        $clone = (clone $this);
        $clone->callbackUrl = $callbackUrl;
        return $clone;
    }

    /**
     * Set parameters to the callback URL for this call to taskd.
     *
     * These parameters will be added to the call to the callback URL when taskd
     * completes.
     *
     * In addition: taskd adds a download link to the uploaded generated ZIP
     * (relative to this Schoolbox instance) in the `href` parameter.
     *
     * @param array|null $callbackParams
     * @return self
     */
    public function withCallbackParams(?array $callbackParams): self
    {
        $clone = (clone $this);
        $clone->callbackParams = $callbackParams;
        return $clone;
    }

    /**
     * Set an effecting user for this call to taskd.
     *
     * This user will be used as the user for:
     * * any PDF content generated from Schoolbox URLs
     * * any file content downloaded from a Schoolbox instance
     * * the user which is authenticated for the callback URL
     *
     * @param User|null $effector
     * @return $this
     */
    public function withUser(?User $effector): self
    {
        $clone = (clone $this);
        $clone->effector = $effector;
        return $clone;
    }

    /**
     * Set footer content for all PDFs generated by taskd.
     *
     * @see https://gotenberg.dev/docs/6.x/html#header-and-footer
     *
     * @param string|null $footer
     * @return $this
     */
    public function withPdfFooter(?string $footer): self
    {
        $clone            = (clone $this);
        $clone->pdfFooter = $footer;
        return $clone;
    }

    /**
     * Add a set of HTML URL's response contents to the downloaded ZIP, after
     * converting them to PDFs and merging them together.
     *
     * @see https://gotenberg.dev/docs/6.x/url
     * @see https://gotenberg.dev/docs/6.x/merge
     *
     * @param string $filename The name of the file in the downloaded ZIP.
     * @param string ...$urls  These URLs will be visited HTML content will be
     *                         converted to PDF and then merged.
     * @return self
     */
    public function addPdfContent(string $filename, string ...$urls): self
    {
        $clone = (clone $this);
        $clone->content[] = ['filename' => $filename, 'urls' => $urls];
        return $clone;
    }

    /**
     * Add a URL's response content to the downloaded ZIP.
     *
     * @param string $filename The name of the file in the downloaded ZIP.
     * @param string $url      This URL's response body will be included
     *                         in `$filename` in the downloaded ZIP.
     * @return self
     */
    public function addFileContent(string $filename, string $url): self
    {
        $clone = (clone $this);
        $clone->content[] = ['filename' => $filename, 'source' => $url];
        return $clone;
    }

    /**
     * Clear all files from the downloaded ZIP.
     *
     * @return self
     */
    public function clearContent(): self
    {
        $clone = (clone $this);
        $clone->content = [];
        return $clone;
    }

    /**
     * Build the request to send to taskd.
     *
     * @param string $outfile
     * @return Message
     */
    public function build(string $outfile): Message
    {
        $params = [
            'outfile'   => $outfile,
            'content'   => $this->content,
            'gotenberg' => null,
        ];
        $token = $this->effector ? $this->tokenBuilder->generate($this->effector) : null;
        if (isset($token)) {
            $params['token'] = $token;
        }
        if (isset($this->gotenbergUrl)) {
            $params['gotenberg'] = [
                'url'  => $this->gotenbergUrl,
                'auth' => isset($this->gotenbergKey, $this->gotenbergHttpHeader)
                    ? ['key' => $this->gotenbergKey, 'header' => $this->gotenbergHttpHeader]
                    : null,
                'footer' => $this->pdfFooter,
            ];
        }
        return new Message(
            self::TASK,
            $params,
            Alaress_Date_Format::now()->getDateTimeObject(),
            $this->instance->getId(),
            $this->instance->getHostname(),
            $this->instance->getDomain(),
            $this->instance->getVersion(),
            $this->instance->getType(),
            $this->instance->getSchoolCode(),
            $this->callbackUrl,
            $this->callbackParams,
            $token,
        );
    }

    /**
     * How many content files have been added to this message factory?
     *
     * @return int
     */
    public function contentCount(): int
    {
        return count($this->content);
    }
}
