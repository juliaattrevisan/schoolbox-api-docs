declare(strict_types=1);

namespace Schoolbox\TaskDaemon\Request\DownloadPages;

use Schoolbox\API\Token\Jwt;
use Schoolbox\Instance;
use Schoolbox\TaskDaemon\Request\BaseMessageFactory;

/**
 * Factory for building download pages taskd requests.
 *
 * This class is designed to be immutable: all `set`/`add`/`clear` methods will
 * return a new instance of this object with only the relevant field changed.
 */
class MessageFactory extends BaseMessageFactory
{
    /**
     * The identifier for this task.
     */
    private const TASK = 'download-pages';

    /**
     * Content to download.
     *
     * @var array<array{filename: string, urls?: string[], source?: string}>
     */
    private array $content = [];

    /**
     * Name of the file to output to.
     */
    private string $outfile = 'output.zip';

    /**
     * The footer to add to any PDFs generated by this task.
     */
    private ?string $pdfFooter = null;

    /**
     * Constructor
     *
     * @param Instance    $instance                  Information about the Schoolbox instance.
     * @param Jwt         $tokenBuilder              Used to generate a JWT for use by taskd when:
     *                                               * calling the callback URL
     *                                               * initiating a session for Gotenberg when generating PDFs from
     *                                                 Schoolbox
     * @param string|null $gotenbergUrl              The URL of the Gotenberg container.
     * @param string|null $gotenbergApiKey           The API key which the Gotenberg container requires, if any.
     * @param string|null $gotenbergApiVersion       The API version which the Gotenberg container requires, if any.
     * @param string|null $gotenbergApiKeyHeader     The header in which `$gotenbergApiKey` will be passed.
     * @param string|null $gotenbergApiVersionHeader The header in which `$gotenbergApiVersion` will be passed.
     * @param string|null $kamiApiKey                The API key used to authenticate with Kami.
     * @param string|null $turnitinApiKey            The API key used to authenticate with Turnitin.
     * @param string|null $turnitinApiHost           The host name of this instance's Turnitin instance.
     */
    public function __construct(
        Instance $instance,
        Jwt $tokenBuilder,
        private ?string $gotenbergUrl,
        private ?string $gotenbergApiKey,
        private ?string $gotenbergApiVersion,
        private ?string $gotenbergApiKeyHeader,
        private ?string $gotenbergApiVersionHeader,
        private ?string $kamiApiKey,
        private ?string $turnitinApiKey,
        private ?string $turnitinApiHost,
    ) {
        parent::__construct($instance, $tokenBuilder);
    }

    /**
     * Set footer content for all PDFs generated by taskd.
     *
     * @see https://gotenberg.dev/docs/6.x/html#header-and-footer
     *
     * @param string|null $footer
     * @return self
     */
    public function setPdfFooter(?string $footer): self
    {
        $clone            = clone $this;
        $clone->pdfFooter = $footer;
        return $clone;
    }

    /**
     * Add a set of HTML URL's response contents to the downloaded ZIP, after
     * converting them to PDFs and merging them together.
     *
     * @see https://gotenberg.dev/docs/6.x/url
     * @see https://gotenberg.dev/docs/6.x/merge
     *
     * @param string $filename The name of the file in the downloaded ZIP.
     * @param string ...$urls  These URLs will be visited HTML content will be
     *                         converted to PDF and then merged.
     * @return self
     */
    public function addPdfContent(string $filename, string ...$urls): self
    {
        $clone = clone $this;
        $clone->content[] = ['filename' => $filename, 'urls' => $urls];
        return $clone;
    }

    /**
     * Add a URL's response content to the downloaded ZIP.
     *
     * @param string $filename The name of the file in the downloaded ZIP.
     * @param string $url      This URL's response body will be included
     *                         in `$filename` in the downloaded ZIP.
     * @return self
     */
    public function addFileContent(string $filename, string $url): self
    {
        $clone = clone $this;
        $clone->content[] = ['filename' => $filename, 'source' => $url];
        return $clone;
    }

    /**
     * Add a Kami document to the downloaded ZIP.
     *
     * @param string $filename       The name of the file in the downloaded ZIP.
     * @param string $kamiDocumentId The ID of the Kami document.
     * @return $this
     */
    public function addKamiContent(string $filename, string $kamiDocumentId): self
    {
        $clone = clone $this;
        $clone->content[] = ['filename' => $filename, 'kamiDocumentId' => $kamiDocumentId];
        return $clone;
    }

    /**
     * Add a Turnitin submission to the downloaded ZIP.
     *
     * @param string $filename             The name of the file in the downloaded ZIP.
     * @param string $turnitinSubmissionId The ID of the Turnitin submission.
     * @return $this
     */
    public function addTurnitinContent(string $filename, string $turnitinSubmissionId): self
    {
        $clone = clone $this;
        $clone->content[] = ['filename' => $filename, 'turnitinSubmissionId' => $turnitinSubmissionId];
        return $clone;
    }

    /**
     * Clear all files from the downloaded ZIP.
     *
     * @return self
     */
    public function clearContent(): self
    {
        $clone = clone $this;
        $clone->content = [];
        return $clone;
    }

    /**
     * Set the output filename.
     *
     * @param string $outfile
     * @return self
     */
    public function setOutfile(string $outfile): self
    {
        $clone = clone $this;
        $clone->outfile = $outfile;
        return $clone;
    }

    /**
     * @inheritdoc
     */
    protected function getTaskType(): string
    {
        return self::TASK;
    }

    /**
     * @inheritdoc
     */
    protected function buildParams(): array
    {
        $params = [
            'outfile'   => $this->outfile,
            'content'   => $this->content,
            'gotenberg' => null,
        ];
        if (isset($this->gotenbergUrl)) {
            $params['gotenberg'] = [
                'url'     => $this->gotenbergUrl,
                'version' => isset($this->gotenbergApiVersion, $this->gotenbergApiVersionHeader)
                    ? ['value' => $this->gotenbergApiVersion, 'header' => $this->gotenbergApiVersionHeader]
                    : null,
                'auth'    => isset($this->gotenbergApiKey, $this->gotenbergApiKeyHeader)
                    ? ['key' => $this->gotenbergApiKey, 'header' => $this->gotenbergApiKeyHeader]
                    : null,
                'footer'  => $this->pdfFooter,
            ];
        }
        if (isset($this->kamiApiKey)) {
            $params['kami']['apiKey'] = $this->kamiApiKey;
        }
        if (isset($this->turnitinApiKey, $this->turnitinApiHost)) {
            $params['turnitin'] = [
                'apiKey' => $this->turnitinApiKey,
                'host'   => $this->turnitinApiHost,
            ];
        }
        return $params;
    }
}
