namespace Schoolbox\Groups;

use Alaress\Module\Module as BaseModule;
use Alaress\Twig\Loader\IChainLoader;
use Alaress\Authorizer\Rule;
use Aura\Di\ContainerInterface;
use InvalidArgumentException;

/**
 * Class Module
 *
 * @package Schoolbox\Groups
 */
class Module extends BaseModule
{
    /**
     * @var string
     */
    protected $basename = 'groups';

    /**
     * @inheritDoc
     * @throws InvalidArgumentException
     */
    public function registerRoutes(): void
    {
        parent::registerRoutes(); // TODO: Change the autogenerated stub
        $loggedInAccess = new Rule\IsLoggedIn();
        $this->register('GET', '', 'newGroups', $loggedInAccess);
        $this->register('POST', '', 'postMyGroup', $loggedInAccess);
    }

    /**
     * {@inheritdoc}
     */
    public function initTemplatePaths(IChainLoader $templateLoader)
    {
        $this->addTemplatePath($templateLoader, __DIR__ . '/templates');
    }

    /**
     * @param ContainerInterface $injector
     */
    public function initControllers(ContainerInterface $injector)
    {
        $injector->set('controller:' . $this->basename, $injector->lazyNew(Controller::class));
    }
}
