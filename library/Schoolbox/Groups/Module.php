namespace Schoolbox\Groups;

use Alaress\Module\Module as BaseModule;
use Alaress\Twig\Loader\IChainLoader;
use Alaress\Authorizer\Rule;
use Aura\Di\ContainerInterface;
use InvalidArgumentException;
use Schoolbox\Permission\Access\UserAccessMapper;
use Schoolbox\Realtime\Message\RerouteOverrideMapper;
use Schoolbox\Resource\Folder\Mapper as FolderMapper;
use Schoolbox\Resource\GroupMapper;
use Schoolbox\Permission\Access\Access;

/**
 * Class Module
 *
 * @package Schoolbox\Groups
 */
class Module extends BaseModule
{
    /**
     * @var string
     */
    protected $basename = 'groups';

    /**
     * @inheritDoc
     * @throws InvalidArgumentException
     */
    public function registerRoutes(): void
    {
        parent::registerRoutes(); // TODO: Change the autogenerated stub
        $loggedInAccess = new Rule\IsLoggedIn();
        $this->register('GET', '', 'getNewGroups', $loggedInAccess);
        $this->register('POST', '/add', 'postMyGroupAdd', $loggedInAccess);
        $this->register('POST', '/delete', 'postMyGroupDelete', $loggedInAccess);
        $this->register('POST', '/notify', 'postMyGroupNotify', $loggedInAccess);
        $this->register('POST', '/favourite', 'postMyGroupFavourite', $loggedInAccess);
    }

    /**
     * {@inheritdoc}
     */
    public function initTemplatePaths(IChainLoader $templateLoader)
    {
        $this->addTemplatePath($templateLoader, __DIR__ . '/templates');
    }


    /**
     * @inheritdoc
     */
    public function buildController(): \Alaress\Web\Controller\Base
    {
        return new Controller();
    }

    /**
     * @param ContainerInterface $injector
     */
    public function initControllers(ContainerInterface $injector)
    {
        $injector->set(
            'controller:' . $this->basename,
            $injector->lazyNew(
                Controller::class,
                [
                    'groupMapper'               => $this->getMapperFactory()->getLazy(GroupMapper::class),
                    'userAccessMapper'          => $this->getMapperFactory()->getLazy(UserAccessMapper::class),
                    'folderMapper'              => $this->getMapperFactory()->getLazy(FolderMapper::class),
                    'accessHelper'              => $this->getMapperFactory()->getLazy(Access::class),
                    'timetable_ColourMapper'    => $this->getMapperFactory()->getLazy(\Timetable_ColourMapper::class),
                    'reRouteOverrideMapper'     => $this->getMapperFactory()->getLazy(RerouteOverrideMapper::class),
                ]
            )
        );
    }
}
