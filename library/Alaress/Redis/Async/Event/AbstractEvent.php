namespace Alaress\Redis\Async\Event;

abstract class AbstractEvent implements IEvent
{

    /** @var string  */
    protected $payload;

    /**
     * @param string $payload
     */
    public function __construct($payload)
    {
        $this->payload = $payload;
    }

    /**
     * @return string
     */
    public function getPayload()
    {
        return $this->payload;
    }
}
