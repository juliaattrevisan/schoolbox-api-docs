namespace Alaress\Async\Notification\Cloud\TassOrbit;

use Alaress\Async\Notification\Cloud\AbstractService;
use Alaress\Async\Notification\Instance\Instance;
use Alaress\Async\Notification\Notification;
use Schoolbox\External\Connector\DSNFactory;
use Schoolbox\External\Connector\TassApi\Base\Endpoint\Api;
use Schoolbox\External\Connector\TassApi\Base\Endpoint\Codec\DSN;
use Schoolbox\IConfigLoader;
use Schoolbox\MobileApp\Registry;
use Schoolbox\MobileApp\RegistryMapper;
use Schoolbox\User;
use SensitiveParameter;

class Service extends AbstractService
{
    private const PARENT_TASS_ORBIT_NOTIFICATION = 'setParentPushNotificaiton';
    private const PARENT_TASS_ORBIT_DATETIME_FORMAT = 'Y-m-d h:00:00';
    private const PARENT_TASS_ORBIT_TYPE = 'tassapi';
    private const PARENT_TASS_ORBIT_MAX_PAR_CODE_LENGTH = 8;
    private const PARENT_TASS_ORBIT_MAX_SFA_NUM_LENGTH = 5;
    private const PARENT_TASS_ORBIT_SPOUSE_DEFAULT_PREFIX = 'S';
    public const PARENT_TASS_ORBIT_STUDENT_EXTERNAL_ID = 'studentExternalId';

    public function __construct(
        RegistryMapper $registryMapper,
        private string $appIdentifier,
        #[SensitiveParameter] private string $config,
        private ?IConfigLoader $configLoader = null
    ) {
        parent::__construct($registryMapper, $appIdentifier);
    }

    /**
     * @inheritDoc
     */
    protected function propagate(array $tokens, $id, $title, $unreadCount = 0, ?Instance $instance = null, ?User $recipient = null): bool
    {

        try {
            if (!$recipient->getRole()->isParent()) {
                $this->getLog()->warning('User is not a parent.');
                return false;
            }

            if (!$recipient->getExternalId()) {
                $this->getLog()->warning('User does not have a valid external id.');
                return false;
            }

            $tassParentIdLength = trim($this->configLoader?->get('external_tass_parent_id_length'));
            if (!is_numeric($tassParentIdLength)) {
                $this->getLog()->warning('Tass Parent ID length must be a number.');
                return false;
            }

            /**
             * Parent/Spouse prefixes = P or S by default
             * Parent Code = Number of characters specified by external_tass_parent_id_length
             * Split Family Number = Appending characters up to 5 characters
             */
            $regex = '/(?:[P,%s])(?<parCode>[0-9]{%d})(?<sfaNum>[0-9]{0,%d})/';
            preg_match(
                sprintf(
                    $regex,
                    $this->getSpousePrefix(),
                    min($tassParentIdLength, self::PARENT_TASS_ORBIT_MAX_PAR_CODE_LENGTH),
                    self::PARENT_TASS_ORBIT_MAX_SFA_NUM_LENGTH,
                ),
                $recipient->getExternalId(),
                $matches
            );

            $parCode = $matches['parCode'] ?? null;
            $sfaNum  = $matches['sfaNum'] ?? '';

            //Parent Code should exist and be a non-falsey value
            //Parent code length should be a number
            if (!$parCode) {
                $this->getLog()->warning('Unable to derive Parent Code from the external id.');
                return false;
            }

            $key = json_decode($this->config, true);

            $dsn = (new DSNFactory())->produceDSNString(self::PARENT_TASS_ORBIT_TYPE, [
                self::PARENT_TASS_ORBIT_TYPE => [
                    'modules' => [
                        DSN::MODULE_PARENT_PUSH_NOTIFICATION => [
                            'companycode' => $key['companycode'],
                            'appcode' => $this->appIdentifier,
                            'token' => $key['token']
                        ]
                    ],
                    'options' => []
                ]
            ]);

            $api = (new Api(
                $key['host'],
                $dsn,
                DSN::MODULE_PARENT_PUSH_NOTIFICATION
            ));

            $timeNow = \Alaress_Date_Format::now();

            $notifRequest = [
                'push_message' => $title,
                'par_code' => $parCode,
                'sfa_num' => $sfaNum,
                'start_datetime' => $timeNow->getUsingFormat(self::PARENT_TASS_ORBIT_DATETIME_FORMAT),
                'end_datetime' => $timeNow->addWeeks(2)->getUsingFormat(self::PARENT_TASS_ORBIT_DATETIME_FORMAT),
                //Using the hash generated by with a combination of getBasehash and getParamHash
                'external_id' => sha1($instance->getBaseHash() . $instance->getParamHash()),
            ];

            $notification = new Notification([ $instance ]);

            $meta = $notification->getMeta();

            //Is the event related to their children?
            if (isset($meta[self::PARENT_TASS_ORBIT_STUDENT_EXTERNAL_ID])) {
                $notifRequest['stud_code'] = $meta[self::PARENT_TASS_ORBIT_STUDENT_EXTERNAL_ID];
            }

            if ($notification->getHref()) {
                $href = $notification->getHref();
                $parsedUrl = parse_url($href);
                //Building absolute url path for external use
                $detailMessage = (new \Schoolbox\Url\Factory($this->configLoader))
                    ->buildFullyQualified()
                    ->withPath($parsedUrl['path'] ?? '');

                //Separate the query parameter so it doesn't get encoded incorrectly
                if (isset($parsedUrl['query'])) {
                    $detailMessage = $detailMessage->withQuery($parsedUrl['query']);
                }

                //Encoding the fragment if exists
                if (isset($parsedUrl['fragment'])) {
                    $detailMessage = $detailMessage->withFragment($parsedUrl['fragment']);
                }

                $notifRequest['detail_message'] =
                    "<p>More Details: <a href='" . htmlspecialchars($detailMessage) . "'>" . htmlspecialchars($this->configLoader->get('title')) . "</a></p>";
            }

            $this->getLog()->info(json_encode($notifRequest));

            $response = $api->retrieveDocument(
                self::PARENT_TASS_ORBIT_NOTIFICATION,
                $notifRequest
            );

            $this->getLog()->info($response['message'] ?? 'No message received from response.');
            return true;
        } catch (\RuntimeException $e) {
            $this->getLog()->warning($e->getMessage());
            return false;
        } catch (\Exception $e) {
            $this->getLog()->error($e->getMessage());
            return false;
        }
    }

    /**
     * @inheritDoc
     */
    public function getProviderName(): string
    {
        return Registry::PROVIDER_TASS_ORBIT;
    }

    /**
     * A similar carbon copy of the getSpousePrefix() in External_Tass_Helper
     * @return string
     */
    private function getSpousePrefix(): string
    {
        $spousePrefix = trim((string)$this->configLoader?->get('external_tass_spouse_prefix'));

        return ('' !== $spousePrefix) ?
            $spousePrefix :
            self::PARENT_TASS_ORBIT_SPOUSE_DEFAULT_PREFIX;
    }
}
