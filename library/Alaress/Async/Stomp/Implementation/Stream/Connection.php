declare(strict_types=1);

namespace Alaress\Async\Stomp\Implementation\Stream;

use Alaress\Async\Stomp\ConnectionException;
use React\EventLoop\LoopInterface;
use React\Promise\Deferred;
use React\Promise\PromiseInterface;
use React\Stream\DuplexResourceStream as Stream;
use Stomp\Exception\StompException;
use Stomp\Protocol;
use Stomp\Transport\Frame as BaseFrame;
use Stomp\Transport\Parser;

/**
 * Streaming connection to a STOMP server.
 *
 * This provides a wrapper around the setup of a STOMP stream, and the protocol
 * used to parse messages from it.
 */
class Connection
{
    /**
     * @var LoopInterface
     */
    private $loop;


    /**
     * @var string
     */
    private $host;


    /**
     * @var int
     */
    private $port;


    /**
     * @var string|null
     */
    private $login;


    /**
     * @var string|null
     */
    private $passcode;


    /**
     * @var string|null
     */
    private $vhost;


    /**
     * @var Protocol\Protocol
     */
    private $protocol;


    /**
     * @var Parser
     */
    private $parser;


    /**
     * @var Stream
     */
    private $stream;


    /**
     * @var PromiseInterface|null
     */
    private $connectionPromise;


    /**
     * Constructor
     *
     * @param LoopInterface     $loop
     * @param Protocol\Protocol $protocol
     * @param Parser            $parser
     * @param string            $host
     * @param int               $port
     * @param string|null       $login
     * @param string|null       $passcode
     * @param string|null       $vhost
     */
    public function __construct(
        LoopInterface $loop,
        Protocol\Protocol $protocol,
        Parser $parser,
        string $host,
        int $port,
        ?string $login,
        ?string $passcode,
        ?string $vhost
    ) {
        $this->loop     = $loop;
        $this->protocol = $protocol;
        $this->parser   = $parser;
        $this->host     = $host;
        $this->port     = $port;
        $this->login    = $login;
        $this->passcode = $passcode;
        $this->vhost    = $vhost;
    }


    /**
     * Destructor: close the stream once this object is destroyed.
     */
    public function __destruct()
    {
        if ($this->stream instanceof Stream) {
            $this->stream->close();
        }
    }


    /**
     * Attempt to connect to the STOMP server.
     *
     * @return PromiseInterface Resolves (unused parameter) if the connection is
     *                          successful:
     *                          Rejects with `ConnectionException` if it is not.
     */
    public function connect(): PromiseInterface
    {
        // Have I tried to connect already? Give the same promise back
        if ($this->connectionPromise instanceof PromiseInterface) {
            return $this->connectionPromise;
        }

        // Make a promise
        $deferred                = new Deferred();
        $this->connectionPromise = $deferred->promise();

        // Setup the stream
        try {
            $this->setupStream();
        } catch (ConnectionException $e) {
            $deferred->reject($e);
        }

        // Now attempt to connect, waiting for a response.
        $connectFrame = $this->protocol->getConnectFrame($this->login, $this->passcode, [], $this->vhost);
        $this->stream->write($connectFrame);

        // If the connection is successful, $onConnect is called:
        // otherwise, $onError is called.
        // Either way, once I know the status remove both listeners.
        $onConnect = static function () use ($deferred): void {
            $deferred->resolve(true);
        };
        $onError   = static function (BaseFrame $frame) use ($deferred): void {
            $deferred->reject(new ConnectionException($frame->getBody() ?? ''));
        };
        $this->stream->once('connect', function () use ($onConnect, $onError): void {
            $this->stream->removeListener('error', $onError);
            $onConnect();
        });
        $this->stream->once('error', function (BaseFrame $frame) use ($onConnect, $onError): void {
            $this->stream->removeListener('connect', $onConnect);
            $onError($frame);
        });

        return $this->connectionPromise;
    }


    /**
     * Subscribe to a destination.
     *
     * @param string      $destination
     * @param string      $ackMode
     * @param string|null $subscriptionId ID for the subscription.
     *                                    Autogenerated if not provided.
     * @return string The subscription ID
     * @throws StompException if `$ackMode` isn't recognized
     *                        (@see https://stomp.github.io/stomp-specification-1.2.html#SUBSCRIBE_ack_Header)
     */
    public function subscribe(string $destination, string $ackMode, string $subscriptionId = null): string
    {
        $subId          = $subscriptionId ?? uniqid('', true);
        $subscribeFrame = $this->protocol->getSubscribeFrame($destination, $subId, $ackMode);
        $this->stream->write($subscribeFrame);
        return $subId;
    }


    /**
     * Log a callback to occur when a message with a particular subscription ID
     * is received.
     *
     * @param string   $subscriptionId
     * @param callable $callback
     */
    public function onMessage(string $subscriptionId, callable $callback): void
    {
        $this->stream->on('message', function (BaseFrame $frame) use ($subscriptionId, $callback): void {
            if ($frame['subscription'] === $subscriptionId) {
                $callback(
                    $frame,
                    new AckResolver($this->stream, $this->protocol, $frame)
                );
            }
        });
    }


    /**
     * Creates the stream connection to the STOMP server, and sets up a
     * connection to its data feed.
     */
    private function setupStream(): void
    {
        $socket = stream_socket_client(
            sprintf('tcp://%s:%d/', $this->host, $this->port),
            $errno,
            $errstr
        );
        if (!$socket) {
            throw new ConnectionException($errstr, $errno);
        }

        // Create the stream, subscribe to its data event
        $this->stream = new Stream($socket, $this->loop);
        $this->stream->on('data', function ($data): void {
            $this->parser->addData($data);
            while ($frame = $this->parser->nextFrame()) {
                if ($frame instanceof BaseFrame) {
                    // What kind of frame?
                    switch ($frame->getCommand()) {
                        case 'CONNECTED':
                            $this->stream->emit('connect', [$frame]);
                            break;
                        case 'ERROR':
                            $this->stream->emit('error', [$frame]);
                            break;
                        case 'MESSAGE':
                            $this->stream->emit('message', [$frame]);
                            break;
                    }
                }
            }
        });
    }
}
