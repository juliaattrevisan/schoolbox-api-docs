CREATE OR REPLACE VIEW SCHOOLBOX_EVENT AS
SELECT

	EDUMATE.EVENT.EVENT_ID AS ID,
	EDUMATE.EVENT.EVENT AS TITLE,
	EDUMATE.EVENT.DESCRIPTION AS "COMMENT",
	EDUMATE.STUDENT.STUDENT_NUMBER AS OWNER,
	EDUMATE.ROOM.ROOM AS ROOM,
	EDUMATE.EVENT_TYPE.EVENT_TYPE,
	EDUMATE.EVENT.START_DATE,
	EDUMATE.EVENT.END_DATE,
	EDUMATE.EVENT.LOCATION

	FROM

	EDUMATE.EVENT

	INNER JOIN EDUMATE.EVENT_STUDENT ON EDUMATE.EVENT.EVENT_ID = EDUMATE.EVENT_STUDENT.EVENT_ID
	INNER JOIN EDUMATE.STUDENT ON EDUMATE.EVENT_STUDENT.EVENT_STUDENT_ID = EDUMATE.STUDENT.STUDENT_ID
	INNER JOIN EDUMATE.EVENT_TYPE ON EDUMATE.EVENT.EVENT_TYPE_ID = EDUMATE.EVENT_TYPE.EVENT_TYPE_ID
	LEFT JOIN EDUMATE.EVENT_ROOM ON EDUMATE.EVENT_ROOM.EVENT_ID = EDUMATE.EVENT.EVENT_ID
	LEFT JOIN EDUMATE.ROOM ON EDUMATE.EVENT_ROOM.ROOM_ID = EDUMATE.ROOM.ROOM_ID
	WHERE EDUMATE.EVENT.PUBLISH_FLAG = 1

UNION

SELECT

	EDUMATE.EVENT.EVENT_ID AS ID,
	EDUMATE.EVENT.EVENT AS TITLE,
	EDUMATE.EVENT.DESCRIPTION AS "COMMENT",
	EDUMATE.STAFF.STAFF_NUMBER AS OWNER,
	EDUMATE.ROOM.ROOM AS ROOM,
	EDUMATE.EVENT_TYPE.EVENT_TYPE,
	EDUMATE.EVENT.START_DATE,
	EDUMATE.EVENT.END_DATE,
	EDUMATE.EVENT.LOCATION

	FROM

	EDUMATE.EVENT

	INNER JOIN EDUMATE.EVENT_STAFF ON EDUMATE.EVENT.EVENT_ID = EDUMATE.EVENT_STAFF.EVENT_ID
	INNER JOIN EDUMATE.STAFF ON EDUMATE.EVENT_STAFF.STAFF_ID = EDUMATE.STAFF.STAFF_ID
	INNER JOIN EDUMATE.EVENT_TYPE ON EDUMATE.EVENT.EVENT_TYPE_ID = EDUMATE.EVENT_TYPE.EVENT_TYPE_ID
	LEFT JOIN EDUMATE.EVENT_ROOM ON EDUMATE.EVENT_ROOM.EVENT_ID = EDUMATE.EVENT.EVENT_ID
	LEFT JOIN EDUMATE.ROOM ON EDUMATE.EVENT_ROOM.ROOM_ID = EDUMATE.ROOM.ROOM_ID
