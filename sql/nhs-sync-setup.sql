-- Copy timetable periods for other semesters too.
-- Yes, I really DO want that cross join. This selects all timetable period entries that are for cycle_id = 1,
-- and performs a cross join on all timetable campuses that aren't cycle_id = 1.
-- It adds an entry for all of them.
INSERT INTO `timetable_period` (`cycle_id`, `title`, `day`, `sequence`, `start`, `finish`, `usable`)
    SELECT `tc`.`cycle_id`, `tp`.`title`, `tp`.`day`, `tp`.`sequence`, `tp`.`start`, `tp`.`finish`, `tp`.`usable`
    FROM `timetable_period` `tp`
        CROSS JOIN `timetable_campus` `tc` ON `tc`.`cycle_id` != 1
    WHERE `tp`.`cycle_id` = 1
    ORDER BY `tc`.`cycle_id` ASC, `tp`.`id` ASC;
